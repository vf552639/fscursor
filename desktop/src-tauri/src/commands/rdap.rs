//! Tauri-команда чтения делегирования домена из РЕЕСТРА (RDAP).
//!
//! Отдельным файлом, а не строчкой в `commands::registrars`, потому что источник
//! здесь принципиально другой. Все команды соседнего модуля начинаются с
//! `reg_service`: мастер-ключ из keychain, открытие зашифрованного кэша,
//! расшифровка блоба с API-ключом. Здесь нет ничего из этого — RDAP публичен, а
//! имя домена секретом не является. Команда не просит ни `user_id`, ни
//! `account_id` не потому, что их забыли, а потому, что реестру всё равно, чей
//! это домен и есть ли у нас доступ к аккаунту регистратора; она отвечает и для
//! домена у провайдера без API вовсе (Dynadot), где `registrar_get_nameservers`
//! ответить не может ничем.
//!
//! Аудита тут нет — как и у остальных чтений (`registrar_get_domains`,
//! `registrar_test_connection`): в audit_log пишут действия, которые что-то
//! меняют.

use crate::rdap::{self, RegistryNameservers};

/// Куда домен делегирован по данным реестра.
///
/// Без `Result`: все три исхода — содержательные ответы (см.
/// `RegistryNameservers`), и неудача запроса среди них полноправна. Отдай мы её
/// как ошибку команды, фронт снова не смог бы отличить «не смогли спросить» от
/// «домена нет в реестре» — то, ради чего этот тип и заведён.
///
/// Клиент команда не собирает: `rdap::registry_nameservers` берёт общий на
/// процесс (TLS-конфиг и пул соединений — не то, что стоит переучреждать на
/// каждый домен списка; подробности у `rdap::shared`).
#[tauri::command]
pub async fn domain_registry_nameservers(domain: String) -> RegistryNameservers {
    rdap::registry_nameservers(&domain).await
}
