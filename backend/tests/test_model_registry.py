"""Реестр ORM-моделей полон у любого процесса, а не только у веба.

Предмет один и он невидим изнутри обычного теста: **метаданные `Base` должны
быть полными там, где нет роутов**. Веб-процесс импортирует роуты, а те попутно
тянут `auth`, `blobs` и `audit`; воркер роуты не грузит никогда, и его реестр
собирается из того, что случайно оказалось в цепочке
`app/tasks/__init__.py` → `server_monitor_task` → `app.models.server`.

Чем это кончилось на живом стеке: `BlobStorage` в реестр воркера не попадал, а
на `blob_storage.id` ссылаются шесть колонок в четырёх моделях. `ForeignKey`
разрешается лениво, на flush, когда unit of work сортирует таблицы по
зависимостям, — и каждая запись результата падала с `NoReferencedTableError`.
Мониторинг доступности не записал **ни одной** проверки за всё время
существования: выборка проходила, опрос проходил, запись падала на всех шести
серверах.

Тест уходит в **отдельный интерпретатор** намеренно, и без этого он был бы
бессмысленным: pytest грузит `conftest.py` и соседние модули, которые
импортируют `app.main`, — к моменту проверки реестр давно полон, и она зеленела
бы одинаково с фиксом и без него. Чистый процесс — единственный способ увидеть
ровно то, что видит воркер.

`configure_mappers()` для этой проверки не годится, хотя и напрашивается: он
конфигурирует отношения, а `relationship()` на `BlobStorage` ни у кого нет —
только сырые FK-колонки. На сломанном реестре он проходит без единой жалобы
(проверено). Ленивое разрешение FK форсирует обращение к `metadata.sorted_tables`
— тот самый путь, которым ходит flush, и та самая ошибка, что была в логах.
"""

import json
import subprocess
import sys
from pathlib import Path

BACKEND_ROOT = Path(__file__).resolve().parents[1]

# Сначала — импорт, доступный воркеру, и снимок реестра. Потом — импорт веба и
# второй снимок. Полнота проверяется двумя утверждениями сразу:
#
# * `sorted_tables` на первом снимке обязан разрешить все FK. Это ровно тот путь,
#   которым ходит flush, и ровно та ошибка, что ловилась в логах воркера;
# * набор таблиц не должен вырасти после импорта веба. Так проверка сама себя
#   поддерживает: любая модель, до которой можно дотянуться из роутов, но нельзя
#   из воркера, всплывёт разницей — без списка ожидаемых таблиц, который пришлось
#   бы править руками и о котором забыли бы первым делом.
_PROBE = """
import json, sys
import app.tasks                       # ровно то, с чего начинается воркер
from app.core.database import Base

worker_tables = sorted(Base.metadata.tables)
try:
    Base.metadata.sorted_tables        # форсирует разрешение всех ForeignKey
    resolved, error = True, ""
except Exception as exc:
    resolved, error = False, f"{type(exc).__name__}: {exc}"

import app.main                        # поверхность веба: роуты и всё за ними
web_tables = sorted(Base.metadata.tables)

json.dump(
    {"worker": worker_tables, "web": web_tables, "resolved": resolved, "error": error},
    sys.stdout,
)
"""


def test_the_worker_sees_every_model_the_web_does():
    """Воркеру реестр достаётся уже полным — без импорта роутов.

    Падение этого теста означает не «неудобно импортировать», а «фоновая задача
    не сможет ничего записать»: любая модель с FK на отсутствующую таблицу
    роняет flush целиком.
    """
    result = subprocess.run(
        [sys.executable, "-c", _PROBE],
        cwd=BACKEND_ROOT,
        capture_output=True,
        text=True,
        timeout=120,
    )
    assert result.returncode == 0, f"проба не отработала:\n{result.stderr[-2000:]}"
    report = json.loads(result.stdout)

    assert report["resolved"], (
        "в процессе без роутов не разрешаются внешние ключи — фоновые задачи не "
        f"смогут писать в БД: {report['error']}"
    )
    missing = sorted(set(report["web"]) - set(report["worker"]))
    assert not missing, (
        f"эти модели видит только веб, но не воркер: {missing}. "
        "Модель объявлена вне `app/models/` и не внесена в `app/models/__init__.py`"
    )
