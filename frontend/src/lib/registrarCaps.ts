/**
 * Что фронт вправе ждать от аккаунта регистратора — один модуль на весь фронт,
 * по образцу `lib/domainStatus.ts` и `lib/cfZoneMatch.ts`.
 *
 * Знание здесь не своё, а зеркало десктопа: и чтение доменов
 * (`registrar_get_domains`), и запись nameservers (`registrar_set_nameservers`)
 * идут через `make_service` (`desktop/src-tauri/src/registrars/mod.rs`), а он
 * знает ровно двух провайдеров и на любом третьем отвечает
 * `unknown provider: …` — ещё до всякой сети. Фронт, который этого списка не
 * знает, рисует живую кнопку с гарантированной ошибкой за ней.
 *
 * Отдельным модулем, а не проверкой по месту, потому что мест уже два (карточка
 * домена и мастер полной настройки), и разъехаться им есть где: список
 * провайдеров растёт в десктопе, а копия в UI остаётся прежней — и тогда
 * добавленный регистратор молча остаётся с выключенной кнопкой.
 */

/**
 * Провайдеры с NS-API — ровно те, которых различает `make_service`.
 *
 * Не экспортируется: наружу нужен ответ на вопрос, а не список, по которому
 * вызывающий напишет своё сравнение (и напишет его без `toLowerCase`).
 */
const NS_API_PROVIDERS: readonly string[] = ["hostiq", "namecheap"];

/**
 * Умеет ли этот провайдер менять NS через API.
 *
 * Регистр и пробелы схлопываются, потому что так делает и сам десктоп
 * (`provider.to_lowercase()` в `make_service`): значение приезжает строкой из
 * колонки `registrar_accounts.provider`, и «Namecheap» из чужого импорта
 * отличается от «namecheap» только здесь.
 *
 * Аргумент — `string`, а не `RegistrarProvider`: провайдер в модели объявлен как
 * `RegistrarProvider | string` (в базе лежит произвольная строка), и сужение
 * типа тут выдавало бы за невозможное ровно тот случай, ради которого функция и
 * заведена. Пустое значение — «не знаем провайдера», и это НЕ «умеет»:
 * незнание в сторону работоспособности не округляем.
 */
export function registrarSupportsNsApi(provider: string | null | undefined): boolean {
  return provider != null && NS_API_PROVIDERS.includes(provider.trim().toLowerCase());
}
