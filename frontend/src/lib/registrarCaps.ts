/**
 * Что фронт вправе ждать от аккаунта регистратора — один модуль на весь фронт,
 * по образцу `lib/domainStatus.ts` и `lib/cfZoneMatch.ts`.
 *
 * Знание здесь не своё, а зеркало десктопа: смена NS
 * (`registrar_set_nameservers`) идёт через `make_service`
 * (`desktop/src-tauri/src/registrars/mod.rs`), а он знает ровно двух провайдеров
 * и на любом третьем отвечает `unknown provider: …` — ещё до всякой сети. Фронт,
 * который этого списка не знает, рисует живую кнопку с гарантированной ошибкой
 * за ней.
 *
 * Речь ТОЛЬКО про запись. Чтения NS через API регистратора больше нет ни на
 * фронте, ни в десктопе: «как есть» спрашивают у реестра (`api/rdap.ts`), и ему
 * всё равно, знаком ли нам провайдер, — поэтому этим предикатом ничего не
 * решается про бейдж делегирования. Пока он гейтил и чтение, домен у ручного
 * провайдера получал серое «нет API» вместо ответа, которого у нас теперь не
 * может не быть.
 *
 * Отдельным модулем, а не проверкой по месту, потому что мест уже два (карточка
 * домена и мастер полной настройки), и разъехаться им есть где: список
 * провайдеров растёт в десктопе, а копия в UI остаётся прежней — и тогда
 * добавленный регистратор молча остаётся с выключенной кнопкой.
 */

/**
 * Провайдеры с NS-API — ровно те, которых различает `make_service`.
 *
 * Не экспортируется: наружу нужен ответ на вопрос, а не список, по которому
 * вызывающий напишет своё сравнение (и напишет его без `toLowerCase`).
 */
const NS_API_PROVIDERS: readonly string[] = ["hostiq", "namecheap"];

/**
 * Умеет ли этот провайдер менять NS через API — то есть можно ли ЗАПИСАТЬ.
 *
 * Схлопывается РОВНО регистр — ровно то, что схлопывает `make_service`
 * (`provider.to_lowercase()`), и ни символом больше. «Namecheap» из чужого
 * импорта десктоп понимает, а `" namecheap "` — нет: пробелы он не срезает, и
 * признай мы такую строку рабочей, кнопка «Set NS» осталась бы живой ради
 * гарантированного `unknown provider`. Зеркало обязано быть точным в обе
 * стороны, иначе оно не зеркало.
 *
 * Аргумент — `string`: в колонке `registrar_accounts.provider` лежит
 * произвольная строка (сам `RegistrarProvider` для того и ослаблен до `string` —
 * провайдера заводит пользователь), и сужение типа тут выдавало бы за
 * невозможное ровно тот случай, ради которого функция и заведена. Пустое
 * значение — «не знаем провайдера», и это НЕ «умеет»: незнание в сторону
 * работоспособности не округляем.
 *
 * Этим предикатом отвечает и каталог показа (`lib/registrarProviders.hasApi`):
 * бейдж «API» с кнопкой Test в Settings и тумблер «Прописать NS» на карточке
 * домена обязаны говорить про один аккаунт одно и то же.
 *
 * Про делегирование он не говорит ничего: домен у провайдера без API читается из
 * реестра наравне со всеми, и бейдж у него живой — выключена только кнопка.
 */
export function registrarSupportsNsApi(provider: string | null | undefined): boolean {
  return provider != null && NS_API_PROVIDERS.includes(provider.toLowerCase());
}

/**
 * Знаем ли мы провайдера аккаунта вообще — то есть прочитан ли сам аккаунт.
 *
 * Это ДРУГОЙ вопрос, чем `registrarSupportsNsApi`, и путать их нельзя: «список
 * аккаунтов ещё летит» лечится ожиданием, а «у провайдера нет NS-API» — походом
 * в панель регистратора. Обе фразы стоят подписями под одной и той же
 * выключенной кнопкой «Set NS at registrar» (`DomainNsPanel`) — единственного
 * места, где ответ на этот вопрос вообще на что-то влияет, — и назвать причину
 * они обязаны каждая свою: «не смогли выяснить» вместо «нет API» обвиняло бы
 * регистратора в том, чего мы про него не узнали.
 *
 * Функция остаётся отдельной, а не сливается с проверкой по месту, по той же
 * причине, по которой заведён весь модуль: правило про строку в колонке
 * `provider` должно быть одно на фронт. Бейдж делегирования им больше не судит —
 * реестр отвечает и про непрочитанный аккаунт (`lib/nsDelegation.ts`).
 *
 * Строка из пробелов считается ЗАПОЛНЕННОЙ намеренно: это мусор в колонке, а не
 * отсутствие ответа, и десктоп на неё отвечает `unknown provider` — то есть
 * правда про неё «нет NS-API», а не «не прочитано».
 */
export function registrarProviderKnown(provider: string | null | undefined): boolean {
  return provider != null && provider !== "";
}
