/**
 * Палитра макета — одним модулем на весь фронт.
 *
 * Заведён по той же причине, что `lib/serverStatus.ts` и `lib/domainStatus.ts`,
 * и с тем же уже случившимся ущербом: знание, размноженное копипастой, ВСЕГДА
 * расходится, а замечают это глазами и поздно. Карточка домена переехала на
 * новый визуальный язык, а список, из которого она открывается, остался в
 * старой палитре (`#e5e7eb`, `#2563eb`, `#6b7280`) — клик по строке переносил
 * человека будто в другой продукт. Три места уже держали свои копии этих хексов
 * (`ui/Primitives` → `SectionCard`, `domains/DomainSslCard`, вкладки карточки),
 * а редизайн вкладки Domains добавляет ещё шесть. Шесть новых копий — это шесть
 * будущих расхождений, и дешевле их не заводить, чем потом сводить.
 *
 * Что здесь есть и чего здесь НЕТ. Здесь — только значения показа: цвета,
 * рамки, поверхности, радиусы. Правил тут нет никаких: какой домен считается
 * активным, когда измерение протухло, в каком порядке идут статусы — всё это
 * живёт в `domainStatus.ts` и `serverStatus.ts` и переезжать сюда не должно.
 * Граница проходит ровно по вопросу «изменится ли ответ, если завтра поменяют
 * макет»: если да — значению место здесь, если нет — там.
 *
 * Имена — по роли, а не по цвету. `surface.page`, а не `slate100`: роль
 * переживает смену оттенка, а имя цвета при первой же правке макета начинает
 * врать (`gray` со значением `#eef2f7` — это не серый, но переименовывать
 * его будет уже поздно, он к тому моменту в двадцати местах).
 *
 * Списка потребителей здесь БОЛЬШЕ НЕТ, и это решение, а не пропажа. Список
 * был («`SectionCard` и компоненты редизайна вкладки Domains») и устарел за
 * одну ветку: к нему добавились `lib/domainExpiry`, `DomainExpiryField`,
 * `BulkActionToolbar`, `Btn` и `RowActions`, и никто из них себя не дописал.
 * Перечень импортёров общего модуля устаревает по построению — он растёт в
 * чужих файлах, а чинится в этом, — а комментарий, который врёт, обходится
 * дороже отсутствующего. Кто палитру берёт, отвечает поиск по `designTokens`;
 * здесь записано обратное и поиском не выводимое: кто её ещё НЕ берёт и
 * почему. `DomainSslCard` и вкладки карточки домена держат свои копии хексов —
 * переводить их отдельная работа, и делать её заодно значит смешать «переехал
 * на токены» с «поменял вид» в одном коммите.
 */

