/**
 * Палитра макета — одним модулем на весь фронт.
 *
 * Заведён по той же причине, что `lib/serverStatus.ts` и `lib/domainStatus.ts`,
 * и с тем же уже случившимся ущербом: знание, размноженное копипастой, ВСЕГДА
 * расходится, а замечают это глазами и поздно. Карточка домена переехала на
 * новый визуальный язык, а список, из которого она открывается, остался в
 * старой палитре (`#e5e7eb`, `#2563eb`, `#6b7280`) — клик по строке переносил
 * человека будто в другой продукт. Три места уже держали свои копии этих хексов
 * (`ui/Primitives` → `SectionCard`, `domains/DomainSslCard`, вкладки карточки),
 * а редизайн вкладки Domains добавляет ещё шесть. Шесть новых копий — это шесть
 * будущих расхождений, и дешевле их не заводить, чем потом сводить.
 *
 * Что здесь есть и чего здесь НЕТ. Здесь — только значения показа: цвета,
 * рамки, поверхности, радиусы. Правил тут нет никаких: какой домен считается
 * активным, когда измерение протухло, в каком порядке идут статусы — всё это
 * живёт в `domainStatus.ts` и `serverStatus.ts` и переезжать сюда не должно.
 * Граница проходит ровно по вопросу «изменится ли ответ, если завтра поменяют
 * макет»: если да — значению место здесь, если нет — там.
 *
 * Имена — по роли, а не по цвету. `surface.page`, а не `slate100`: роль
 * переживает смену оттенка, а имя цвета при первой же правке макета начинает
 * врать (`gray` со значением `#eef2f7` — это не серый, но переименовывать
 * его будет уже поздно, он к тому моменту в двадцати местах).
 *
 * Потребители на сегодня: `SectionCard` и компоненты редизайна вкладки Domains.
 * `DomainSslCard` и вкладки карточки домена свои копии пока держат — переводить
 * их отдельная работа, и делать её заодно значит смешать «переехал на токены»
 * с «поменял вид» в одном коммите.
 */

/**
 * Цвет текста — лестница по светлоте, от самого тёмного к самому бледному.
 *
 * Ступеней семь, и это не запас на будущее: макет правда различает заголовок
 * карточки (`ink`) и заголовок секции (`heading`), основной текст (`body`) и
 * вторичный (`secondary`), подпись (`muted`) и совсем тихую мету (`faint`).
 * Сливать соседние ступени нельзя — на них держится иерархия, ради которой
 * редизайн и затевался: «плотность без тесноты» получается тогда, когда глаз
 * ведут по светлоте, а не по пустому месту.
 */
const text = {
  /** Заголовки страницы и крупные числа — самый тёмный тон макета. */
  ink: "#0f172a",
  /** Заголовки карточек и секций. */
  heading: "#1e293b",
  /** Основной текст: значения полей, содержимое ячеек. */
  body: "#334155",
  /** Вторичный текст: подписи рядом со значением, текст на нейтральной пилюле. */
  secondary: "#475569",
  /** Подписи колонок, мета-строки, «Checked 4h ago». */
  muted: "#64748b",
  /** Совсем тихое: плейсхолдеры, разделители в мета-ряду. */
  faint: "#94a3b8",
  /**
   * Недоступное действие и прочерк «значения нет».
   *
   * Совпадает с `border.control` намеренно: выключенная кнопка в макете
   * сливается по тону со своей же рамкой — это и делает её «выключенной» на вид,
   * а не полупрозрачной.
   */
  disabled: "#cbd5e1",
} as const;

/**
 * Рамки — четыре толщины присутствия, не четыре оттенка серого.
 *
 * `card` заметно синее остальных (`#dbe3ee`): карточка обязана читаться как
 * отдельный предмет на странице, и нейтрально-серая рамка этого не давала.
 * `hairline` наоборот почти не видна — это разлиновка внутри таблицы, где
 * заметная линия превратила бы список в сетку.
 */
const border = {
  /** Внешняя рамка карточки и граница её шапки-полоски. */
  card: "#dbe3ee",
  /** Рамка поля ввода, селекта, кнопки — того, что можно нажать. */
  control: "#cbd5e1",
  /** Разделитель блоков внутри карточки, рамка шапки таблицы. */
  light: "#e2e8f0",
  /** Разлиновка строк списка: видна на просвет, не режет глаз. */
  hairline: "#f1f5f9",
} as const;

/**
 * Поверхности — от страницы вглубь карточки.
 *
 * Порядок здесь смысловой: `page` темнее, чем `card`, и именно поэтому карточка
 * выглядит лежащей НА странице, а не вырезанной в ней. Если однажды захочется
 * «осветлить фон страницы» — это сломает всю глубину, а не поправит оттенок.
 */
const surface = {
  /** Фон страницы — самая дальняя плоскость. */
  page: "#f1f5f9",
  /** Шапка-полоска карточки: темнее тела, светлее страницы. */
  cardHeader: "#eef2f7",
  /** Ховер строки, фон нейтральной плашки, «тихая» ячейка. */
  subtle: "#f8fafc",
  /** Тело карточки — почти белое, но не белое. */
  card: "#fbfcfe",
  /** Белый: модалка, поле ввода в фокусе, выпадающий список. */
  base: "#fff",
  /**
   * Строка списка, на которой стоит фокус или которая открыта в карточке.
   *
   * Холодный синий, а не более тёмный серый: серый читался бы как «строка
   * приглушена», то есть противоположность выделению.
   */
  rowFocus: "#eff4ff",
} as const;

/**
 * Семантические цвета — те, что что-то УТВЕРЖДАЮТ.
 *
 * Отделены от нейтральных намеренно: нейтральный тон можно поменять ради
 * красоты, а зелёный на этой странице значит «проверено и работает». Тронуть
 * его — значит поменять смысл, и разделение на две группы это напоминает.
 */
const semantic = {
  /** Успех, «дошли до конца»: активный домен, выпущенный сертификат. */
  successText: "#047857",
  successBg: "#ecfdf5",
  /** Ошибка: `failed`, недоступный сервер, отказ операции. */
  dangerText: "#b91c1c",
  dangerBg: "#fee2e2",
  dangerBorder: "#fecaca",
  /** «Ждём чужого действия»: делегирование NS, выпуск сертификата, срок истекает. */
  warningText: "#b45309",
  /**
   * Бейдж регистратора — единственное тёплое пятно на всей странице.
   *
   * Текст на нём НЕ оранжевый (`text.body`), и это не недосмотр: регистратор —
   * не состояние и ничего не утверждает, ему нужна узнаваемость метки, а не
   * тревожность предупреждения. Тёплые здесь только фон и рамка.
   */
  registrarBg: "#fff7ed",
  registrarBorder: "#fed7aa",
} as const;

/**
 * Радиусы. Шкала по размеру, а не по роли: одно и то же скругление в макете
 * достаётся и чипу, и ячейке, и роль ему не приписать честно.
 *
 * `sm` и `md` отличаются на пиксель, и это не опечатка макета: 8 — у кнопок и
 * полей, 9 — у пилюль статуса, которые стоят вплотную к ним в одном ряду.
 * Разница не читается по отдельности и работает только в этом соседстве.
 */
const radius = {
  /** 6 — мелкие чипы, иконочные кнопки. */
  xs: 6,
  /** 8 — кнопки, поля ввода, селекты. */
  sm: 8,
  /** 9 — пилюли статуса. */
  md: 9,
  /** 12 — карточки и модалки. */
  lg: 12,
  /** 99 — полная капля: фильтр-чипы, счётчики. */
  pill: 99,
} as const;

export const tokens = { text, border, surface, semantic, radius } as const;

/**
 * Вариант пилюли статуса. Строки те же, что отдаёт `domainStatusVariant`
 * (`lib/domainStatus`), и объявлены здесь заново лишь потому, что там тип не
 * экспортирован.
 *
 * ВАЖНО, где проходит граница: какой статус какого цвета — знание `domainStatus`
 * и остаётся там; здесь только то, КАК этот цвет выглядит. Перетащить сюда
 * лестницу — значит завести её вторую копию, ровно ту ошибку, от которой
 * `domainStatus` и лечили.
 */
export type StatusPillVariant = "gray" | "blue" | "green" | "yellow" | "red";

/** Тройка цветов пилюли: текст, заливка, рамка. */
export interface StatusPillColors {
  color: string;
  bg: string;
  border: string;
}

/**
 * Показ пилюли статуса в палитре макета.
 *
 * Рамка есть у всех пяти, включая серую: без неё пилюля на светлой заливке
 * теряет края и перестаёт читаться как пилюля — становится подкрашенным
 * текстом. У `gray` это особенно важно, потому что серый означает «статус нам
 * незнаком», и терять такую пилюшку глазами нельзя.
 *
 * Оговорка о происхождении значений, чтобы её не открывали заново: зелёный,
 * красный и янтарный взяты из макета напрямую, а заливки и рамки серого, синего
 * и жёлтого макет не задавал — они достроены по тому же семейству оттенков
 * (текст — тон 700, заливка — 50/100, рамка — 200), из которого собрана вся
 * остальная палитра. Если макет однажды назовёт их явно — менять здесь и только
 * здесь.
 */
export const STATUS_PILL: Record<StatusPillVariant, StatusPillColors> = {
  gray: { color: text.secondary, bg: surface.page, border: border.light },
  blue: { color: "#1d4ed8", bg: "#eff6ff", border: "#bfdbfe" },
  green: { color: semantic.successText, bg: semantic.successBg, border: "#a7f3d0" },
  yellow: { color: semantic.warningText, bg: "#fffbeb", border: "#fde68a" },
  red: { color: semantic.dangerText, bg: semantic.dangerBg, border: semantic.dangerBorder },
};
