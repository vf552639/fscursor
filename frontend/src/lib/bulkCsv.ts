/**
 * Разбор CSV массового добавления — отдельным модулем, а не обработчиком внутри
 * диалога.
 *
 * Причина та же, что у `lib/fullSetupPlan` и `lib/cfZoneMatch`: здесь не
 * разметка, а решения. Третья колонка превращается в `server_id`, по которому
 * provision заливает сайт на конкретную машину, — то есть ошибка разбора
 * материализуется чужим сайтом на чужом железе, и увидеть её глазами в диалоге
 * нельзя. Такое проверяется без DOM.
 *
 * Почему резолв «строка → сервер» вообще на фронте, хотя регистратор рядом
 * резолвится по имени на бэкенде (`find_reg_id`): только фронт держит ИСХОДНЫЙ
 * текст и может назвать номер строки, в которой опечатка, и не дать отправить
 * пачку. Бэкенд на его месте либо завёл бы домен без сервера молча, либо уронил
 * бы всю пачку, не сказав, какая строка виновата. Поэтому в
 * `DomainBulkCreateItem` нет и не будет поля `server_name`/`server_ip`.
 */

/** Что нужно от сервера для резолва — подмножество `Server` (`api/servers.ts`). */
export interface ResolvableServer {
  id: number;
  name: string;
  ip_address: string;
}

export interface BulkCsvOptions {
  /** Все серверы пользователя: только среди них ищется третья колонка. */
  servers: ReadonlyArray<ResolvableServer>;
  /** Сервер из селекта диалога — для строк без третьей колонки. */
  defaultServerId?: number | null;
  /**
   * Регистратор из селекта диалога — для строк без второй колонки.
   *
   * Пара к `defaultServerId`, а не украшение: оба селекта видны на вкладке CSV,
   * и селект, который ни на что не влияет, — это молча потерянный выбор
   * пользователя. Ставится ТОЛЬКО там, где своего имени в строке нет:
   * `find_reg_id` на бэкенде смотрит `registrar_id` раньше `registrar_name`, и
   * проставленный поверх имени id перебил бы то, что человек написал в строке.
   */
  defaultRegistrarId?: number | null;
}

/**
 * Почему строка не принята. Поводы различаются намеренно: «не найден» чинят
 * опечаткой, «подходит нескольким» — тем, что пишут IP вместо имени (или
 * наоборот), а дубль — удалением строки. Одно слово на все случаи солгало бы в
 * двух показах из трёх.
 */
export type BulkCsvErrorReason = "not-found" | "ambiguous" | "duplicate";

/** Общее у всех непринятых строк: где она и что в ней написано. */
interface BulkCsvErrorBase {
  /**
   * Номер строки в textarea, считая с единицы и ВКЛЮЧАЯ пустые.
   *
   * Пустые строки между данными — обычная копипаста, и номер, посчитанный после
   * их отбрасывания, отправил бы человека искать опечатку не туда. Это
   * единственный способ найти одну строку среди сотни вставленных.
   */
  line: number;
  /**
   * Значение словами пользователя — по нему он и ищет строку глазами. Что
   * именно в нём лежит, зависит от `reason`: у серверных причин — третья
   * колонка, у дубля — имя домена (см. `REASON_TEXT`).
   */
  value: string;
}

/**
 * Непринятая строка. Union, а не одна структура с необязательными полями (тот же
 * приём, что у `ZoneMatch` в `lib/cfZoneMatch`): `firstLine` есть ТОЛЬКО у
 * дубля, и напечатать в сообщении `undefined` поэтому нечем.
 */
export type BulkCsvError =
  | (BulkCsvErrorBase & { reason: "not-found" })
  | (BulkCsvErrorBase & { reason: "ambiguous" })
  | (BulkCsvErrorBase & {
      reason: "duplicate";
      /**
       * Номер строки, где этот домен встретился ВПЕРВЫЕ.
       *
       * Не украшение и не «уже есть выше»: ключ сравнения нормализован, поэтому
       * первая строка может выглядеть иначе, чем вторая (`Example.COM.` против
       * `example.com`), и человек не узнал бы в чужом написании собственную
       * строку. Довод тот же, что и у `line`: в сотне строк ищут по номеру.
       */
      firstLine: number;
    });

/**
 * Формулировка живёт рядом с причиной, которую объясняет, а не тернарником в
 * разметке: карта по закрытому union компилятор обязан покрыть целиком, и
 * четвёртая причина не сможет молча напечататься уверенным «не найден».
 *
 * Функции, а не строки, потому что у причин разное и подлежащее, и данные: у
 * двух первых в `value` лежит сервер, у дубля — домен плюс номер первой строки.
 */
const REASON_TEXT: {
  [R in BulkCsvErrorReason]: (error: Extract<BulkCsvError, { reason: R }>) => string;
} = {
  "not-found": (e) => `сервер «${e.value}» не найден`,
  ambiguous: (e) => `сервер «${e.value}» подходит нескольким — уточните имя или IP`,
  duplicate: (e) => `домен «${e.value}» — дубль строки ${e.firstLine}`,
};

/** Одна строка отчёта — без номера строки: его подставляет тот, кто рисует. */
export function bulkCsvErrorText(error: BulkCsvError): string {
  // Единственное место, где связь «причина → её данные» держится не типом:
  // индексация union'ом сужение теряет, а разбирать его вторым switch значило бы
  // завести ту же таблицу дважды.
  const render = REASON_TEXT[error.reason] as (e: BulkCsvError) => string;
  return render(error);
}

export interface BulkCsvParse {
  items: DomainBulkCreateItem[];
  /**
   * Непринятые строки — не больше одной записи на строку. Непустой список —
   * запрет на отправку: отправив пачку, продукт завёл бы часть доменов без
   * сервера (или уронил бы вставку целиком, см. `duplicate`), а вернуться к
   * исходному тексту уже было бы неоткуда.
   *
   * Длина списка не ограничена намеренно: обрезав его, продукт заставил бы
   * чинить сотню строк за столько же попыток «отправить и посмотреть, что ещё
   * не так». Показать столько, сколько влезает, — решение того, кто рисует.
   */
  errors: BulkCsvError[];
  /**
   * Хотя бы одна непустая строка похожа на CSV с запятыми вместо `;` — и этого
   * достаточно, чтобы отменить разбор всего текста (поведение старого парсера
   * сохранено). Одна кривая строка из ста глушит и серверные диагнозы: вставка
   * пришла из одного источника, и разделитель в ней либо тот, либо не тот.
   *
   * Не строчная ошибка, а диагноз всему вводу, поэтому отдельным полем, а не
   * элементом `errors`: разобранный по `;` текст с запятыми даёт домены вида
   * «example.com,Namecheap,45.83.194.107» и ни одной осмысленной ошибки про
   * сервер — то есть шум вместо единственной внятной новости «поменяйте
   * разделитель». Поле, а не отдельная экспортируемая проверка, ровно потому,
   * что вызвать её было бы можно забыть.
   */
  commaSeparated: boolean;
}

/**
 * Найти сервер по значению третьей колонки: по `ip_address` ИЛИ по `name`.
 *
 * «Или/или» — то же правило, что у `find_reg_id` для регистратора: человек
 * пишет то, чем помнит машину. IP сверяется как есть (после `trim`), имя — без
 * учёта регистра, потому что имена набирают руками, а IP копируют.
 *
 * Совпадение у двух РАЗНЫХ серверов — отказ, а не первый попавшийся. Ровно то
 * же решение, что в `lib/cfZoneMatch`, и по той же причине: угадав, продукт
 * записал бы домену чужой `server_id`, а provision залил бы сайт на машину, о
 * которой пользователь не просил. Один сервер, совпавший обоими способами
 * сразу (машина, названная собственным IP), неоднозначностью не является —
 * выбирать не из чего.
 */
function resolveServer(
  raw: string,
  servers: ReadonlyArray<ResolvableServer>,
): { outcome: "matched"; id: number } | { outcome: "not-found" | "ambiguous" } {
  const key = raw.toLowerCase();
  const hits = servers.filter(
    (s) => s.ip_address.trim() === raw || s.name.trim().toLowerCase() === key,
  );
  if (hits.length === 0) return { outcome: "not-found" };
  if (hits.length > 1) return { outcome: "ambiguous" };
  return { outcome: "matched", id: hits[0].id };
}

/**
 * Строки CSV → элементы `/domains/bulk-structured` плюс список непринятых
 * строк.
 *
 * Про домены модуль отвечает ровно на один вопрос из двух, и граница здесь не
 * случайная. ВАЛИДНОСТЬ имени — не наше дело: её проверяет бэкенд
 * (`is_valid_domain`) и называет непринятые в `skipped`, а диалог уже
 * показывает этот ответ; вторая проверка была бы вторым мнением о том же
 * вопросе и разошлась бы с первым молча. А вот ДУБЛЬ ВНУТРИ ОДНОЙ ВСТАВКИ —
 * наше: `bulk_create_structured` (маршрут этого диалога, в отличие от
 * текстового `bulk_create`) внутри пачки не дедуплицирует, а `domain_name`
 * уникален глобально, и два одинаковых имени доезжают до `commit` и дают 500 —
 * без единого номера строки и без единого созданного домена. Молча схлопнуть
 * их тоже нельзя: у одного и того же домена в двух строках могут стоять РАЗНЫЕ
 * серверы, и выбор между ними — то же угадывание, что и с неоднозначным IP.
 * Ключ сравнения — `normalizeZoneName`, потому что бэкенд нормализует имя тем
 * же правилом (`normalize_domain`: trim + lower + срез точки), и своё правило
 * здесь означало бы «`Example.COM` и `example.com` — разные домены» на фронте и
 * «один и тот же» в базе.
 *
 * Строка без первой колонки выпадает молча и без ошибки: привязывать сервер
 * не к чему, а жалоба на её третью колонку была бы жалобой на строку, которой
 * в отправке всё равно нет.
 *
 * Колонки с четвёртой и дальше отбрасываются молча: лишний `;` в конце строки —
 * обычная копипаста из таблицы, и ругаться на неё значило бы блокировать
 * вставку из-за того, что мы и так не читаем. Ошибка у строки одна, даже если
 * поводов два: у дубля свой сервер уже не спрашивают — строки в отправке нет.
 */
export function parseBulkCsv(text: string, options: BulkCsvOptions): BulkCsvParse {
  const { servers, defaultServerId = null, defaultRegistrarId = null } = options;

  // Индекс строки в исходном тексте — единственный источник номера в ошибке,
  // поэтому нумеруем ДО любой фильтрации.
  const lines = text.split("\n").map((line, i) => ({ n: i + 1, text: line.trim() }));
  const filled = lines.filter((l) => l.text);

  if (filled.some((l) => l.text.includes(",") && !l.text.includes(";"))) {
    return { items: [], errors: [], commaSeparated: true };
  }

  const items: DomainBulkCreateItem[] = [];
  const errors: BulkCsvError[] = [];
  // Значение — номер ПЕРВОЙ строки с этим именем: он уезжает в сообщение про
  // дубль (см. `firstLine`).
  const seen = new Map<string, number>();

  for (const line of filled) {
    const parts = line.text.split(";");
    const domainName = parts[0].trim();
    // Гард пустого домена стоит ДО проверки дубля намеренно, и переставить их
    // местами нельзя: пустые имена нормализуются в один и тот же ключ, и вторая
    // строка вида `;Reg;web-01` стала бы «дублём» первой — вставка блокировалась
    // бы жалобой на домен, которого в ней нет.
    if (!domainName) continue;

    const key = normalizeZoneName(domainName);
    const firstLine = seen.get(key);
    if (firstLine !== undefined) {
      // Второе вхождение не попадает в `items` вовсе: отправку держат `errors`,
      // но нести в payload строку, о которой уже известно, что она уронит
      // вставку в 500, нельзя ни при каком повороте событий.
      errors.push({ line: line.n, value: domainName, reason: "duplicate", firstLine });
      continue;
    }
    seen.set(key, line.n);

    const registrarName = (parts[1] ?? "").trim();
    const serverRaw = (parts[2] ?? "").trim();

    let serverId: number | null = defaultServerId;
    if (serverRaw) {
      const hit = resolveServer(serverRaw, servers);
      if (hit.outcome === "matched") {
        serverId = hit.id;
      } else {
        errors.push({ line: line.n, value: serverRaw, reason: hit.outcome });
        // Именно `null`, а не сервер из селекта: подставить дефолт вместо
        // непонятого значения — это и есть то самое угадывание. Отправку
        // всё равно держат `errors`, но элемент не должен нести догадку на
        // случай, если однажды их прочитает кто-то другой.
        serverId = null;
      }
    }

    items.push({
      domain_name: domainName,
      registrar_name: registrarName || null,
      registrar_id: registrarName ? null : defaultRegistrarId,
      server_id: serverId,
    });
  }

  return { items, errors, commaSeparated: false };
}
