/**
 * Короткое имя ОС сервера: приведение любой строки (ручной выбор в форме или
 * автоопределение по SSH) к каноничному имени семейства, без версии и
 * архитектуры. `serverOsName` — единственное место, где решается приоритет
 * между ручным выбором и автоопределением; вызывающий код им и пользуется, а
 * не собирает выражение на месте.
 */

/**
 * Только имя семейства ОС, без версии и архитектуры: десктоп по этому имени
 * выбирает пакетный менеджер для установки FastPanel (`apt` или `yum`),
 * версия ему не нужна.
 *
 * Новое имя из RHEL-семейства обязано попадать под подстроки
 * `cent|rhel|rocky|alma|fedora` из
 * `desktop/src-tauri/src/provision/fastpanel_install.rs::update_command` —
 * иначе оно молча получит apt (там `else`, а не whitelist). Debian-подобные
 * (Debian, Ubuntu) под эти подстроки не попадают нарочно — apt для них и
 * есть правильный ответ.
 */
export const OS_OPTIONS = ["Debian", "Ubuntu", "CentOS", "AlmaLinux", "Rocky Linux"] as const;

/**
 * Подстрока → каноничное имя. Список ШИРЕ, чем `OS_OPTIONS`: та константа —
 * это то, что можно ВЫБРАТЬ в форме «Add Server», а сюда приходит вдобавок
 * то, что десктоп сам вычитал из `/etc/os-release` (`os_pretty`) — и там
 * встречается Red Hat и Fedora, которых в форме нет и не будет (RHEL требует
 * платной подписки для доступа к репозиториям, ставить на неё FastPanel
 * незачем; Fedora — не серверный дистрибутив). Опознать их всё равно нужно,
 * иначе вместо имени в бейдже — обрубок вида «Red».
 *
 * Иголки для CentOS и AlmaLinux — не полное имя ("centos", "almalinux"), а
 * подстрока покороче ("cent", "alma"), парно с Rust `update_command`: там
 * матчер тоже смотрит на "cent"/"alma", и написание вроде "Cent OS 7" (с
 * пробелом — так генерируют некоторые сборки) обязано опознаваться одинаково
 * по обе стороны SSH-границы, а не только в Rust.
 *
 * Поиск подстроки для "Rocky Linux" — короче, "rocky", а не нижний регистр
 * имени целиком ("rocky linux"), потому что PRETTY_NAME по разным сборкам
 * пишет то "Rocky Linux release 9.3", то "Rocky Linux 9.3 (Blue Onyx)".
 *
 * Порядок значим: производные дистрибутивы (Rocky, AlmaLinux, CentOS) стоят
 * ПЕРЕД "rhel"/"red hat" нарочно. Строка вроде "Rocky Linux 9.3 (RHEL 9
 * compatible)" содержит обе подстроки одновременно, а бейдж на карточке
 * обязан назвать дистрибутив, который реально стоит, а не апстрим, с которым
 * он совместим. Переставь массив в алфавитном порядке — и это молча сломается
 * без единого красного теста, кроме того самого на совместимость ниже.
 */
const FAMILY_NEEDLES: ReadonlyArray<readonly [string, string]> = [
  ["ubuntu", "Ubuntu"],
  ["debian", "Debian"],
  ["cent", "CentOS"],
  ["alma", "AlmaLinux"],
  ["rocky", "Rocky Linux"],
  ["red hat", "Red Hat"],
  ["rhel", "Red Hat"],
  ["fedora", "Fedora"],
];

/**
 * Приводит произвольную строку ОС (ручной выбор из формы или
 * автоопределённый `PRETTY_NAME` вида «Ubuntu 20.04.6 LTS») к короткому
 * имени семейства. Тип результата — `string`, а не литеральный union из
 * `OS_OPTIONS`: помимо пяти пунктов формы сюда прилетают и другие семейства
 * из живого `/etc/os-release` (см. `FAMILY_NEEDLES`) и произвольный fallback.
 *
 * Принимает `null`/`undefined` напрямую — вызывающий код читает поля вида
 * `s.os_pretty`, которые в API всегда `string | null`, но в паре мест по пути
 * успевают стать `undefined` (например, до первой загрузки сервера), и
 * заставлять каждый вызов приводить тип было бы лишним трением.
 */
export function osShortName(label: string | null | undefined): string | null {
  // `.trim()` на `null`/`undefined` бросает исключение — этот guard нужен
  // именно ради типа, а не ради пустой строки: строку из пробелов ниже
  // приводит к `null` тот же путь, что и "39" (см. комментарий у `return`),
  // отдельная ранняя проверка на пустоту после обрезки была бы мёртвым кодом.
  if (!label) return null;
  const trimmed = label.trim();

  const lower = trimmed.toLowerCase();
  for (const [needle, canonical] of FAMILY_NEEDLES) {
    if (lower.includes(needle)) return canonical;
  }

  // Ни одно известное семейство не подошло — это ОС, для которой у нас нет
  // отдельного пункта (Slackware, openSUSE...). Версия почти всегда начинается
  // с цифры сразу после имени («openSUSE 15.5») — обрезаем по ней и берём
  // первое слово, а не всю голову целиком: иначе «Fedora Linux» остался бы с
  // лишним «Linux», которого нет у канонических имён.
  const beforeVersion = trimmed.split(/\d/, 1)[0].trim();
  const firstWord = beforeVersion.split(/\s+/)[0];
  // Хвостовой мусор вроде "[0m" — не часть имени: `parseServerMetrics`
  // намеренно вычищает из `os_pretty` только сам управляющий байт (ESC), а
  // видимый остаток экранированной последовательности оставляет как есть
  // (см. `serverMetrics.test.ts`), и он может уехать в это первое слово.
  const cleaned = firstWord.replace(/[^\p{L}]+$/u, "");
  // Пустая строка сюда попадает в трёх случаях: строка была из одних пробелов,
  // цифра стояла в самом начале ("39"), или после обрезки хвостового мусора
  // не осталось ни одной буквы. Возвращаем null, а не "", потому что пустая
  // строка в JSX рисуется как пустое место, а вызывающий код проверяет именно
  // null, чтобы показать «—».
  return cleaned || null;
}

/** Поля сервера, из которых складывается отображаемое имя ОС. */
export interface ServerOsInput {
  os?: string | null;
  os_pretty?: string | null;
}

/**
 * Отображаемое короткое имя ОС сервера — с приоритетом ручного выбора над
 * автоопределением.
 *
 * У сервера два источника этого поля с разной природой: `os` — то, что
 * пользователь выбрал руками в «Add Server», `os_pretty` — то, что десктоп
 * сам вычитал из `/etc/os-release` по SSH. Ручной выбор перекрывает
 * автоопределение, а не наоборот: это решение пользователя, автоопределение —
 * только догадка десктопа (может не совпасть с тем, что сервер отдал по
 * факту, или вовсе не собраться, если SSH недоступен).
 *
 * Единственное место, где считается это правило: все, кто его показывает —
 * список серверов (`pages/Servers.tsx`), страница деталей и префилл модалки
 * правки OS (`pages/ServerDetail.tsx`), — берут отсюда готовое значение, а не
 * собирают то же выражение каждый на свой лад.
 *
 * Автоопределённое значение при этом не исчезает с глаз совсем: модалка правки
 * ОС показывает `osShortName(os_pretty)` отдельной подсказкой, когда оно
 * расходится с выбранным, — расхождение означает, что установка FastPanel
 * пойдёт не тем пакетным менеджером.
 */
export function serverOsName(s: ServerOsInput): string | null {
  return osShortName(s.os) || osShortName(s.os_pretty);
}
