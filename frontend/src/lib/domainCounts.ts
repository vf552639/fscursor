import { DomainStatusName } from "./domainStatus";

/**
 * Правила подсчёта срезов вкладки Domains — отдельно от того, кто их рисует.
 *
 * Жили внутри компонента (`DomainStats`, потом `DomainStatChips`), и там же
 * жили два объяснения ниже — самое дорогое, что в этом коде есть. Довод «держать
 * подсчёт рядом с показом, чтобы не разводить объяснение и то, что оно
 * объясняет» бил по варианту «числа приходят пропсами», но не по этому:
 * комментарии уехали ВМЕСТЕ с правилом, а не остались у разметки. Разница в
 * цене проверки: правило внутри компонента проверяется рендером всей страницы —
 * поднять QueryClient, замокать четыре эндпоинта, кликнуть «NS details», —
 * а чистая функция проверяется списком из пяти объектов.
 *
 * Про показ здесь нет ничего: ни цветов, ни подписей, ни порядка чипов. Граница
 * та же, что у `designTokens` с обратным знаком — там только вид, здесь только
 * счёт.
 */

/**
 * Статусы, у которых на вкладке есть собственный чип.
 *
 * Имена выведены из лестницы (`DomainStatusName`), а не написаны строками:
 * опечатка или переименование статуса на бэкенде роняет теперь сборку, а не
 * даёт молча нулевой счётчик. Их ровно три из восьми, и остальные пять — не
 * забытые, а сложенные в `inProgress` (см. ниже).
 */
export type LifecycleStatus = Extract<DomainStatusName, "new" | "active" | "failed">;

export interface DomainCounts {
  /** Весь список — число на чипе «All». */
  total: number;
  /** Три статуса, у которых есть свой чип. */
  byStatus: Record<LifecycleStatus, number>;
  /** Всё остальное: домены между «заведён» и «работает». */
  inProgress: number;
  ns: { ok: number; pending: number; error: number };
  /** Домены, у которых провижининг дошёл до SSL и сертификата не получил. */
  failedAtSsl: number;
}

/**
 * Что этому правилу нужно знать о домене — три поля, и ни одного больше.
 *
 * Структурная подпись, а не импорт `DomainUI` из `components/domains/types`:
 * `lib/` не должен зависеть от компонентов (тот же приём и та же причина, что
 * у `cfZoneMatch`), а вызывающему не приходится собирать промежуточных
 * объектов — строка вкладки подходит как есть.
 */
export interface CountableDomain {
  status: string;
  ns_status: string;
  ssl_status?: string | null;
}

/**
 * Срезы списка доменов — за один проход.
 *
 * Проход один, потому что раньше их было семь (шесть `filter` по статусам плюс
 * SSL), а не потому, что сотня строк это дорого: семь проходов заставляли
 * читать правило по кусочкам, разбросанным по файлу. Здесь оно целиком перед
 * глазами — и видно, в частности, что `inProgress` НЕ участвует в цикле вовсе.
 */
export function countDomains(domains: readonly CountableDomain[]): DomainCounts {
  const byStatus: Record<LifecycleStatus, number> = { new: 0, active: 0, failed: 0 };
  const ns = { ok: 0, pending: 0, error: 0 };
  let failedAtSsl = 0;

  for (const d of domains) {
    if (d.status === "new" || d.status === "active" || d.status === "failed") {
      byStatus[d.status] += 1;
    }
    if (d.ns_status === "ok" || d.ns_status === "pending" || d.ns_status === "error") {
      ns[d.ns_status] += 1;
    }
    /*
     * Домены, у которых провижининг дошёл до SSL и сертификата не получил.
     *
     * Считается по `ssl_status === "error"` — единственному признаку, который
     * такой прогон о себе действительно оставляет: провал выпуска (как и
     * пропуск из-за DNS или отсутствия почты) намеренно НЕ роняет провижининг,
     * поэтому домен остаётся `site_created`, а не `failed`, и в
     * `last_provision_error` ничего не пишется — там живут только фатальные
     * провалы, и их текст (`provision failed at {шаг}: {класс}`) слова «ssl» не
     * содержит вовсе. Прежний предикат (`status === "failed"` И текст ошибки со
     * словом «ssl») не мог стать истинным ни при одном прогоне.
     */
    if (d.ssl_status === "error") failedAtSsl += 1;
  }

  return {
    total: domains.length,
    byStatus,
    /*
     * «In progress» считается ОСТАТКОМ, а не перечислением промежуточных
     * статусов, и это не лень: перечисление молча теряет любой статус, которого
     * автор не вспомнил (а ровно так и потерялся `ns_ok` — см. `domainStatus`),
     * и ряд переставал бы сходиться с общим числом. Остаток сходится по
     * построению — включая статусы, которых на фронте не знают вовсе.
     */
    inProgress: domains.length - byStatus.new - byStatus.active - byStatus.failed,
    ns,
    failedAtSsl,
  };
}

/**
 * Число на чипе по значению его фильтра. Пустое значение — чип «All».
 *
 * Существует затем, чтобы подпись чипа и его счётчик нельзя было сопоставить
 * НЕВЕРНО: пара, собранная руками (`{ value: "active", count: byStatus.failed }`),
 * компилируется молча и даёт чип, который показывает одно, а фильтрует другое.
 * Здесь счётчик выводится из того же значения, которое уедет в фильтр, — то
 * есть разъехаться им нечем.
 */
export function chipCount(counts: DomainCounts, status: LifecycleStatus | ""): number {
  return status === "" ? counts.total : counts.byStatus[status];
}
