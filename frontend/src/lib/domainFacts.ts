/**
 * Что показать про копии домена. Четыре состояния, и ни одно не сводится к
 * другому:
 *
 * - `no-snapshot` — сервер не читали ни разу;
 * - `not-in-snapshot` — снимок есть, а поля `backups` в нём нет (снимок старее
 *   этой функции либо сама функция ещё не приехала — см. `DESKTOP_READS_BACKUPS`);
 * - `unreadable` — панель ответила, разобрать ответ не вышло. **Не** «копий нет»;
 * - `listed` — панель ответила, и это её список; он может быть и пустым, и
 *   ровно этот случай — единственное место продукта, где мы утверждаем
 *   отсутствие копий.
 */
export type BackupsView =
  | { state: "no-snapshot" }
  | { state: "not-in-snapshot" }
  | { state: "unreadable" }
  | { state: "listed"; items: DomainBackup[] };

/**
 * Разбор списка копий из снимка — правило одно на все экраны, и живёт оно
 * здесь, а не во вкладке, по той же причине, что `snapshotOf` и `sslState`:
 * лестницы состояний, переписанные заново у каждого показа, в этом проекте уже
 * разъезжались (принцип №6 CLAUDE.md).
 *
 * Две развилки, которые важно не перепутать:
 *
 * 1. **Снимка нет вовсе** (`noSnapshot`) — это `no-snapshot`, а не «поля нет»:
 *    мы не спрашивали сервер ни о чём, и претензии к содержимому снимка тут
 *    неуместны. Пара «отметка есть, фактов нет» (её гасит сам `snapshotOf`)
 *    трактуется как `not-in-snapshot`: подпись возраста рядом уже напечатала
 *    «Checked …», и сказать под ней «сервер не читали» значило бы дать два
 *    ответа про один снимок.
 * 2. **`state: "unknown"` — это не пустой список.** Пустым списком мы
 *    утверждаем, что копий нет; «unknown» говорит только о нас.
 *
 * Сортировка своя, а не порядок панели: новые сверху, копия без разобранной
 * даты — в конец. Копия, о дате которой мы ничего не знаем, не может
 * претендовать на «самую свежую», а именно так читается первая строка списка.
 * Неразобранная дата (`NaN`) считается отсутствующей по той же причине.
 * Порядок внутри «бездатных» сохраняется тем, каким его отдал десктоп.
 */
export function backupsOf(snapshot: Snapshot): BackupsView {
  if (snapshot.noSnapshot) return { state: "no-snapshot" };
  const backups = snapshot.facts?.backups;
  if (!backups) return { state: "not-in-snapshot" };
  if (backups.state !== "known") return { state: "unreadable" };
  return { state: "listed", items: sortBackups(backups.entries ?? []) };
}

/** Новые сверху, без даты — в конец (см. оговорку у `backupsOf`). */
function sortBackups(entries: DomainBackup[]): DomainBackup[] {
  const at = (b: DomainBackup) => {
    const ts = b.created_at ? new Date(b.created_at).getTime() : NaN;
    return Number.isNaN(ts) ? null : ts;
  };
  return [...entries].sort((a, b) => {
    const ta = at(a);
    const tb = at(b);
    if (ta === null && tb === null) return 0;
    if (ta === null) return 1;
    if (tb === null) return -1;
    return tb - ta;
  });
}
