/**
 * Что мы прочитали с сервера про домен — и насколько это знание свежее.
 *
 * Живёт отдельным чистым модулем по образцу `lib/serverStatus`, и по той же
 * причине: порог протухания — правило продукта, а не украшение компонента, и
 * стоит ему поселиться в карточке, как он разъедется по трём экранам (у
 * сервера так уже было). Одно правило на всех: **незнание нельзя рисовать как
 * здоровье** (принцип №6 CLAUDE.md).
 *
 * TS-тип `DomainFacts` ТОЧНО повторяет то, что сериализует Rust
 * (`ssh/fastpanel_facts.rs`, serde → snake_case) и кладёт бэкенд в поле
 * `fp_facts` ответа домена. Имена полей менять нельзя — это wire-контракт.
 *
 * Внутри три предмета, и все три про одно знание: сам wire-тип, лестница
 * состояния сертификата (`sslState` + `SSL_BADGE`) и РАЗБОР СНИМКА
 * (`snapshotOf`) — «есть ли он, протух ли и сколько ему лет». Разбор, кроме
 * флагов, собирает готовую английскую подпись («Checked 4h ago · stale»,
 * «Never checked»), то есть слова интерфейса выходят отсюда наружу в ДВУХ
 * местах, а не только из `SSL_BADGE`; оговорка про это — там же, над картой.
 */

import { formatAgoStale } from "./format";

/** Снимок состояния домена, прочитанный с сервера по SSH. */
export type DomainFacts = {
  /** Сайт на сервере; `null` — домена на сервере нет вовсе (не ошибка проверки). */
  site: {
    domain_name: string;
    site_user: string | null;
    site_path: string | null;
    php_version: string | null;
  } | null;
  ssl: {
    has_certificate: boolean;
    /** ISO-строка UTC. `null` — сертификата нет либо срок не прочитан. */
    expires_at: string | null;
    issuer: string | null;
    is_letsencrypt: boolean;
    /** Присутствует, только если чтение сертификата само по себе провалилось. */
    error?: string;
  };
  /** Логин + домашняя папка. Пароля здесь нет и быть не может — CLI его не отдаёт. */
  ftp_accounts: { login: string; home: string | null }[];
  php_version: string | null;
  php_handler: string | null;
  databases: string[];
  logs: { path: string; exists: boolean; size_bytes: number | null }[];
};

/** Состояние SSL так, как его честно можно назвать. */
export type SslState = "unchecked" | "missing" | "expired" | "expiring" | "valid" | "error";

/**
 * Порог, после которого снимок с сервера считается протухшим.
 *
 * Неделя — не с потолка: это ровно тот срок, на котором вывод о НАЛИЧИИ
 * перестаёт быть знанием. «Сертификат есть» недельной давности уже ничего не
 * гарантирует (могли отозвать, переставить, перевыпустить), а домен читается не
 * по расписанию, а по кнопке в десктопе — редкое ручное действие, как и снятие
 * метрик. Мельче порог — и почти каждое открытие карточки показывало бы
 * «протухло»; крупнее — и зелёный «valid» держался бы на позавчерашнем сервере.
 */
export const FACTS_STALE_MS = 7 * 24 * 60 * 60 * 1000;

/**
 * Порог «сертификат скоро истекает». 14 дней — обычный запас на перевыпуск
 * Let's Encrypt (сертификат живёт 90 дней, certbot обновляет за 30). Живёт в
 * модуле, а не в карточке, по той же причине, что и `FACTS_STALE_MS`.
 */
const SSL_EXPIRING_MS = 14 * 24 * 60 * 60 * 1000;

/** Старше порога ли отметка. `null` («ничего не было») — это не «протухло». */
function olderThan(iso: string | null | undefined, maxAgeMs: number, now: number): boolean {
  if (!iso) return false;
  const ts = new Date(iso).getTime();
  return !Number.isNaN(ts) && now - ts > maxAgeMs;
}

/**
 * Протух ли снимок фактов (см. `FACTS_STALE_MS`).
 *
 * `now` параметром не только ради тестов: карточка берёт время один раз на
 * рендер и раздаёт его и сюда, и в `sslState`, — иначе на границе порога рядом
 * оказались бы «valid» и подпись «· stale» про один и тот же снимок.
 */
export function isFactsStale(iso: string | null | undefined, now: number = Date.now()): boolean {
  return olderThan(iso, FACTS_STALE_MS, now);
}

/**
 * Состояние SSL по лестнице честности.
 *
 * `factsAt` — время УДАЧНОГО снимка (`fp_facts_at`), а не последней попытки:
 * протухание считается от того, когда снимок реально сняли.
 *
 * Асимметрия свежести — сердце функции:
 *
 * - **Вывод о наличии протухает.** «Сертификат есть» и «сертификата нет» —
 *   утверждения о том, что было на сервере в момент снимка; за неделю всё могло
 *   стать наоборот. Поэтому `valid` (зелёный) и `missing` требуют свежего
 *   снимка, а протухнув, оба уходят в `unchecked` — «мы не знаем», а не выдумка
 *   в любую сторону.
 * - **Вывод о сроке переживает протухание.** `expired`/`expiring` считаются
 *   против АБСОЛЮТНОГО `expires_at` и текущего `now`: если неделю назад срок
 *   истекал через 3 дня, сейчас он точно истёк, каким бы старым ни был снимок.
 *   Эти состояния не «здоровье», ошибиться в их сторону безопасно, поэтому они
 *   старому снимку разрешены.
 *
 * `error` (само чтение сертификата провалилось) — отрицательное измерение, оно
 * сильнее наличия и переживает протухание, ровно как `error` у сервера.
 */
export function sslState(
  ssl: DomainFacts["ssl"] | null | undefined,
  factsAt: string | null | undefined,
  now: number = Date.now(),
): SslState {
  // Удачной проверки не было — снимка нет. Не зелёный и не «missing»: незнание.
  if (!ssl || !factsAt) return "unchecked";

  // Чтение сертификата провалилось — это измерение, и оно отрицательное.
  if (ssl.error) return "error";

  const stale = isFactsStale(factsAt, now);

  if (!ssl.has_certificate) {
    // «Сертификата нет» свежее — повод действовать (`missing`); протухшее — уже
    // не знание (мог выпуститься), показываем `unchecked`, а не пугаем зря.
    return stale ? "unchecked" : "missing";
  }

  // Сертификат есть. Сначала — выводы о сроке: они действительны и на протухшем
  // снимке, потому что меряются абсолютной датой против «сейчас».
  const exp = ssl.expires_at ? new Date(ssl.expires_at).getTime() : NaN;
  if (!Number.isNaN(exp)) {
    if (exp <= now) return "expired";
    if (exp - now <= SSL_EXPIRING_MS) return "expiring";
  }

  // Срок в порядке (или неизвестен — тогда судим только по наличию). «Валиден»
  // — зелёное утверждение о здоровом сертификате: только под свежий снимок.
  return stale ? "unchecked" : "valid";
}

/**
 * Ярлык и цвет бейджа состояния SSL. `unchecked` — серый, зелёный только под
 * `valid`.
 *
 * Живёт рядом с `sslState`, который её и питает, а не в компоненте: читателей у
 * карты СТАНЕТ двое (карточка SSL и шапка карточки домена, которая её
 * получит), а два экрана, считающих состояние сервера по своей копии правила, в
 * этом проекте уже разъезжались (принцип №6 CLAUDE.md). Заодно
 * `Record<SslState, …>` не даст добавить состояние, забыв его
 * нарисовать: пропуск станет ошибкой типов, а не серым пятном на экране.
 *
 * Оговорка: вместе с состоянием сюда уехала и англоязычная ПОДПИСЬ — у соседних
 * модулей `lib` наружу выходит только токен, а слова остаются у показа. Здесь
 * иначе ровно затем, чтобы два места не назвали одно состояние по-разному;
 * появится словарь интерфейса — подписи уйдут в него. Вместе с ними уйдёт и
 * `freshness` из `snapshotOf`: это вторая дверь, через которую английские слова
 * выходят из этого модуля, и не назвать её здесь значило бы обречь будущую
 * миграцию её не найти.
 */
export const SSL_BADGE: Record<SslState, { label: string; variant: string }> = {
  unchecked: { label: "Not checked", variant: "gray" },
  missing: { label: "No certificate", variant: "red" },
  expired: { label: "Expired", variant: "red" },
  expiring: { label: "Expiring soon", variant: "yellow" },
  valid: { label: "Valid", variant: "green" },
  error: { label: "Read error", variant: "red" },
};

/** Снимок сервера, разобранный на то, что о нём спрашивают экраны. */
export interface Snapshot {
  /**
   * Факты снимка либо `null`. Читаются ТОЛЬКО вместе со своей отметкой времени:
   * «когда сняли» — часть самого снимка, а не украшение. Бэкенд пишет обе
   * колонки одной транзакцией (`domain_service.record_facts`), так что пара
   * «факты есть, отметки нет» не должна возникать; гейт — чтобы, если она
   * возникнет, экран не сказал «Сервер ещё не читали» и тут же не напечатал эти
   * факты списком аккаунтов. Одна истина вместо двух независимых.
   */
  facts: DomainFacts | null;
  /** Удачного снимка не было ни разу. */
  noSnapshot: boolean;
  /** Снимок есть, но он старше порога `FACTS_STALE_MS`. */
  stale: boolean;
  /** Готовая подпись возраста: «Checked 4h ago · stale» либо «Never checked». */
  freshness: string;
}

/**
 * Разбор снимка — ОДНО правило на все экраны, которые его показывают.
 *
 * Копий было две (вкладка Server и `DomainSslCard`), а с приездом вкладки Logs,
 * которой нужна та же тройка, стало три. Четыре строки выглядят слишком мелкими,
 * чтобы их собирать, но собраны они как раз потому, что мелкие: в них сидят два
 * решения, которые нельзя принять по-разному дважды — гейт отметки времени над
 * фактами (см. `Snapshot.facts`) и то, что свежесть считается от `fp_facts_at`
 * (когда снят снимок), а НЕ от `fp_checked_at` (когда была последняя попытка): иначе
 * протухший снимок молодел бы от проваленной проверки. Ровно так же и по той же
 * причине собран показ полей (`components/domains/facts/fields.tsx`), а правило
 * расхождения — в `lib/domainDrift`.
 *
 * Типа `Domain` функция НЕ знает — как и `sslState` над ней, и как весь
 * `lib/domainDrift`: берутся два значения, а не строка из тридцати полей.
 * Дело не в аккуратности вызова, а в том, что знание домена завело бы у `lib`
 * ссылку на `api` ради двух колонок, а правило перестало бы проверяться без
 * сборки объекта домена.
 *
 * @param facts   колонка `fp_facts` домена — сам снимок.
 * @param factsAt колонка `fp_facts_at` — когда снимок УДАЛСЯ.
 */
export function snapshotOf(
  facts: DomainFacts | null | undefined,
  factsAt: string | null | undefined,
  now: number,
): Snapshot {
  const noSnapshot = !factsAt;
  const stale = isFactsStale(factsAt, now);
  return {
    facts: noSnapshot ? null : facts ?? null,
    noSnapshot,
    stale,
    freshness: factsAt ? `Checked ${formatAgoStale(factsAt, stale, now)}` : "Never checked",
  };
}
