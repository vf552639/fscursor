/**
 * Сколько осталось до срока — и что говорить, когда срока мы не знаем.
 *
 * Живёт отдельным модулем по образцу `lib/serverStatus.ts` и по той же причине:
 * порог «скоро истекает» читают три места (колонка Expires, колонка SSL,
 * карточка домена), а размазанный по JSX он расходится молча — сравнение
 * `days < 30` в одной ячейке и `days <= 30` в соседней дают разный ответ про
 * один и тот же домен, и заметить это можно только глазами.
 *
 * Правило то же, что у серверов: **незнание нельзя рисовать как «всё хорошо».**
 * У домена без `expiry_date` и у сертификата без `ssl_expires_at` состояние
 * `unknown` и прочерк, а не зелёная тишина: пустая ячейка читается как
 * «показывать нечего, значит порядок», то есть ровно наоборот. Продукт для того
 * и заведён, чтобы про просрочку человек узнавал от него, а не от клиента.
 */

// Единственный импорт модуля — и только ради `expiryTextColor` внизу. Правила
// («истёк ли», «скоро ли») от палитры не зависят и зависеть не должны; цвет —
// зависит, и держать его хексами здесь значило бы завести четвёртую копию
// палитры ровно того сорта, против которого написан `designTokens`.
import { tokens } from "./designTokens";

/** Состояния срока. `unknown` — «даты нет или она нечитаема», не «ок». */
export type ExpiryState = "unknown" | "expired" | "soon" | "ok";

/**
 * За сколько дней до срока пора беспокоиться.
 *
 * Месяц — потому что обе операции, которыми на это отвечают, в месяц
 * укладываются с запасом: продление домена у регистратора (оплата, иногда
 * ручная возня с балансом и с переносом) и перевыпуск сертификата (certbot,
 * которому нужны рабочие NS и доступный сервер). Порог короче недели превратил
 * бы предупреждение в уведомление о случившемся, а длиннее месяца — покрасил бы
 * жёлтым половину списка, и жёлтый перестал бы значить «сделай что-то».
 */
export const EXPIRY_SOON_DAYS = 30;

const DAY_MS = 24 * 60 * 60 * 1000;

/** Прочерк — ответ «мы не знаем». Один на модуль, чтобы не разъехались начертания. */
export const NO_VALUE = "—";

/**
 * Дата без времени? Ровно в таком виде (`2026-09-01`) бэкенд отдаёт
 * `expiry_date`: в схеме это `Optional[date]`, а не `datetime`.
 *
 * Группы — ради `parseExpiryInput` (ниже): он принимает эту же запись с
 * клавиатуры и разбирает её ЭТОЙ же регуляркой, а не своей копией. Копия у
 * него сначала была — вторая запись одного ответа, в полутора сотнях строк
 * отсюда, — и это ровно тот сорт дубля, из-за которого разбор и поселён в один
 * файл с печатью: «как выглядит date-only» модуль решает однажды.
 */
const DATE_ONLY = /^(?<year>\d{4})-(?<month>\d{2})-(?<day>\d{2})$/;

function isDateOnly(iso: string | null | undefined): boolean {
  return !!iso && DATE_ONLY.test(iso);
}

/**
 * Разбор ISO-строки БЕЗ каких-либо сдвигов; `null` — строки нет или она
 * нечитаема.
 *
 * Одна на модуль, хотя пользуются ею двое и по-разному: `expiryTs` прибавляет
 * date-only значению сутки (срок такой даты — конец дня), а `formatExpiryDate`
 * печатает саму дату и потому обязана видеть её несдвинутой. Общая у них
 * ровно политика «чего мы не разобрали, того мы не знаем» — и разъехаться этим
 * двум копиям `Number.isNaN` было бы нечем себя выдать: одна ячейка печатала бы
 * «Invalid Date», а соседняя подпись под ней — честный прочерк.
 */
function parse(iso: string | null | undefined): number | null {
  if (!iso) return null;
  const ts = new Date(iso).getTime();
  return Number.isNaN(ts) ? null : ts;
}

/**
 * Момент, в который срок ИСТЕКАЕТ; `null` — срока мы не знаем.
 *
 * Мусор (`new Date(x)` → `NaN`) уравнен с отсутствием намеренно: и то и другое
 * — «мы не знаем срок», а не «срок истёк». Разница видна только нам, а
 * пользователю в обоих случаях честен один и тот же прочерк.
 *
 * **Дата без времени означает ВЕСЬ этот день, поэтому срок у неё — его КОНЕЦ**
 * (полночь UTC плюс сутки). Это решение продукта, а не деталь разбора: у
 * регистратора «expiry date: 1 сентября» значит, что первого числа домен ещё
 * жив. Считая сроком начало дня, продукт первого сентября рисовал бы красное
 * «expired today» домену, который работает, — то есть звал бы человека
 * продлевать то, что не истекло, и заодно учил бы не верить красному. Раннего
 * предупреждения это не отнимает: за месяц до срока строка уже жёлтая
 * (`EXPIRY_SOON_DAYS`), и день туда-сюда на этом фоне ничего не решает, тогда
 * как ложная просрочка видна сразу и стоит доверия.
 *
 * `ssl_expires_at` — полноценный `datetime`, у него момент известен точно, и
 * сдвигать его нечем и незачем.
 *
 * Экспортируется ради сортировки таблицы: сравнивать сроки надо числами, а не
 * подписями («in 9 days» и «in 10 days» строкой сравниваются наоборот). Своим
 * `new Date(x).getTime()` сортировка обошлась бы только до первой битой даты:
 * `NaN` в компараторе ложен во всех сравнениях сразу, и порядок от него не
 * «чуть съезжает», а становится произвольным. Здесь же нечитаемое — это `null`,
 * и у `null` в компараторе есть одно явное правило (в конец, в обе стороны).
 */
export function expiryTs(iso: string | null | undefined): number | null {
  const ts = parse(iso);
  if (ts === null) return null;
  return isDateOnly(iso) ? ts + DAY_MS : ts;
}

/**
 * Сама дата срока, как её называет регистратор: `01.09.2026`. Незнание — прочерк.
 *
 * Живёт здесь, а не берётся местом показа из общего `fmtDate`, потому что
 * date-only значение обязано печататься в UTC. `new Date("2026-09-01")` — это
 * полночь UTC, и `toLocaleDateString` без зоны переводит её в зону читателя: в
 * Нью-Йорке та же строка печаталась как `31.08.2026`, то есть колонка называла
 * дату, которой у домена нет, и расходилась с письмом регистратора. Заметить
 * это, живя восточнее UTC, нельзя вовсе — тесты и разработчики в UTC+3 видели
 * верную дату.
 *
 * `datetime` (`ssl_expires_at`) печатается, наоборот, в зоне читателя: там
 * момент настоящий, и «когда у МЕНЯ» — правильный ответ. Разные правила у двух
 * колонок не расхождение: у `date` мгновения нет вовсе, у `datetime` есть.
 *
 * Формат — тот же `ru-RU` `dd.mm.yyyy`, что у `fmtDate` на всех остальных
 * экранах: два написания одной даты читатель принимает за две разные даты.
 */
export function formatExpiryDate(iso: string | null | undefined): string {
  // НЕ через `expiryTs`: тот сдвигает date-only значение на конец дня, и печать
  // от него называла бы СЛЕДУЮЩИЙ день. Общий у них разбор (`parse`), а сдвиг —
  // нет: это разные вопросы, «когда истекает» и «что за дата написана».
  const ts = parse(iso);
  if (ts === null) return NO_VALUE;
  return new Date(ts).toLocaleDateString("ru-RU", {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
    ...(isDateOnly(iso) ? { timeZone: "UTC" } : {}),
  });
}

/** Чем именно плоха набранная строка. Два ответа, потому что чинить их по-разному. */
export type ExpiryInputError = "format" | "date";

/**
 * Исход разбора набранной строки. Размеченное объединение, а не «строка или
 * `null`»: исходов ТРИ, и третий («поле очищено») — не ошибка и не дата, а
 * распоряжение снять срок. Слив его с любым из двух соседей, поле лишилось бы
 * единственного способа стереть однажды записанную дату.
 */
export type ExpiryInputResult =
  | { kind: "parsed"; iso: string }
  | { kind: "empty" }
  | { kind: "error"; error: ExpiryInputError };

/**
 * Написания, которые поле принимает. День-первым — оба разделителя: продукт
 * печатает `ru-RU` (`01.09.2026`), и прочитанное по-американски `09/01/2026`
 * означало бы 1 сентября там, где показано 9 января, — расхождение молчаливое и
 * ровно в тех данных, ради которых продукт заведён.
 *
 * День и месяц — строго по две цифры, год — строго по четыре. Это не придирка:
 * двузначный год `01.09.26` пришлось бы ДОГАДЫВАТЬСЯ достроить до века, а
 * догадка тут молчит — записанным окажется срок, которого человек не называл.
 * Раз уж форма диктуется (placeholder поля обещает `DD.MM.YYYY`), диктуется она
 * целиком: принимаем ровно то, что печатаем.
 */
const INPUT_FORMATS: RegExp[] = [
  /^(?<day>\d{2})\.(?<month>\d{2})\.(?<year>\d{4})$/,
  /^(?<day>\d{2})\/(?<month>\d{2})\/(?<year>\d{4})$/,
  DATE_ONLY,
];

/**
 * Границы правдоподобного года. Всё за ними — описка, а не дата.
 *
 * Сторожат они перестановку цифр при наборе: `0226` вместо `2026` — запись
 * читаемая, и в календаре такой день существует, поэтому сама по себе сверка
 * его пропускала. Дальше домену уезжал на сервер III век, список красил его
 * красным «expired», а исправить значение на месте было НЕЛЬЗЯ: `ru-RU` печатает
 * такой год тремя цифрами (`01.09.226`), и разбор эту строку уже не принимал.
 * То есть модуль отказывался читать собственную подпись — ровно то расхождение
 * печати и разбора, ради которого они и живут в одном файле.
 *
 * Нижняя граница — эпоха Unix: ни домена, ни сервера, ни сертификата раньше
 * неё не бывает, а `Date` до 1970-го считает исправно и молча, так что сама
 * себя эта ошибка не выдаст. Верхняя взята заведомо дальше любого осмысленного
 * срока: регистраторы продают домен максимум на десять лет вперёд, так что за
 * 2100-м годом не остаётся ничего у всех трёх полей, которые этот разбор
 * обслуживает, — срока домена, даты покупки и срока сервера.
 */
const MIN_YEAR = 1970;
const MAX_YEAR = 2100;

/**
 * Есть ли такая дата в календаре.
 *
 * Сверка — обратным преобразованием: собрали UTC-дату из чисел, прочитали из
 * неё год, месяц и день обратно, сошлось — дата настоящая. Нужна она потому,
 * что `Date` переполнение не ловит, а МОЛЧА переносит: 31 февраля становится
 * 3 марта, и без сверки домену записался бы срок, которого никто не набирал.
 *
 * Так, а не таблицей длин месяцев: таблице нужно ещё и правило високосности с
 * оговоркой про 400 лет (1900-й не високосный, 2000-й високосный) — то есть
 * второй календарь в проекте, который ошибается редко и без единого признака.
 *
 * `Date.UTC`, а не локальный конструктор: сравнение идёт с теми же числами,
 * что пришли, и зоне читателя попасть в него нечем ни на одном шаге.
 *
 * Правдоподобие года эта сверка НЕ проверяет и проверить не может: календарь
 * знает 226-й год не хуже 2026-го. Отсекает такое отдельный явный порог
 * (`MIN_YEAR`/`MAX_YEAR`), и стоит он ПЕРЕД сверкой — заодно поэтому сюда не
 * доходят годы меньше сотни, которым `Date.UTC` молча приписывает 1900.
 */
function isRealDate(year: number, month: number, day: number): boolean {
  const t = new Date(Date.UTC(year, month - 1, day));
  return (
    t.getUTCFullYear() === year && t.getUTCMonth() === month - 1 && t.getUTCDate() === day
  );
}

/**
 * Разбор даты, набранной руками: `01.09.2026` → `2026-09-01`.
 *
 * Появилась, когда из проекта ушёл нативный `<input type="date">`: в WKWebView
 * десктопа он не принимал ввод с клавиатуры вовсе — цифры не вставали в
 * сегменты, календарь не открывался, — а поле, которое молча не берёт ввод,
 * хуже отсутствующего. Форму даты читает теперь не браузер, а этот модуль.
 *
 * Живёт вплотную к `formatExpiryDate` намеренно: печать и разбор — одно
 * решение, а не два. Разъехавшись (а такие пары расходятся на первой же правке
 * формата), они дают поле, которое не принимает обратно строку, им же самим и
 * показанную, — и виноватым в этом выглядит человек.
 *
 * Отдаёт ISO-строку БЕЗ времени и без зоны — ровно ту форму, в которой
 * `expiry_date` живёт на бэкенде (`Optional[date]`) и в которой её узнаёт
 * `isDateOnly`. Ни `new Date(y, m, d)`, ни `toISOString()` тут не участвуют:
 * локальная полночь, переведённая в UTC, западнее Гринвича называет предыдущий
 * день — поле разошлось бы с колонкой списка на сутки, а на 1 января ещё и на
 * год. Строка собирается из разобранных чисел, `Date` берётся только для сверки
 * календаря и только в UTC.
 *
 * Ошибки две, и различены они не для порядка: «не понял запись» (`format`) и
 * «такой даты быть не может» (`date`) просят от человека разного — дописать век
 * либо исправить число. Одна подпись на оба случая заставила бы искать ошибку
 * там, где её нет.
 */
export function parseExpiryInput(raw: string): ExpiryInputResult {
  const text = raw.trim();
  // Тримминг ради вставки из буфера: дата, скопированная из письма
  // регистратора, приезжает с пробелом или переводом строки чаще, чем без них.
  if (text === "") return { kind: "empty" };

  for (const format of INPUT_FORMATS) {
    const groups = format.exec(text)?.groups;
    // Куски достаются ПО ИМЕНАМ, а не по номерам: порядок у трёх написаний
    // разный (день-первым и год-первым), и номера пришлось бы раскладывать
    // вторым, отдельно живущим правилом — то есть держать порядок записанным
    // дважды и надеяться, что правки достанутся обеим записям.
    if (!groups) continue;
    const { year, month, day } = groups;
    const y = Number(year);
    if (y < MIN_YEAR || y > MAX_YEAR || !isRealDate(y, Number(month), Number(day))) {
      // Обе беды — `date`, а не `format`: запись человек составил верно,
      // править ему надо само число, и подпись поля обязана позвать его туда.
      return { kind: "error", error: "date" };
    }
    // Куски берутся строками, как пришли: они уже ровно по две и четыре цифры
    // (см. `INPUT_FORMATS`), и обратное превращение чисел в строку добавило бы
    // сюда padding — то есть второе место, где решается форма даты.
    // Четыре цифры года при этом не формальность: именно они и делают строку
    // такой, какую `formatExpiryDate` напечатает обратно один в один.
    return { kind: "parsed", iso: `${year}-${month}-${day}` };
  }
  return { kind: "error", error: "format" };
}

/**
 * Сколько полных суток осталось до срока; `null` — срок неизвестен.
 *
 * Отрицательное число значит только «срок уже прошёл», и НЕ значит «столько
 * суток назад»: у прошедшего срока `floor` уводит от нуля, поэтому и час назад,
 * и ровно сутки назад дают `-1`. Давность спрашивают у `formatExpiry` — он
 * считает её отдельно, ровно из-за этого.
 *
 * Считаем в сутках, а не в часах: у `expiry_date` времени нет вовсе, и любая
 * арифметика по часам над ним означала бы точность, которой в данных нет.
 * `ssl_expires_at` — полноценный datetime, но ответ на вопрос «пора ли
 * шевелиться» у него тот же суточный.
 *
 * Округление — ВНИЗ (`floor`), то есть остаток занижается: «осталось 30 дней»
 * при 30 сутках и 20 часах. Асимметрия намеренная, как и у порогов протухания в
 * `serverStatus`: ошибиться в сторону более раннего предупреждения дёшево, в
 * обратную — это просроченный домен, про который продукт молчал до последнего
 * дня.
 *
 * `now` параметром — по той же причине, что и там: экран берёт время ОДИН раз
 * на рендер и раздаёт его всем ячейкам. Иначе у соседних строк одного списка
 * «сейчас» разное, и на границе суток два домена с одной датой получили бы
 * разные подписи.
 *
 * Наружу не выходит намеренно: снаружи на вопрос «сколько осталось» отвечают
 * `expiryState` (цветом) и `formatExpiry` (словами), и третий способ спросить
 * то же самое — это третий шанс разойтись с ними в округлении.
 */
function daysLeft(iso: string | null | undefined, now: number = Date.now()): number | null {
  const ts = expiryTs(iso);
  if (ts === null) return null;
  return Math.floor((ts - now) / DAY_MS);
}

/**
 * Состояние срока.
 *
 * Граница `soon` включающая (`<= EXPIRY_SOON_DAYS`): ровно 30 оставшихся суток —
 * это уже «пора», а не «ещё нет».
 *
 * День самого срока у date-only значения читается как `soon` («in <1 day»), а
 * не как `expired`: срок такой даты — конец дня, см. `expiryTs`. `expired`
 * начинается со следующих суток, и подпись тогда честно говорит «expired
 * today», а не выдумывает давность.
 */
export function expiryState(iso: string | null | undefined, now: number = Date.now()): ExpiryState {
  const days = daysLeft(iso, now);
  if (days === null) return "unknown";
  if (days < 0) return "expired";
  return days <= EXPIRY_SOON_DAYS ? "soon" : "ok";
}

/** Множественное число по-английски: «1 day», но «2 days». */
function plural(n: number, unit: string): string {
  return `${n} ${unit}${n === 1 ? "" : "s"}`;
}

/**
 * Подпись срока словами: `in 12 days`, `expired 3 days ago`, `—`.
 *
 * Прочерк на неизвестном сроке — не заглушка вёрстки, а ответ: «мы не знаем».
 * Поэтому подпись отдаёт его сама, а не оставляет это решение каждому месту
 * показа: пустая строка там превратилась бы в пустую ячейку, а пустая ячейка
 * читается как «всё в порядке».
 */
export function formatExpiry(iso: string | null | undefined, now: number = Date.now()): string {
  const ts = expiryTs(iso);
  if (ts === null) return NO_VALUE;
  const diff = ts - now;
  if (diff < 0) {
    // Прошедшие сутки считаем ОТДЕЛЬНЫМ `floor` от положительной разности, а не
    // выводим из `daysLeft` вычитанием единицы (`-daysLeft - 1`).
    //
    // Разница между двумя формулами — ровно в одной точке: на ЦЕЛОМ числе
    // суток. Для дробной давности они тождественны (`ceil(u) - 1 === floor(u)`
    // при нецелом `u`), а на целом старая занижала на день: ровно сутки назад
    // называлось «expired today», ровно двое — «1 day ago». Причина в том, что
    // у отрицательного аргумента `floor` уводит ОТ нуля, и вычитание единицы,
    // честное для неполных суток, на полных лишнее.
    //
    // Точка редкая (в проде разность попадает на целые сутки, только если
    // «сейчас» совпало с полуночью UTC даты с точностью до миллисекунды), но
    // граница — это то, что ломается молча и что проверяет тест.
    const elapsed = Math.floor(-diff / DAY_MS);
    return elapsed === 0 ? "expired today" : `expired ${plural(elapsed, "day")} ago`;
  }
  const days = Math.floor(diff / DAY_MS);
  return days === 0 ? "in <1 day" : `in ${plural(days, "day")}`;
}

/**
 * Цвет подписи срока — четырьмя ролями палитры макета, без единого хекса.
 *
 * Раньше здесь стояли четыре хекса старой палитры (`#dc2626`, `#d97706`,
 * `#9ca3af`, `#374151`), подобранные под соседние бейджи страницы: «почти
 * совпадающий оттенок хуже явно другого — рядом в строке стоят бейджи, и
 * подпись на полтона мимо читается как поломка вёрстки». Довод остался в силе
 * ровно так же — только бейджи рядом теперь другие, и совпадать надо с ними.
 * Оттого и токены, а не новые хексы: соседство держится само, а не сверкой глаз
 * при каждой правке.
 *
 * Потребителей у функции ДВА, и второй — не список: `DomainExpiryField` в шапке
 * карточки домена. Это не побочный ущерб, а смысл модуля: срок домена в списке
 * и он же в карточке обязаны выглядеть одинаково, иначе клик по строке
 * переносит человека будто в другой продукт.
 *
 * ГДЕ ЭТА ЛЕСТНИЦА КОНЧАЕТСЯ. Она красит СОСТОЯНИЕ СРОКА — то есть значение,
 * которое показывают. Действию — кнопке, ссылке, приглашению что-то сделать —
 * цвет отсюда не положен, даже если оно стоит на месте значения. Разница не
 * теоретическая: у состояния `unknown` цвет заведомо бледный (см. ниже), и
 * кнопка «set date» в карточке, взявшая его себе, оказалась призывом к
 * действию с контрастом 1.48:1 — на грани невидимости. Свой цвет она теперь и
 * берёт (`DomainExpiryField`), а сюда за ним больше не ходит.
 *
 * **Осознанное отступление от макета.** Макет красит красным всё, до чего
 * меньше тридцати дней, то есть сливает «истёк» и «скоро истечёт» в одно
 * пятно. Здесь эти состояния различены по построению (см. `expiryState`), и
 * сливать их цветом значило бы отнять у красного его единственный смысл —
 * «поздно». `soon` остаётся янтарным.
 *
 * Зелёного в этой лестнице нет намеренно: «срок ещё далеко» — это отсутствие
 * повода, а не достижение, и красить им ряд из ста строк значило бы отнять
 * различимость у тех двух, где действительно жёлтое и красное.
 */
export function expiryTextColor(state: ExpiryState): string {
  if (state === "expired") return tokens.semantic.danger.text;
  if (state === "soon") return tokens.semantic.warning.text;
  // `unknown` — самый бледный тон палитры, тот же, каким на странице нарисованы
  // прочерки и выключенные действия: незнание выглядит как незнание, а не как
  // норма и не как тревога.
  //
  // Бледность тут ЗАКОНЧЕННАЯ, а не «поправим потом»: 1.48:1 на белом, ниже
  // любого порога WCAG. Допустимо это ровно потому, что читать в этом
  // состоянии нечего — на экране стоит прочерк «—», знак «значения нет», и
  // смысл несёт не начертание знака, а его пустота. Прочерк, набранный
  // читаемым тоном, спорил бы за внимание с настоящими датами соседних строк —
  // то есть отсутствие срока кричало бы громче истёкшего.
  //
  // Отсюда и граница: как только `unknown` достаётся не прочерку, а СЛОВУ,
  // которое надо прочесть, этот цвет неверен, и брать его нельзя. Так уже
  // случилось однажды — см. абзац «где эта лестница кончается» выше.
  if (state === "unknown") return tokens.text.disabled;
  return tokens.text.ink;
}

/**
 * Насыщенность подписи срока. Живёт рядом с цветом и по той же причине: «какие
 * состояния тревожные» — это одно решение, а не два. Пока начертание считалось
 * по месту показа (`state === "ok" || state === "unknown" ? 400 : 600`), пятое
 * состояние получило бы жирный шрифт молча — при том что цвет ему здесь
 * назначили бы явно.
 *
 * Тревожное — полужирным: цвет в списке на сотню строк работает на периферии
 * зрения, но не работает у тех, кто его не различает, и вес — второй,
 * дублирующий канал (тот же приём, что у подписи «· stale» рядом с цветом
 * протухшего показания).
 */
export function expiryTextWeight(state: ExpiryState): number {
  return state === "expired" || state === "soon" ? 600 : 400;
}
