/**
 * Имя лог-файла для человека — выведенное ИЗ ПУТИ, а не взятое из списка.
 *
 * Пути логов строит десктоп (`ssh/fastpanel_facts.rs`, `log_candidates`) по
 * одной раскладке: `<домашний каталог владельца>/logs/<домен>-<вид>.log`, где
 * вид сегодня один из четырёх (`frontend.access`, `frontend.error`,
 * `backend.access`, `backend.error`). Соблазн зашить эти четыре названия
 * табличкой и брать подпись оттуда велик, и он неверен дважды: список приезжает
 * с сервера и бывает ПУСТЫМ (владелец сайта не найден — путь построить не из
 * чего), а поменяйся раскладка в FastPanel или у нас — табличка молча подписала
 * бы чужой файл знакомым именем. Из пути же подпись либо выводится, либо честно
 * не выводится.
 *
 * Имя домена приходит аргументом, а не отрезается «до первого дефиса»: дефис —
 * законный символ имени домена (`my-site.com-frontend.error.log`), и такое имя
 * резалось бы посреди себя.
 */
export function logFileLabel(path: string, domainName: string): string {
  // Каталог отбрасываем: он одинаков у всех логов сайта и стоит под чипами
  // целиком, отдельной строкой.
  const base = path.split("/").pop()?.trim() ?? "";
  // Путь без последнего сегмента (пустая строка, слеш на конце) — не наш
  // случай; печатаем как пришло, чтобы не подписать файл пустотой.
  if (!base) return path.trim() || path;

  // Регистр имени домена не значим (RFC 1035), а в нашей строке и в ответе
  // сервера он может отличаться: сверяем в нижнем, режем по длине префикса.
  const prefix = `${domainName}-`;
  const known =
    domainName.length > 0 &&
    base.toLowerCase().startsWith(prefix.toLowerCase()) &&
    base.toLowerCase().endsWith(".log");
  // Путь незнакомой формы — это ровно то место, где выдумывать нельзя: имя
  // файла остаётся как есть. Оно ничего не обещает и ни с чем не спорит, тогда
  // как разбор «на всякий случай» (точки в пробелы) превратил бы
  // `example.com.error.log` в бодрое «Example com error» — подпись, которой в
  // системе нет.
  if (!known) return base;

  const kind = base.slice(prefix.length, base.length - ".log".length);
  // `<домен>-.log` — формально знакомая форма без вида. Имя файла честнее пустой
  // подписи.
  if (!kind) return base;

  // `frontend.access` → «Frontend access»: точки разделяют слова, заглавная —
  // только первая (подписи продукта в предложном регистре, не Title Case).
  const words = kind.split(".").join(" ");
  return words.charAt(0).toUpperCase() + words.slice(1);
}
