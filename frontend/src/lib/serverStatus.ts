/**
 * Что мы на самом деле знаем про сервер — и насколько это знание свежее.
 *
 * Живёт отдельным модулем, потому что читают его ТРИ экрана (дашборд, список
 * серверов, деталь сервера), и раньше лестница статусов была переписана на
 * каждом из них заново. Расхождение было не теоретическим: на дашборде
 * `status === "active" ? "healthy"` не смотрел на результат проверки вовсе, и
 * подтверждённо упавший сервер светился там зелёным на первом же экране.
 *
 * Правило одно на всех: **незнание нельзя рисовать как здоровье.** Отсюда все
 * решения ниже.
 */

/**
 * Статус «мы не знаем, отвечает ли машина». Отдельное слово, а не отсутствие
 * бейджа: пустое место читается как «показывать нечего, значит всё хорошо», то
 * есть ровно наоборот.
 */
export const UNCHECKED = "unchecked";

/** Значения, которыми экраны рисуют состояние сервера. */
export type ServerUiStatus = "error" | "active" | typeof UNCHECKED | "provisioned" | "new";

/** Поля сущности, из которых состояние выводится. */
export interface ServerStatusInput {
  status?: string | null;
  last_check_at?: string | null;
  last_check_ok?: boolean | null;
}

/**
 * Порог, после которого проверка доступности считается протухшей.
 *
 * Проверка идёт раз в 6 часов, поэтому порог обязан быть заметно больше шага:
 * иначе статус мигал бы между прогонами при любой задержке очереди. 18 часов —
 * это ТРИ пропущенных прогона подряд: одиночный пропуск (перезапуск воркера,
 * деплой, забитая очередь) в «не знаем» не проваливается, а три подряд — это
 * уже не икота, а умерший beat, и зелёный бейдж после него держится на
 * позавчерашнем ответе.
 */
const CHECK_STALE_MS = 18 * 60 * 60 * 1000;

/**
 * Порог «метрики протухли». Сутки — потому что снимает их десктоп по кнопке, а
 * не расписание: сутки без открытого десктопа — обычный рабочий цикл, а
 * позавчерашнее показание описывает уже другую машину.
 */
const METRICS_STALE_MS = 24 * 60 * 60 * 1000;

/** Старше порога ли отметка. `null` («ничего не было») — это не «протухло». */
function olderThan(iso: string | null | undefined, maxAgeMs: number, now: number): boolean {
  if (!iso) return false;
  const ts = new Date(iso).getTime();
  return !Number.isNaN(ts) && now - ts > maxAgeMs;
}

/**
 * Протухли ли метрики этого снимка (см. `METRICS_STALE_MS`).
 *
 * `now` параметром не только ради тестов: экран берёт время ОДИН раз на рендер
 * и раздаёт его всем трём функциям этого модуля. Иначе у одного сервера часы
 * читались бы трижды, и на границе порога рядом оказались бы бейдж «active» и
 * подпись «· stale» — про одну и ту же отметку.
 */
export function isMetricsStale(iso: string | null | undefined, now: number = Date.now()): boolean {
  return olderThan(iso, METRICS_STALE_MS, now);
}

/** Протухла ли проверка доступности (см. `CHECK_STALE_MS` и `now` выше). */
export function isCheckStale(iso: string | null | undefined, now: number = Date.now()): boolean {
  return olderThan(iso, CHECK_STALE_MS, now);
}

/**
 * Состояние сервера так, как его честно можно назвать.
 *
 * Ключевое: `servers.status` — это поле, выставленное при заведении сервера
 * (бэкенд пишет туда `new` и `active`), и об ответе машины оно не говорит
 * ничего. Отвечает ли она, знает только фоновая проверка порта, поэтому
 * «active» требует ПОЛОЖИТЕЛЬНОГО и СВЕЖЕГО ответа проверки — и только его.
 * Колонка со словом «active» без такого ответа (нет проверки, результат
 * неподтверждён, отметка протухла) даёт `unchecked`.
 *
 * Подтверждённое падение при этом протухшим не объявляется: `error` на старой
 * отметке — это «была проблема, свежих данных нет», и оно не усыпляет. Обратная
 * ошибка (нарисовать зелёным то, чего не знаем) стоит дороже, поэтому лестница
 * несимметрична намеренно. Честной асимметрию делает то, что возраст проверки
 * подписан рядом со статусом во всех местах показа: строка читается как «упал,
 * данные трёхмесячной давности», а не «упал только что».
 *
 * А вот колонка `status` — ЛЮБОЕ её значение — свежему положительному ответу
 * УСТУПАЕТ. Асимметрия выше — про старую ОТМЕТКУ измерения; здесь же измерения
 * нет вовсе: колонку двигает не монитор, а код заведения сервера, и написанное
 * в ней может пережить и починку машины, и её смерть — снимать оттуда некому.
 *
 * Насколько некому, стоит сказать точно: `"active"` в эту колонку пишет ровно
 * одно место во всём бэкенде — `server_service.create`, и только если сервер
 * заводят с уже установленной панелью. Из `new` не выводит ни установка
 * FastPanel с десктопа (write-back шлёт только `fastpanel_*`), ни bulk-import,
 * ни одна форма продукта: поле принимает `PUT /servers/{id}`
 * (`ServerUpdate.status`), но не шлёт его никто. Пока колонка была сильнее
 * ответа монитора, это означало, что сервер, добавленный руками по SSH,
 * отвечает, монитор об этом знает — а человек видит бейдж «new», серую точку,
 * пустой фильтр «active» и плитку «Unknown». Подтверждённое падение при этом
 * показывалось (ветка выше стоит первой), то есть продукт показывал downtime и
 * не показывал uptime.
 *
 * Поэтому `provisioned` и `new` ниже читаются как «что известно про сервер,
 * когда измерения нет», а не как этап, который измерение не вправе отменить.
 *
 * Чего лестница СОЗНАТЕЛЬНО не учитывает: успешный снимок метрик. Он снимается
 * по SSH, то есть доказывает доступность машины сильнее, чем наша TCP-проверка
 * порта, и сервер со свежими метриками формально «жив», даже если монитор
 * молчит. Знание здесь занижается намеренно: `active` означает ровно «фоновая
 * проверка получила ответ», один сигнал с одним смыслом и одним ритмом.
 * Подмешать сюда метрики значило бы получить статус, который у одних серверов
 * обновляется расписанием, а у других — тем, открывал ли человек десктоп; а
 * ошибка от такого занижения безопасна (`unchecked` рядом с «Metrics: 10m ago»
 * читается как «проверка молчит», и это правда).
 */
export function serverUiStatus(s: ServerStatusInput, now: number = Date.now()): ServerUiStatus {
  // Подтверждённое падение — сильнее всего остального: это измерение, и оно
  // отрицательное.
  if (s.last_check_ok === false) return "error";
  // «Монитор только что получил ответ» — второе измерение, и оно
  // положительное. Сильнее любого значения колонки (см. разбор выше).
  if (s.last_check_ok === true && !!s.last_check_at && !isCheckStale(s.last_check_at, now)) {
    return "active";
  }
  // Измерения нет: показываем то единственное, что про сервер известно, —
  // колонку. Незнакомое значение — «new»: гадать в сторону здоровья нельзя.
  if (s.status === "error") return "error";
  if (s.status === "provisioned") return "provisioned";
  if (s.status !== "active") return "new";
  // Колонка говорит «active», а измерения нет: это и есть «не знаем».
  return UNCHECKED;
}

/**
 * Цвет бейджа статуса. Зелёный в этом UI занят под «машина ответила», и больше
 * ни под что: `provisioned` — про этап жизненного цикла, а не про здоровье, и
 * зелёным он вводил бы в заблуждение ровно как `unchecked` (заодно у `StatusDot`
 * ключа `provisioned` нет, так что зелёный бейдж стоял бы рядом с серой точкой).
 *
 * Аргумент — только `ServerUiStatus`: единственный производитель этих значений
 * — `serverUiStatus` выше, а прежнее `| string` обнуляло union и позволяло
 * опечатке молча получить серый бейдж вместо ошибки сборки.
 */
export function statusBadgeVariant(status: ServerUiStatus): string {
  if (status === "error") return "red";
  if (status === "active") return "green";
  return "gray";
}
