import { normalizeZoneName } from "./cfZoneMatch";

/**
 * Куда ведёт apex домена в Cloudflare — и тот ли это сервер, что выбран в
 * карточке домена.
 *
 * Зачем вообще: связка «домен → сервер» в базе — это НАША запись, а не факт.
 * Поменять её в селекте можно за секунду, и сайт от этого никуда не переедет;
 * единственное, что говорит правду о том, куда пойдёт запрос, — A-запись зоны.
 * Поле сервера показывает расхождение подсказкой и выбор при этом не
 * блокирует: назначить домену новый сервер ДО развёртывания — нормальный
 * путь (ради него read-only и отменён), и требовать в этот момент совпадения
 * с DNS значило бы запретить сам сценарий.
 *
 * Отдельным модулем, а не тремя строками в компоненте, по той же причине, что и
 * `serverSites`: нормализация имени — правило про реальные данные (регистр из
 * письма регистратора, завершающая точка FQDN, пробелы из копипасты), и живёт
 * оно один раз в `normalizeZoneName`. Переписанное здесь заново, оно дало бы
 * «расхождение» на верной записи ровно там, где сверка зон и сайтов говорит
 * «совпало».
 *
 * Исходов ЧЕТЫРЕ, и четвёртый — не про аккуратность типов. `unknown` («сверять
 * нечем») обязан отличаться и от `match`, и от `no-a-record`: по нему карточка
 * молчит, а спутав его с любым из соседей, она либо утверждает про запись,
 * которой не видела (принцип №6 CLAUDE.md), либо обвиняет в расхождении
 * домен, чей DNS мы вообще не читали, — например, в вебе, где чтение DNS
 * десктопное и записей не бывает никогда.
 */
export type OriginCheck =
  /** A-запись apex ведёт на выбранный сервер. */
  | { kind: "match" }
  /** A-запись apex ведёт на другой адрес; `origin` — тот, что стоит в записи. */
  | { kind: "mismatch"; origin: string }
  /** Зону прочитали, A-записи на apex в ней нет (и подменить её нечем). */
  | { kind: "no-a-record" }
  /** Сравнивать не с чем: записей не читали, у сервера нет адреса, apex ведёт CNAME/AAAA. */
  | { kind: "unknown" };

const UNKNOWN: OriginCheck = { kind: "unknown" };

/**
 * Минимум, что нужно от записи DNS. Типом `DnsRecord` модуль намеренно НЕ
 * связан — по тому же правилу, что у `domainDrift`: правило можно проверить,
 * не собирая запись Cloudflare из восьми полей.
 */
export interface ComparableRecord {
  type: string;
  name: string;
  content: string;
}

/**
 * Типы, которые на apex ЗАМЕНЯЮТ собой A-запись: домен куда-то ведёт, но не по
 * адресу, который есть у нас. Сказать про такую зону «A-записи apex нет» —
 * формально верно и по смыслу враньё: человек пойдёт заводить A поверх CNAME,
 * которого Cloudflare рядом не примет.
 */
const A_SUBSTITUTES = new Set(["CNAME", "AAAA"]);

/**
 * Сверить apex домена с адресом сервера.
 *
 * `records === undefined` — записей НЕ ЧИТАЛИ (веб; десктоп до ответа
 * Cloudflare; домен без зоны). Это `unknown`, а не пустая зона: пустой список
 * — это прочитанный ответ, и по нему сказать «A-записи нет» уже можно.
 *
 * `proxied` не смотрим намеренно: за оранжевым облаком Cloudflare меняет то,
 * что отдаёт публичный DNS, а в `content` записи по-прежнему лежит origin —
 * ровно тот адрес, на который поедет запрос от Cloudflare к нашему серверу.
 * Пропусти мы проксированные записи, сверка молчала бы именно на тех доменах,
 * ради которых Cloudflare и подключают.
 *
 * Берётся ПЕРВАЯ A-запись apex, а не любая совпавшая: у round-robin из двух A
 * выбор «той, что сошлась» превращал бы половину трафика, идущего мимо
 * выбранного сервера, в зелёное молчание.
 */
export function domainOriginCheck(
  records: readonly ComparableRecord[] | undefined,
  domainName: string,
  ip: string | null | undefined,
): OriginCheck {
  if (!records) return UNKNOWN;

  const target = (ip ?? "").trim();
  // Адреса нет — сравнивать не с чем. `ip_address` в схеме сервера обязателен,
  // но пустой строкой быть может, и «расхождение с пустотой» было бы
  // утверждением про сервер, а не про DNS.
  if (!target) return UNKNOWN;

  const apexName = normalizeZoneName(domainName);
  // Мусорное имя не должно совпасть с безымянной записью — то же правило, что
  // у `compareServerSites`.
  if (!apexName) return UNKNOWN;

  const apex = records.filter((r) => normalizeZoneName(r.name) === apexName);
  // Регистр типа приводим: Cloudflare отдаёт `A`, но тип едет через две
  // сериализации, и сверка, чувствительная к регистру, молча теряла бы запись.
  const a = apex.find((r) => r.type.trim().toUpperCase() === "A");

  if (!a) {
    if (apex.some((r) => A_SUBSTITUTES.has(r.type.trim().toUpperCase()))) return UNKNOWN;
    return { kind: "no-a-record" };
  }

  const origin = a.content.trim();
  // A-запись с пустым `content` — испорченный ответ, а не адрес: назвав его
  // расхождением, строка карточки печатала бы «ведёт на » без адреса.
  if (!origin) return UNKNOWN;

  return origin === target ? { kind: "match" } : { kind: "mismatch", origin };
}
