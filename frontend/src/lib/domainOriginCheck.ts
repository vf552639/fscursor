import { normalizeZoneName } from "./cfZoneMatch";

/**
 * Куда ведёт apex домена в Cloudflare — и тот ли это сервер, что выбран в
 * карточке домена.
 *
 * Зачем вообще: связка «домен → сервер» в базе — это НАША запись, а не факт.
 * Поменять её в селекте можно за секунду, и сайт от этого никуда не переедет;
 * единственное, что говорит правду о том, куда пойдёт запрос, — A-запись зоны.
 * Поле сервера показывает расхождение подсказкой и выбор при этом не
 * блокирует: назначить домену новый сервер ДО развёртывания — нормальный
 * путь (ради него read-only и отменён), и требовать в этот момент совпадения
 * с DNS значило бы запретить сам сценарий.
 *
 * Отдельным модулем, а не тремя строками в компоненте, по той же причине, что и
 * `serverSites`: нормализация имени — правило про реальные данные (регистр из
 * письма регистратора, завершающая точка FQDN, пробелы из копипасты), и живёт
 * оно один раз в `normalizeZoneName`. Переписанное здесь заново, оно дало бы
 * «расхождение» на верной записи ровно там, где сверка зон и сайтов говорит
 * «совпало».
 *
 * **Исходов четыре, а печатает по ним сегодня один потребитель и только один
 * исход.** Карточка домена (`DomainServerField`) рисует строку ТОЛЬКО на
 * `mismatch` и молчит на всех остальных — в том числе молчит ОДИНАКОВО на
 * `no-a-record` и на `unknown`. Значит, у границы между этими двумя потребителя
 * нет ни одного, и искать его не надо: сверка на карточке сервера
 * (`serverSites`, `compareServerSites`) к DNS не обращается вовсе — она сличает
 * список сайтов FastPanel со строками SDMP и про A-записи не знает ничего.
 *
 * Граница всё равно проведена — заранее, и вот почему. `unknown` — это «мы не
 * смотрели» (веб, где чтение DNS десктопное; непрочитанный ответ; сервер без
 * адреса), а `no-a-record` — прочитанный ответ, в котором A-записи apex нет.
 * Первое утверждать нельзя ничем, второе — можно. Слить их в один исход дешевле
 * сегодня и необратимо завтра: из общего «не знаем» уже не восстановить, читали
 * мы зону или нет, — а на этом и держится разница между диагнозом и молчанием
 * (принцип №6 CLAUDE.md).
 */
export type OriginCheck =
  /** Хотя бы одна A-запись apex ведёт на выбранный сервер. */
  | { kind: "match" }
  /**
   * Ни одна A-запись apex не ведёт на выбранный сервер. `origins` — ВСЕ адреса
   * apex, а не первый попавшийся: см. `domainOriginCheck` про round-robin.
   */
  | { kind: "mismatch"; origins: string[] }
  /** Зону прочитали, A-записи на apex в ней нет (и подменить её нечем). */
  | { kind: "no-a-record" }
  /** Сравнивать не с чем: записей не читали, у сервера нет адреса, apex ведёт CNAME/AAAA. */
  | { kind: "unknown" };

const UNKNOWN: OriginCheck = { kind: "unknown" };

/**
 * Минимум, что нужно от записи DNS. Типом `DnsRecord` модуль намеренно НЕ
 * связан — по тому же правилу, что у `domainDrift`: правило можно проверить,
 * не собирая запись Cloudflare из восьми полей.
 */
export interface ComparableRecord {
  type: string;
  name: string;
  content: string;
}

/**
 * Типы, которые на apex ЗАМЕНЯЮТ собой A-запись: домен куда-то ведёт, но не по
 * адресу, который мы умеем сравнить. Сказать про такую зону «A-записи apex
 * нет» — формально верно и по смыслу враньё: человек пойдёт заводить A поверх
 * CNAME, которого Cloudflare рядом не примет.
 *
 * AAAA здесь НЕ потому, что «у нас адреса только IPv4»: `lib/ipInput` принимает
 * и IPv6, и карточка сервера его сохраняет (`{ ipv6: true }`). Причина другая —
 * сравнивать AAAA с `ip_address` мы сегодня не беремся вовсе: у сервера в
 * колонке один адрес, и совпадение IPv6-записи с ним ничего не говорит о том,
 * куда идёт трафик по A. Молчание (`unknown`) здесь честнее обеих альтернатив.
 */
const A_SUBSTITUTES = new Set(["CNAME", "AAAA"]);

/**
 * Сверить apex домена с адресом сервера.
 *
 * `records === undefined` — записей НЕ ЧИТАЛИ (веб; десктоп до ответа
 * Cloudflare; домен без зоны или без сервера). Это `unknown`, а не пустая зона:
 * пустой список — это прочитанный ответ, и по нему сказать «A-записи нет» уже
 * можно.
 *
 * `proxied` не смотрим намеренно: за оранжевым облаком Cloudflare меняет то,
 * что отдаёт публичный DNS, а в `content` записи по-прежнему лежит origin —
 * ровно тот адрес, на который поедет запрос от Cloudflare к нашему серверу.
 * Пропусти мы проксированные записи, сверка молчала бы именно на тех доменах,
 * ради которых Cloudflare и подключают.
 *
 * **Берутся ВСЕ A-записи apex, а совпадением считается вхождение адреса
 * сервера в их набор.** Прежнее правило «первая A» было дефектом на два фронта.
 * По существу: у round-robin из `9.9.9.9` и `1.2.3.4` при выбранном `1.2.3.4`
 * оно печатало «ведёт не туда» — то есть отправляло чинить ВЕРНУЮ запись,
 * которая там есть. По устойчивости: порядок записей в ответе Cloudflare не
 * гарантирован ничем, и та же зона на следующем чтении могла отдать `1.2.3.4`
 * первым — янтарная строка то появлялась бы, то исчезала без единого изменения
 * в DNS. Мигающий диагноз хуже отсутствующего: после второго раза его перестают
 * читать (принцип №6 CLAUDE.md).
 *
 * Размен у нового правила есть, и он назван, чтобы его не переоткрыли как
 * дефект: наш адрес СРЕДИ чужих — это `match`, то есть молчание, хотя часть
 * трафика при round-robin идёт мимо выбранного сервера. Сказать, какая именно
 * часть, карточка не умеет (доли трафика она не измеряет), а ложное обвинение
 * верной записи стоит дороже несказанного — отсюда выбор. Отдельным исходом
 * «наш адрес не единственный» станет тогда, когда появится, кому его печатать;
 * возврат к «первой A» им не является — он врёт и мигает.
 *
 * По той же причине `origins` СОРТИРУЮТСЯ: строка карточки перечисляет их
 * человеку, и порядок в ней обязан зависеть от содержимого зоны, а не от
 * настроения API. Порядок лексикографический — не числовой: он никого не
 * ранжирует, он только делает вывод воспроизводимым.
 */
export function domainOriginCheck(
  records: readonly ComparableRecord[] | undefined,
  domainName: string,
  ip: string | null | undefined,
): OriginCheck {
  if (!records) return UNKNOWN;

  const target = (ip ?? "").trim();
  // Адреса нет — сравнивать не с чем. `ip_address` в схеме сервера обязателен,
  // но пустой строкой быть может, и «расхождение с пустотой» было бы
  // утверждением про сервер, а не про DNS.
  if (!target) return UNKNOWN;

  const apexName = normalizeZoneName(domainName);
  // Мусорное имя не должно совпасть с безымянной записью — то же правило, что
  // у `compareServerSites`.
  if (!apexName) return UNKNOWN;

  const apex = records.filter((r) => normalizeZoneName(r.name) === apexName);
  // Регистр типа приводим: Cloudflare отдаёт `A`, но тип едет через две
  // сериализации, и сверка, чувствительная к регистру, молча теряла бы запись.
  const aRecords = apex.filter((r) => r.type.trim().toUpperCase() === "A");

  if (aRecords.length === 0) {
    if (apex.some((r) => A_SUBSTITUTES.has(r.type.trim().toUpperCase()))) return UNKNOWN;
    return { kind: "no-a-record" };
  }

  // Дубли схлопываются: две одинаковые A на apex — не два адреса, а один, и в
  // строке карточки он должен быть назван один раз.
  const origins = [...new Set(aRecords.map((r) => r.content.trim()).filter(Boolean))].sort();
  // A-записи есть, но все с пустым `content` — испорченный ответ, а не адрес:
  // назвав его расхождением, строка карточки печатала бы «ведёт на » без адреса.
  if (origins.length === 0) return UNKNOWN;

  return origins.includes(target) ? { kind: "match" } : { kind: "mismatch", origins };
}
