import { describe, expect, it } from "vitest";

import { domainWord } from "./format";

/**
 * Слово «домен» при счётчике.
 *
 * Здесь стояли пять таблиц на русское склонение — «11 доменов» против «21
 * домен», ноль, сотни. Правило ушло вместе с переводом вкладки Domains на
 * английский (фаза 6 плана `2026-08-21-domains-shest-pravok.md`), и таблицы
 * ушли с ним: тест, проверяющий ветку, которой в функции больше нет, — это
 * описание прошлого, выданное за требование.
 *
 * Осталось то, ради чего функция и переживает своё правило: подпись обязана
 * различать единственное число. «1 domains» — опечатка ровно того же сорта, что
 * «1 доменов» до неё, и живёт она так же вечно.
 */

describe("domainWord", () => {
  it("единица — «domain», всё остальное — «domains»", () => {
    expect(domainWord(1)).toBe("domain");
    expect(domainWord(2)).toBe("domains");
    expect(domainWord(11)).toBe("domains");
    expect(domainWord(21)).toBe("domains");
  });

  /**
   * Ноль сюда доезжает: пустую пачку кнопки не отправляют, но подпись
   * загруженности сервера («prod-01 — 0 domains») считается по тому же правилу.
   */
  it("ноль — множественное, а не единственное и не пустая строка", () => {
    expect(domainWord(0)).toBe("domains");
  });
});
