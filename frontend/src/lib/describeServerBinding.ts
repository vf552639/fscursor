import { domainWord } from "./format";

/**
 * Вопрос перед массовой привязкой доменов к серверу — один текст на все места,
 * откуда её запускают.
 *
 * Почему вопрос вообще есть: `server_id` записью МЕНЯЕТСЯ, а сайт при этом
 * никуда не едет, и бэкенд на каждой записи сбрасывает снимок `fp_facts`.
 * Молчаливая привязка означала бы, что домен теряет прочитанные с прежней
 * машины факты (FTP-доступ, пути, PHP) без единого слова — а держать их после
 * переезда нельзя: это доступ к ЧУЖОМУ теперь серверу, показанный как рабочий.
 *
 * Почему отдельным модулем, а не шаблоном по месту: писателей у `server_id`
 * три (карточка домена, панель выделенных, сверка на карточке сервера), и они
 * уже разъехались однажды — панель выделенных писала молча, пока две другие
 * предупреждали. Разъехаться второй раз им теперь нечем: расхождение здесь —
 * это два РАЗНЫХ ответа на один вопрос «что со мной случится», и читатель по
 * ним решает, что случится разное.
 *
 * `moving` считает не весь набор, а тех, кого привязка ПЕРЕВЕЗЁТ: домен без
 * сервера не теряет ничего, домен уже на целевом сервере не двигается вовсе.
 * Назвав ценой операции весь набор, вопрос пугал бы сотней там, где переезжает
 * один, — и его перестали бы читать (принцип №6 CLAUDE.md).
 */
export function describeServerBinding(count: number, moving: number, serverName: string): string {
  const move = moving
    ? ` У ${moving} из них сейчас стоит другой сервер: привязка переедет, а прочитанные с прежней машины факты (FTP-доступ, пути, PHP) будут сброшены.`
    : "";
  return `Привязать ${count} ${domainWord(count)} к ${serverName}?${move}`;
}
