import { describe, it, expect } from "vitest";

import {
  EXPIRY_SOON_DAYS,
  expiryState,
  expiryTextColor,
  expiryTextWeight,
  expiryTs,
  formatExpiry,
  formatExpiryDate,
  parseExpiryInput,
} from "./domainExpiry";

/**
 * Сроки домена и сертификата — чистые функции, и проверяются они отдельно от
 * экранов: одну и ту же лестницу читают колонка Expires, колонка SSL и карточка
 * домена, и уронить её рендером одного из мест значит проверить треть.
 *
 * Проверяется не «функция вернула строку», а правило продукта: незнание срока —
 * отдельное состояние, а не «всё хорошо».
 */

const NOW = new Date("2026-08-11T12:00:00Z").getTime();
const HOUR = 60 * 60 * 1000;
const DAY = 24 * HOUR;

/** ISO-строка на N миллисекунд позже «сейчас» (отрицательное — раньше). */
const at = (ms: number) => new Date(NOW + ms).toISOString();

describe("expiryState", () => {
  it("далёкий срок — «ok», близкий — «soon», прошедший — «expired»", () => {
    expect(expiryState(at(200 * DAY), NOW)).toBe("ok");
    expect(expiryState(at(10 * DAY), NOW)).toBe("soon");
    expect(expiryState(at(-1 * DAY), NOW)).toBe("expired");
  });

  it("даты нет — это «не знаем», а не «ok» и не «expired»", () => {
    // Правило продукта №6: отсутствие измерения — своё состояние. Домен без
    // `expiry_date` не «в порядке» — про него просто ничего не известно.
    expect(expiryState(null, NOW)).toBe("unknown");
    expect(expiryState(undefined, NOW)).toBe("unknown");
    expect(expiryState("", NOW)).toBe("unknown");
  });

  it("нечитаемая дата уравнена с её отсутствием, а не роняет разбор", () => {
    // `new Date("не дата")` → NaN, и любое сравнение с ним ложно: без явной
    // ветки такой домен молча уехал бы в «ok».
    expect(expiryState("not-a-date", NOW)).toBe("unknown");
    expect(expiryState("2026-13-45", NOW)).toBe("unknown");
  });

  it("граница ровно на пороге входит в «soon»", () => {
    // Число пишем вручную, а не берём из константы модуля: сверка константы с
    // самой собой зеленела бы при любом пороге.
    expect(EXPIRY_SOON_DAYS).toBe(30);
    expect(expiryState(at(30 * DAY), NOW)).toBe("soon");
    // На день дальше порога — уже «ok»…
    expect(expiryState(at(31 * DAY), NOW)).toBe("ok");
    // …а неполные сутки сверх порога остатка не добавляют: округляем вниз,
    // потому что раннее предупреждение дешевле пропущенного.
    expect(expiryState(at(30 * DAY + 20 * HOUR), NOW)).toBe("soon");
  });

  it("день самого срока — уже «expired», а не «остался ноль дней»", () => {
    // У `expiry_date` (тип `date`) времени нет: к обеду того же дня остаток
    // отрицателен. Занижаем намеренно — подпись при этом честно скажет
    // «expired today», а не выдумает давность.
    expect(expiryState(at(-1 * HOUR), NOW)).toBe("expired");
    expect(formatExpiry(at(-1 * HOUR), NOW)).toBe("expired today");
  });
});

describe("formatExpiry", () => {
  it("будущее считает днями, а первые неполные сутки называет своим именем", () => {
    expect(formatExpiry(at(12 * DAY), NOW)).toBe("in 12 days");
    expect(formatExpiry(at(1 * DAY), NOW)).toBe("in 1 day");
    expect(formatExpiry(at(5 * HOUR), NOW)).toBe("in <1 day");
  });

  it("прошедшее считает днями назад", () => {
    expect(formatExpiry(at(-3 * DAY - HOUR), NOW)).toBe("expired 3 days ago");
    expect(formatExpiry(at(-1 * DAY - HOUR), NOW)).toBe("expired 1 day ago");
  });

  it("ровные сутки назад называет своим числом, а не вчерашним", () => {
    // ЕДИНСТВЕННАЯ точка, где прежняя формула (`-daysLeft - 1`) расходилась с
    // нынешней: целое число суток. На дробной давности обе дают одно и то же,
    // поэтому ошибка и не попадалась — соседние тесты берут смещения с часом
    // сверху и границу обходят. Здесь она берётся в упор с обеих сторон.
    expect(formatExpiry(at(-1 * DAY), NOW)).toBe("expired 1 day ago");
    expect(formatExpiry(at(-3 * DAY), NOW)).toBe("expired 3 days ago");
    // А вот сутки ещё не прошли — это «сегодня», и здесь единицы быть не должно.
    expect(formatExpiry(at(-23 * HOUR), NOW)).toBe("expired today");
  });

  it("неизвестный срок подписывает прочерком, а не пустотой", () => {
    // Пустая строка превратилась бы в пустую ячейку, а пустая ячейка читается
    // как «всё хорошо».
    expect(formatExpiry(null, NOW)).toBe("—");
    expect(formatExpiry("not-a-date", NOW)).toBe("—");
  });
});

/**
 * `expiry_date` приезжает с бэкенда РОВНО в этом виде — `Optional[date]`, то
 * есть строка «2026-09-01» без времени и без зоны. До этого блока весь модуль
 * проверялся полными ISO-датами (`at()`), то есть единственная форма, в которой
 * поле вообще существует в проде, не проверялась ничем — и сдвиг даты на день
 * западнее UTC прошёл мимо зелёной сюиты именно так.
 */
describe("дата без времени — это весь день", () => {
  // Полдень UTC 1 сентября: домен со сроком «1 сентября» в этот момент ЖИВ.
  const NOON_SEP_1 = new Date("2026-09-01T12:00:00Z").getTime();

  it("в день своего срока домен ещё не просрочен", () => {
    // Срок такой даты — конец дня, а не его начало: у регистратора «expiry
    // date: 1 сентября» значит, что первого числа домен работает. Красное
    // «expired today» на живом домене зовёт продлевать то, что не истекло.
    expect(expiryState("2026-09-01", NOON_SEP_1)).toBe("soon");
    expect(formatExpiry("2026-09-01", NOON_SEP_1)).toBe("in <1 day");
  });

  it("просрочка начинается со следующих суток", () => {
    const noonSep2 = new Date("2026-09-02T12:00:00Z").getTime();
    expect(expiryState("2026-09-01", noonSep2)).toBe("expired");
    expect(formatExpiry("2026-09-01", noonSep2)).toBe("expired today");
  });

  it("остаток считается от конца дня", () => {
    expect(formatExpiry("2026-09-11", NOON_SEP_1)).toBe("in 10 days");
    // Порог в 30 суток от полудня 1 сентября приходится на конец 1 октября.
    expect(expiryState("2026-10-01", NOON_SEP_1)).toBe("soon");
    expect(expiryState("2026-10-02", NOON_SEP_1)).toBe("ok");
  });

  it("печатается в UTC, а не в зоне читателя — в ЛЮБОЙ зоне", () => {
    // `new Date("2026-09-01")` — полночь UTC, и `toLocaleDateString` без зоны
    // переводит её в зону читателя: западнее UTC (Нью-Йорк, Гонолулу) выходило
    // «31.08.2026» — дата, которой у домена нет.
    //
    // Зона тут НЕ подменяется намеренно: `formatExpiryDate` прибивает
    // `timeZone: "UTC"` для date-only, поэтому ответ от зоны не зависит вовсе, и
    // подмена охраняла бы не поведение, а саму себя. Зона, в которой ошибка
    // видна, задаётся там, где она и нужна, — в тесте страницы
    // (`pages/Domains.expiry.test.tsx`), и там же стоит контроль, что подмена
    // сработала.
    expect(formatExpiryDate("2026-09-01")).toBe("01.09.2026");
  });

  it("а вот у datetime печать идёт в зоне читателя — и это тоже правило", () => {
    // Асимметрия сознательная: у `date` мгновения нет вовсе, у `datetime` есть,
    // и «когда у МЕНЯ истекает сертификат» — правильный ответ. Здесь подмена
    // зоны решает всё: тот же момент в Нью-Йорке приходится на предыдущий день.
    const tz = process.env.TZ;
    try {
      process.env.TZ = "America/New_York";
      expect(formatExpiryDate("2026-09-01T02:00:00Z")).toBe("31.08.2026");
      process.env.TZ = "UTC";
      expect(formatExpiryDate("2026-09-01T02:00:00Z")).toBe("01.09.2026");
    } finally {
      // Именно `delete`, а не присваивание: обычно `TZ` не задан вовсе, и
      // `process.env.TZ = undefined` записал бы туда СТРОКУ «undefined» —
      // зону, которой нет, после чего Node молча считает время в UTC. Так
      // тест уносил бы с собой чужую зону во все следующие в этом воркере.
      if (tz === undefined) delete process.env.TZ;
      else process.env.TZ = tz;
    }
  });

  it("у полноценного datetime мгновение настоящее, и сдвигать его нечем", () => {
    // Сертификат истекает в известную секунду — прибавить ему день значило бы
    // выдумать сутки, которых у сертификата нет.
    const t = new Date("2026-09-01T00:00:00Z");
    expect(expiryTs(t.toISOString())).toBe(t.getTime());
    expect(expiryTs("2026-09-01")).toBe(t.getTime() + DAY);
  });
});

describe("expiryTs", () => {
  it("нечитаемый и отсутствующий срок отдаёт одним `null`, а не NaN", () => {
    // На этом значении держится сортировка: `NaN` в компараторе ложен во всех
    // сравнениях сразу, и одна битая дата сделала бы произвольным весь порядок,
    // а не только своё место в нём.
    expect(expiryTs("not-a-date")).toBeNull();
    expect(expiryTs(null)).toBeNull();
    expect(expiryTs(undefined)).toBeNull();
    expect(expiryTs("2026-08-11T12:00:00Z")).toBe(NOW);
  });
});

describe("expiryTextColor", () => {
  it("тревожные состояния красит, спокойные — нет", () => {
    // Хексы — палитры макета, и держатся тут ЯВНО, а не сверкой с
    // `designTokens`: сверка с источником проходила бы при любом значении и
    // охраняла бы только то, что функция вообще что-то вернула. Правило же,
    // ради которого она написана, — про соотношение четырёх цветов между
    // собой, и его надо назвать вслух.
    expect(expiryTextColor("expired")).toBe("#b91c1c");
    // Янтарный, а НЕ красный — осознанное отступление от макета: макет красит
    // красным всё, до чего меньше тридцати дней, сливая «истёк» и «скоро
    // истечёт» в одно пятно. Слив их, красный перестал бы значить «поздно».
    expect(expiryTextColor("soon")).toBe("#b45309");
    // «Далеко» не зелёное: это отсутствие повода, а не достижение, — иначе
    // жёлтое и красное потерялись бы в зелёном ряду на сотню строк.
    expect(expiryTextColor("ok")).toBe("#0f172a");
    // А «не знаем» — самое бледное: тем же тоном на странице нарисованы
    // прочерки и выключенные действия.
    expect(expiryTextColor("unknown")).toBe("#cbd5e1");
  });

  it("те же состояния выделяет и начертанием — цвет не единственный канал", () => {
    // Второй канал нужен тем, кто цвет не различает; и он обязан совпадать с
    // цветом состояние в состояние, иначе строка спорит сама с собой.
    expect(expiryTextWeight("expired")).toBe(600);
    expect(expiryTextWeight("soon")).toBe(600);
    expect(expiryTextWeight("ok")).toBe(400);
    expect(expiryTextWeight("unknown")).toBe(400);
  });
});

/**
 * Разбор строки, набранной руками.
 *
 * Нативный `<input type="date">` ушёл из проекта: в WKWebView десктопа он не
 * принимал ввод с клавиатуры вовсе — цифры не вставали в сегменты. Значит форму
 * даты читает теперь не браузер, а этот модуль, и он же её печатает. Отсюда и
 * главное правило пары, которое проверяется первым: круг замкнут — что модуль
 * показал, то он обязан принять обратно.
 */
describe("parseExpiryInput", () => {
  /** Выполнить проверки в чужой зоне и вернуть зону на место. */
  const withTZ = (tz: string, check: () => void) => {
    const prev = process.env.TZ;
    try {
      process.env.TZ = tz;
      check();
    } finally {
      // Именно `delete`, а не присваивание `undefined`: строка «undefined» —
      // это зона, которой нет, и Node после неё молча считает в UTC, унося
      // чужое время во все следующие тесты воркера (та же ловушка, что выше).
      if (prev === undefined) delete process.env.TZ;
      else process.env.TZ = prev;
    }
  };

  it("читает обратно ровно то, что печатает сам модуль", () => {
    // Печать и разбор — одно решение, а не два, и живут они в одном файле
    // именно поэтому. Разъехавшись, эти двое дают поле, которое краснеет на
    // собственной подписи, а виноватым при этом выглядит человек.
    const iso = "2026-09-01";
    expect(formatExpiryDate(iso)).toBe("01.09.2026");
    expect(parseExpiryInput(formatExpiryDate(iso))).toEqual({ kind: "parsed", iso });
  });

  it("принимает две привычные записи сверх своей", () => {
    // Слэши приходят из письма регистратора, ISO — из консоли и из самого
    // бэкенда. Оба разделителя читаются ДЕНЬ-ПЕРВЫМ: продукт печатает ru-RU, и
    // прочитанное по-американски `09/01/2026` стало бы 1 сентября вместо
    // 9 января — два ответа на одну строку, причём молча.
    expect(parseExpiryInput("09/01/2026")).toEqual({ kind: "parsed", iso: "2026-01-09" });
    expect(parseExpiryInput("2026-09-01")).toEqual({ kind: "parsed", iso: "2026-09-01" });
  });

  it("пробелы по краям срезает — такую строку чаще вставляют, чем набирают", () => {
    expect(parseExpiryInput("  01.09.2026  ")).toEqual({ kind: "parsed", iso: "2026-09-01" });
    expect(parseExpiryInput("\t01.09.2026\n")).toEqual({ kind: "parsed", iso: "2026-09-01" });
  });

  it("пустая строка — это «срока нет», а не ошибка", () => {
    // Третий исход, а не ошибка и не `null`: очищенное поле — единственный
    // способ снять ошибочно введённый срок. Уравняв пустоту с непонятной
    // записью, продукт запер бы дату, которую сам же и записал.
    expect(parseExpiryInput("")).toEqual({ kind: "empty" });
    // Пробелы — то же самое: так выглядит очистка поля, сделанная руками.
    expect(parseExpiryInput("   ")).toEqual({ kind: "empty" });
  });

  it("двузначный год отвергает, а не угадывает век", () => {
    // `01.09.26` — это 2026-й или 1926-й? Угадав, продукт молча запишет домену
    // срок, которого человек не называл; отказавшись — попросит дописать две
    // цифры. Явный отказ здесь дешевле молчаливой догадки.
    expect(parseExpiryInput("01.09.26")).toEqual({ kind: "error", error: "format" });
  });

  it("непонятную запись называет ошибкой формата и даты из неё не выдумывает", () => {
    expect(parseExpiryInput("not a date")).toEqual({ kind: "error", error: "format" });
    expect(parseExpiryInput("01.09")).toEqual({ kind: "error", error: "format" });
    expect(parseExpiryInput("01.09.2026 12:00")).toEqual({ kind: "error", error: "format" });
    // Разделитель обязан быть одним на всю строку: `01.09/2026` — это, скорее
    // всего, недоправленная строка, а не намерение.
    expect(parseExpiryInput("01.09/2026")).toEqual({ kind: "error", error: "format" });
    // Однозначные день и месяц тоже мимо: принимаем ровно то, что печатаем, и
    // ровно то, что обещает placeholder поля. Узость сознательная — расширить
    // приём потом дёшево, сузить однажды принятое нельзя.
    expect(parseExpiryInput("1.9.2026")).toEqual({ kind: "error", error: "format" });
  });

  it("несуществующую дату отличает от непонятной записи", () => {
    // 31 февраля набирается ровно так же легко, как 31 марта, и запись у него
    // безупречная. Ошибка тут другая по сути, и назвать её надо иначе: править
    // человеку не форму, а само число.
    expect(parseExpiryInput("31.02.2026")).toEqual({ kind: "error", error: "date" });
    expect(parseExpiryInput("29.02.2026")).toEqual({ kind: "error", error: "date" });
    expect(parseExpiryInput("31.04.2026")).toEqual({ kind: "error", error: "date" });
    // Нулевой день и тринадцатый месяц — та же ошибка: запись читается, даты нет.
    expect(parseExpiryInput("00.09.2026")).toEqual({ kind: "error", error: "date" });
    expect(parseExpiryInput("01.13.2026")).toEqual({ kind: "error", error: "date" });
    // ISO-запись проверяется тем же календарём, а не только своей регуляркой.
    expect(parseExpiryInput("2026-02-31")).toEqual({ kind: "error", error: "date" });
  });

  it("високосный день пропускает, включая оговорку про 400 лет", () => {
    // Сверка идёт обратным преобразованием (собрали UTC-дату из чисел, прочли
    // из неё год, месяц и день обратно), а не таблицей длин месяцев: таблице
    // нужен второй календарь с правилом високосности, и ошибается он редко и
    // молча. 1900-й — не високосный, 2000-й — високосный, и это ровно та пара,
    // на которой рукописные правила и спотыкаются.
    expect(parseExpiryInput("29.02.2024")).toEqual({ kind: "parsed", iso: "2024-02-29" });
    expect(parseExpiryInput("29.02.2000")).toEqual({ kind: "parsed", iso: "2000-02-29" });
    expect(parseExpiryInput("29.02.1900")).toEqual({ kind: "error", error: "date" });
  });

  it("не сдвигает дату на сутки ни в одной зоне — по обе стороны от UTC", () => {
    // Границы года взяты не для красоты: сдвиг на сутки внутри месяца читается
    // как описка в тесте, а на 1 января и 31 декабря он меняет ГОД — и спорить
    // с таким ответом не приходится.
    //
    // Зона подменяется в обе стороны, потому что наивных реализаций две, и
    // ломаются они в разных полушариях: `new Date(y, m-1, d).toISOString()`
    // (локальная полночь) уезжает восточнее UTC, а печать UTC-даты в локальной
    // зоне — западнее. Машина разработчика стоит в UTC+3, и одностороннюю
    // проверку она прошла бы, не заметив ни того ни другого.
    withTZ("Pacific/Kiritimati", () => {
      // Контроль: подмена зоны ДЕЙСТВИТЕЛЬНО случилась — иначе тест зеленел бы
      // сам собой. Заодно это и есть та наивная строка, которой сдвиг заводится:
      // в UTC+14 местная полночь 1 января приходится на 31 декабря по UTC.
      expect(new Date(2026, 0, 1).toISOString().slice(0, 10)).toBe("2025-12-31");
      expect(parseExpiryInput("01.01.2026")).toEqual({ kind: "parsed", iso: "2026-01-01" });
      expect(parseExpiryInput("31.12.2026")).toEqual({ kind: "parsed", iso: "2026-12-31" });
    });
    withTZ("Pacific/Honolulu", () => {
      // Тот же контроль с другой стороны: в UTC−10 полночь 31 декабря по UTC —
      // это ещё 30-е число на месте.
      expect(new Date(Date.UTC(2026, 11, 31)).getDate()).toBe(30);
      expect(parseExpiryInput("01.01.2026")).toEqual({ kind: "parsed", iso: "2026-01-01" });
      expect(parseExpiryInput("31.12.2026")).toEqual({ kind: "parsed", iso: "2026-12-31" });
    });
  });

  it("разобранная дата ложится в модуль как есть — без второго разбора по дороге", () => {
    // Итог разбора уходит на сервер и возвращается в колонку списка тем же
    // полем. Значит форма обязана совпасть с той, которую модуль считает
    // date-only: иначе `expiryTs` перестанет прибавлять сутки, и день своего
    // срока домен встретит красным «expired today», будучи живым.
    const result = parseExpiryInput("01.09.2026");
    expect(result.kind).toBe("parsed");
    if (result.kind !== "parsed") return;
    expect(formatExpiryDate(result.iso)).toBe("01.09.2026");
    expect(expiryTs(result.iso)).toBe(new Date("2026-09-02T00:00:00Z").getTime());
  });

  it("год вне досягаемости продукта — это описка, а не дата", () => {
    // `0226` вместо `2026` — обычная перестановка при наборе, и раньше она
    // проходила молча: запись читаемая, дата в календаре существует. На сервер
    // уезжал III век, колонка красила домен красным «expired», а ИСПРАВИТЬ
    // значение на месте было нельзя — модуль печатал `01.09.226` и сам же
    // отказывался принять эту строку обратно.
    expect(parseExpiryInput("01.09.0226")).toEqual({ kind: "error", error: "date" });
    expect(parseExpiryInput("01.09.0026")).toEqual({ kind: "error", error: "date" });
    expect(parseExpiryInput("01.09.9999")).toEqual({ kind: "error", error: "date" });
    // ISO-запись проверяется тем же правилом: вход другой, дата одна.
    expect(parseExpiryInput("0226-09-01")).toEqual({ kind: "error", error: "date" });
    // Ошибка именно `date`, а не `format`: запись человек составил верно,
    // поправить ему надо число — и подпись поля обязана позвать его туда.
  });

  it("границы правдоподобного года названы вслух — по обе стороны", () => {
    // Границы держатся в тесте ЧИСЛАМИ, а не сверкой с константами модуля:
    // сверка зеленела бы при любом диапазоне, включая съехавший.
    expect(parseExpiryInput("01.01.1970")).toEqual({ kind: "parsed", iso: "1970-01-01" });
    expect(parseExpiryInput("31.12.1969")).toEqual({ kind: "error", error: "date" });
    expect(parseExpiryInput("31.12.2100")).toEqual({ kind: "parsed", iso: "2100-12-31" });
    expect(parseExpiryInput("01.01.2101")).toEqual({ kind: "error", error: "date" });
  });

  it("что модуль принял, то он печатает строкой, которую примет обратно", () => {
    // Правило круга целиком: исходов у входа ровно два — отказ либо замкнутый
    // круг. Третьего («принял, а прочесть обратно не смог») быть не должно, и
    // проверяется это не на удобных примерах, а вместе с описками года, где
    // круг и рвался.
    const probes = [
      "01.09.2026",
      "2026-09-01",
      "01.01.1970",
      "31.12.2100",
      "29.02.2024",
      "01.09.0226",
      "01.09.0026",
      "01.09.9999",
    ];
    const accepted = probes.flatMap((probe) => {
      const parsed = parseExpiryInput(probe);
      return parsed.kind === "parsed" ? [parsed.iso] : [];
    });
    // Контроль от пустой проверки: правило «отказ либо круг» зеленело бы и на
    // функции, которая отказывает всем подряд. Поэтому список принятого назван
    // поимённо — видно и что прошло, и что отвергнуто.
    expect(accepted).toEqual([
      "2026-09-01",
      "2026-09-01",
      "1970-01-01",
      "2100-12-31",
      "2024-02-29",
    ]);
    for (const iso of accepted) {
      expect(parseExpiryInput(formatExpiryDate(iso))).toEqual({ kind: "parsed", iso });
    }
  });
});
