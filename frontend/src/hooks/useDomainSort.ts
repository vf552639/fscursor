import { useMemo, useState } from "react";

import { DEFAULT_SORT, Sort, SortKey, sortDomains } from "../components/domains/sortDomains";
import { DomainUI } from "../components/domains/types";

/**
 * Выбранный пользователем порядок строк и применение его к списку.
 *
 * Живёт НАД таблицей, а не внутри неё, и это не вкусовщина. Страница подменяет
 * таблицу целиком в трёх ветках: ошибка загрузки, ожидание запросов и «доменов
 * нет вовсе». Стейт внутри таблицы каждую такую подмену не переживает, а первая
 * из них наступает без всякого действия пользователя: react-query держит
 * прежние `data` и переводит `status` в `error`, когда фоновый рефетч исчерпал
 * ретраи, — то есть сетевая икота на открытой странице показывает
 * `DomainsLoadError`, а после восстановления выбранная колонка молча оказалась
 * бы снова «Domain ↑». Тот же сброс виден, если удалить последний домен и
 * завести новый.
 *
 * Таблица от этого остаётся презентационной: получает готовый порядок и ключ,
 * по которому рисует стрелку.
 */
export function useDomainSort(rows: DomainUI[], now: number): {
  sort: Sort;
  onSort: (k: SortKey) => void;
  sorted: DomainUI[];
} {
  const [sort, setSort] = useState<Sort>(DEFAULT_SORT);
  /** Повторный клик по той же колонке переворачивает; новая колонка начинает с возрастания. */
  const onSort = (k: SortKey) => setSort((p) => ({ key: k, dir: p.key === k && p.dir === "asc" ? "desc" : "asc" }));
  /**
   * Порядок применяется ПОСЛЕ фильтрации и живёт в `useMemo`: список бывает на
   * сотни строк, а сортировка внутри рендера строки означала бы полную
   * пересортировку на каждую из них.
   *
   * Фокус-режим (`ctx.domainId`) сюда не вмешивается — он всего лишь ещё одно
   * условие фильтра страницы, поэтому сортировку не ломает: единственная
   * оставшаяся строка отсортирована сама с собой.
   *
   * `now` — то же «сейчас», что уезжает в строки (`useNow`), и оно же в
   * зависимостях: колонка SSL сортируется по состоянию, которое ПРОТУХАЕТ, то
   * есть порядок обязан стареть вместе с подписями. Тик — раз в минуту, и
   * пересортировка сотни строк на нём дешевле, чем колонка, показывающая «Not
   * checked» на месте, доставшемся ей от «Valid» час назад.
   */
  const sorted = useMemo(() => sortDomains(rows, sort, now), [rows, sort, now]);

  return { sort, onSort, sorted };
}
