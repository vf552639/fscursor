import { useCallback, useState } from "react";

/**
 * Очередь того, что показывается ровно один раз: пароли БД и FTP после
 * provision, пароль панели после install_fastpanel.
 *
 * Почему очередь, а не один слот. Обе операции идут минутами (SSH, certbot,
 * инсталлятор) и запускаются по разным целям параллельно — гейты в UI
 * подоменные и посерверные, а не глобальные. Одноместный слот означал бы, что
 * второй результат затирает первый молча: пользователь читает пароли `a.com`,
 * приходит результат `b.com`, и модалка на глазах превращается в чужую. Взять
 * затёртые пароли негде — сервер их не знает по определению (zero-knowledge),
 * в кэш мутаций они не попадают намеренно, а FTP-аккаунт и БД на сервере уже
 * созданы.
 *
 * Показывается голова очереди; `dismiss` — это «я записал, следующий».
 *
 * `push` и `dismiss` стабильны по идентичности: `push` уезжает пропом в
 * страницу и оседает в замыкании `mutationFn`, которое переживает
 * размонтирование этой страницы.
 */
export interface ShowOnceQueue<T> {
  /** Голова очереди — то, что показывается сейчас. `null` = показывать нечего. */
  current: T | null;
  push: (item: T) => void;
  /** Убрать показанное и открыть следующее. На пустой очереди — no-op. */
  dismiss: () => void;
}

export function useShowOnceQueue<T>(): ShowOnceQueue<T> {
  const [items, setItems] = useState<T[]>([]);
  // Функциональные апдейты, а не `[...items, item]`: два результата, пришедшие
  // в одном тике (или из замыканий разных рендеров), иначе схлопнулись бы в
  // один — ровно та потеря, ради которой заведена очередь.
  const push = useCallback((item: T) => setItems((q) => [...q, item]), []);
  const dismiss = useCallback(() => setItems((q) => q.slice(1)), []);
  return { current: items.length > 0 ? items[0] : null, push, dismiss };
}
