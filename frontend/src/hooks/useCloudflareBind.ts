import { useState, useRef } from "react";

import { runExclusive, useRunPending } from "../api/runGate";
import { Domain } from "../api/domains";
import { autoBindDomainsToCloudflare, summarizeCfBind, summarizeCfBindFailure, CfBindNotice } from "../api/cfAutoBind";
import { useLiveOrAway } from "./useLiveOrAway";

/**
 * Откуда пришёл прогон: `auto` — после создания доменов, `manual` — по кнопке
 * синхрона (их две: по всему списку в шапке вкладки и по выделенным в тулбаре
 * — одно действие с разной областью). Разница в громкости отчёта и в гейте
 * (см. `run`).
 */
export type CfBindMode = "auto" | "manual";

/**
 * Ключ заявки «идёт привязка ПО КНОПКЕ» в `MutationCache`. Сам приём — общий,
 * он же держит гейт полной настройки (`api/runGate.ts`); здесь остаётся только
 * ключ и решение, кого им гасить.
 *
 * Записи привязки идемпотентны, поэтому второй проход не портил данные — но
 * пользователь получал два отчёта на одно действие и не мог понять, какой из
 * них про что.
 *
 * НЕ экспортируется, в отличие от симметричного `PROVISION_DOMAIN_KEY`: тот
 * читают снаружи трое — страница гасит им кнопку `Provision` на вкладке Server
 * карточки домена и кнопку массового прогона в тулбаре, а `runProvisionDomain`
 * и `runBulkProvisionDomains` тот же ключ занимают, — а этот и занимают, и
 * спрашивают только здесь. Экспорт обещал бы внешний контракт, которого нет, —
 * и первый, кто в него поверит, разведёт второе место, решающее «идёт ли
 * привязка».
 */
const CF_BIND_KEY = ["cloudflare-bind"] as const;

export interface CloudflareBind {
  /** Итог последнего прогона для баннера страницы; `null` — баннера нет. */
  notice: CfBindNotice | null;
  /** Погасить баннер по кнопке ✕. */
  dismiss: () => void;
  /**
   * Идёт ли прогон по кнопке — то есть надо ли гасить кнопки синхрона. Их две
   * и живут они в разных компонентах (шапка и тулбар), а признак один: прогон
   * у них общий, и погасшая половина означала бы, что второй вход в то же
   * действие остался живым.
   */
  pending: boolean;
  /** Запустить привязку. Ничего не бросает наружу. */
  run: (rows: Domain[], mode: CfBindMode) => Promise<void>;
}

/**
 * Привязка доменов к зонам Cloudflare: прогон, его гейт и итог в одном месте.
 *
 * `onAway` — куда отдать итог, если страницы к моменту его появления уже нет
 * (тост воркспейса). Развилка — в `deliver` ниже.
 */
export function useCloudflareBind(onAway: (notice: CfBindNotice) => void): CloudflareBind {
  /**
   * Итог привязки доменов к зонам Cloudflare — и почему его основное место
   * на СТРАНИЦЕ, а не наверху, как у результатов provision.
   *
   * Provision показывается воркспейсом всегда, потому что несёт пароли, которых
   * нет больше нигде: потерянный пароль невосстановим. У привязки секретов в
   * отчёте нет вовсе, а повторить прогон можно тем же кликом — правило
   * идемпотентно, уже привязанные домены оно пропускает. Поэтому основная
   * поверхность у неё на самой вкладке: итог называет домены ЭТОГО списка, и
   * показывать его поверх страницы серверов не о чем. Тост вдобавок живёт
   * 2200 мс, а в итоге до пяти чисел плюс оговорка про непрочитанные аккаунты —
   * та часть, которую пропустить нельзя. Место у баннера то же, где страница уже
   * показывает исход массового действия (см. `useBulkProvision`).
   *
   * «Основная», а не единственная: если страницы к возврату отчёта уже нет,
   * итог уезжает наверх тостом — см. `deliver`.
   */
  const [notice, setNotice] = useState<CfBindNotice | null>(null);
  /**
   * Чей отчёт сейчас в баннере. Нужен ровно для одного правила: фоновая
   * автопривязка не затирает отчёт, которого пользователь дождался, нажав
   * кнопку (см. `deliver`). Реф, а не стейт: значение читается в
   * колбэке завершившегося прогона и само по себе ничего не рисует.
   */
  const bannerOwnerRef = useRef<CfBindMode | null>(null);
  const { isLive } = useLiveOrAway();
  /**
   * Идёт ли прогон по кнопке — из `MutationCache`, а не из `useState`: см.
   * `CF_BIND_KEY`. Кнопка гаснет и после возврата на страницу, пока прогон,
   * запущенный прошлым экземпляром, ещё идёт.
   */
  const pending = useRunPending(CF_BIND_KEY);

  /**
   * Куда положить итог привязки: в баннер страницы, а если он недоступен —
   * наверх, тостом воркспейса.
   *
   * Недоступен он в двух случаях, и оба реальны.
   *
   * 1. Страницы больше нет. «Прогон секундный» — это про один домен, а не про
   *    пачку: на двухстах доменах это последовательная вычитка зон каждого
   *    аккаунта (с пагинацией и ретраем) плюс двести `PUT` по четыре за раз, то
   *    есть десятки секунд. Уйти за это время со страницы — обычное дело, а
   *    размонтированный компонент съел бы отчёт молча. Молчание здесь хуже
   *    всего: привязка меняет данные НЕ спросив, и след о ней — единственное,
   *    чем это отличается от правки за спиной у пользователя.
   * 2. Место занято отчётом, который пользователь заказывал САМ. Прогонов бывает
   *    два сразу: автопривязка после bulk-add идёт десятки секунд, и клик по
   *    «Синхронизировать» посреди неё финиширует раньше. Затерев отчёт
   *    кнопки отчётом фоновой привязки, страница ответила бы не на тот вопрос,
   *    который ей задали, — и человек, дождавшийся своего отчёта, увидел бы
   *    вместо него чужие числа.
   *
   * Развилка та же, что у `onBulkProvisionError`. Тост беднее баннера (2200 мс
   * на пять чисел), но несравнимо лучше тишины.
   */
  const deliver = (next: CfBindNotice, mode: CfBindMode) => {
    const bannerTaken = mode === "auto" && bannerOwnerRef.current === "manual";
    if (isLive() && !bannerTaken) {
      bannerOwnerRef.current = mode;
      setNotice(next);
    } else {
      onAway(next);
    }
  };

  /** Забыть, кому принадлежит баннер, вместе с самим баннером. */
  const dismiss = () => {
    bannerOwnerRef.current = null;
    setNotice(null);
  };

  /**
   * Тело прогона — общее для обоих входов. Ничего не бросает наружу: провал
   * привязки — это отдельная строка сообщения, а не провал создания домена.
   * Домен к этому моменту уже создан.
   */
  const bind = async (rows: Domain[], mode: CfBindMode) => {
    // Гасим ПРЕЖНИЙ итог сразу, а не по приходу нового: у нового его может не
    // быть вовсе. `auto` молчит, когда менять оказалось нечего, — то есть после
    // «Cloudflare: 2 of 3 linked» пользователь заводит домен с уже выбранным
    // аккаунтом, привязывать нечего, а старая строка остаётся стоять и читается
    // как отчёт об этом, последнем действии.
    //
    // Но отчёт, которого дождались по кнопке, фоновая привязка не гасит — по
    // той же причине, по которой не затирает его на финише (`deliver`): иначе
    // «12 of 50 linked» исчезало бы от заведения одного домена, и на этом пути
    // даже без тоста — промолчавший прогон наверх ничего не отдаёт. Своё же
    // гасит любой прогон: заказал новое — читаешь новое.
    if (mode === "manual" || bannerOwnerRef.current !== "manual") dismiss();
    try {
      const summary = summarizeCfBind(await autoBindDomainsToCloudflare(rows), mode);
      if (summary) deliver(summary, mode);
    } catch (e) {
      // Сюда доходит только провал чтения СПИСКА аккаунтов: непрочитанный
      // аккаунт и несостоявшийся `PUT` — это строки отчёта, а не исключение.
      // Текст собирает тот же модуль, что и текст удачного прогона: он у
      // привязки весь должен быть проверяем без DOM, а чужая ошибка — обрезана
      // (`e.to_string()` через прокси `api_request` в пределе тело ответа).
      deliver(summarizeCfBindFailure(e), mode);
    }
  };

  /**
   * Прогон привязки к зонам Cloudflare: и автоматический (после создания
   * домена), и по кнопке синхрона — из шапки вкладки по всему списку либо из
   * тулбара по выделенным.
   *
   * Один вход на все три случая намеренно — правило привязки одно, и разница
   * между ними ровно в `mode`: после создания домена молчим, когда прогона не было
   * (аккаунтов нет — это не новость тому, кто Cloudflare не пользуется), а по
   * кнопке отвечаем всегда. Всё остальное решает `summarizeCfBind`.
   *
   * Гейт «один прогон за раз» стоит ТОЛЬКО у кнопок, и это не асимметрия ради
   * асимметрии. Он существует, чтобы второй клик не запускал второй проход —
   * и общий на обе кнопки, потому что действие за ними одно: синхрон по всему
   * списку поверх синхрона по выделенным читал бы те же зоны второй раз.
   * Распространив же гейт на автопривязку, мы получили бы худшее из
   * возможного — домен, заведённый во время прогона по кнопке, молча остался бы
   * непривязанным, то есть ровно тем «доменом, которому нечем прописать NS»,
   * ради которого функция и сделана. Параллельные прогоны безопасны: зоны они
   * делят одной записью кэша (`fetchQuery` схлопывает одинаковые запросы), а
   * `PUT` привязки идемпотентен.
   *
   * Два клика в одном такте гейт останавливает потому, что спрашивает КЭШ, а не
   * отрендеренный `pending` (см. `runExclusive`): иначе зоны читались бы
   * дважды, а `PUT`'ы уходили бы парами. Бросить внутри `bind` может только
   * сама доставка — `onAway` чужой проп, — и отказ там гейту уже не вредит:
   * заявка снята в любом исходе.
   */
  const run = async (rows: Domain[], mode: CfBindMode) => {
    if (mode !== "manual") {
      await bind(rows, mode);
      return;
    }
    await runExclusive(CF_BIND_KEY, () => bind(rows, mode));
  };

  return { notice, dismiss, pending, run };
}
