import { useEffect, useState } from "react";

/**
 * Как часто экран перечитывает часы. Минута — шаг, мельче которого ни одна
 * подпись не отличима: и возраст проверки, и остаток срока считаются сутками и
 * часами.
 */
const CLOCK_TICK_MS = 60_000;

/**
 * Одно «сейчас» на все ячейки экрана.
 *
 * Зачем одно: отдельный `Date.now()` внутри каждой функции даёт разные
 * «сейчас» для статуса сервера и для подписи его возраста в соседней строке —
 * тот же приём применён на трёх остальных экранах.
 *
 * Зачем по таймеру, а не на каждый рендер, — и это не микрооптимизация:
 * значение уезжает пропсом в каждую строку списка, а меняясь от любого нажатия
 * клавиши в поиске, оно делает мемоизацию строки невозможной ПО ПОСТРОЕНИЮ —
 * двести строк перерисовывались бы на букву. Тик вдобавок честнее: подписи
 * «checked 2h ago» и «in 3 days» обязаны стареть сами, а не ждать, пока
 * что-нибудь на странице случайно вызовет рендер.
 */
export function useNow(): number {
  const [now, setNow] = useState(() => Date.now());
  useEffect(() => {
    const id = setInterval(() => setNow(Date.now()), CLOCK_TICK_MS);
    return () => clearInterval(id);
  }, []);
  return now;
}
