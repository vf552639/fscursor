import React from "react";

import { Badge } from "../ui/Primitives";
import type { ProviderMeta } from "../../lib/registrarProviders";

/**
 * Как провайдер регистратора выглядит — в одном месте на все экраны.
 *
 * Провайдера рисуют минимум двое и подряд: выпадашка выбора
 * (`ProviderCombobox`) и карточка аккаунта в `Settings`. Оба берут данные из
 * одного `providerMeta`, но до этого файла рисовали их разным кодом — и код уже
 * начал расходиться: аватар был написан дважды (28px в списке, 38px на
 * карточке), а сигнал «API против manual» — локальным чипом в списке и
 * примитивом `Badge` на карточке, причём в двух разных зелёных (`#dcfce7` и
 * `#f0fdf4`). Один и тот же факт об одном и том же аккаунте, нарисованный
 * двумя способами на двух соседних экранах, читается как два разных факта.
 *
 * Поэтому здесь ровно две маленькие презентационные функции, обе питаются
 * `ProviderMeta`. Это не дизайн-система: ни состояний, ни вариантов, ни темы —
 * только «один провайдер выглядит одинаково везде».
 */

/**
 * Аватар провайдера: буква на фоне из `providerMeta` (у API-каталога — фирменные
 * цвета, у ручного — детерминированный цвет по имени).
 *
 * Размер — единственный параметр; радиус и кегль выведены из него, чтобы
 * вызывающему не приходилось помнить тройку чисел (и чтобы третье место, где
 * нужен аватар, не завело четвёртую пропорцию). Пропорции сняты с карточки
 * (38px → радиус 9.5, буква 15.2 — то же, что было); в выпадашке (28px) буква
 * становится на ~2px мельче прежнего — цена одного кода на два места.
 */
export function ProviderAvatar({ m, size = 28 }: { m: ProviderMeta; size?: number }) {
  return (
    <div
      style={{
        width: size,
        height: size,
        borderRadius: size * 0.25,
        background: m.bg,
        color: m.color,
        display: "flex",
        alignItems: "center",
        justifyContent: "center",
        fontWeight: 800,
        fontSize: size * 0.4,
        flexShrink: 0,
      }}
    >
      {m.icon}
    </div>
  );
}

/**
 * Бейдж способности провайдера: есть ли у него рабочий API-клиент в десктопе.
 *
 * Зелёный достаётся ТОЛЬКО API: у ручного провайдера нет ни Test, ни Set NS, и
 * покрасить его наравне значило бы обещать работоспособность, которой нет
 * (CLAUDE.md §6). Но «manual» — всё равно чип, а не голый серый текст: это
 * измеренное свойство аккаунта, такое же утверждение, как «Inactive» рядом на
 * карточке, и рисовать его подписью на полях означало бы «мы про это ничего не
 * знаем». Серый `Badge` говорит ровно то, что нужно: знаем, и это «нет».
 *
 * Нарисован примитивом `Badge`, а не своим span'ом: на карточке этот бейдж
 * стоит вплотную к `Badge` Active/Inactive, и свой чип рядом с примитивом
 * заметен как чужой — другой зелёный, другой кегль, другие отступы.
 */
export function ProviderApiTag({ api }: { api: boolean }) {
  return <Badge variant={api ? "green" : "gray"}>{api ? "API" : "manual"}</Badge>;
}

/**
 * Имя провайдера так, как его надо ПОКАЗАТЬ, — и это не всегда `m.label`.
 *
 * Обычно это ровно метка, и в разметку не добавляется ни одного лишнего узла
 * (фрагмент с текстом). Исключение одно: строка в колонке отличается от
 * тримленной — `"  hostiq  "` после чужого импорта или ручной правки БД. Такую
 * строку десктоп не знает (`make_service` пробелы не срезает), поэтому аккаунт
 * честно ручной: ни Test, ни полей секретов, провайдер в правке read-only.
 * Беда была не в этом, а в том, что `label` тримлен для списка и дедупа — и на
 * экране оставался опрятный `hostiq` с серым чипом «manual». Со стороны это
 * читается не как «в данных мусор», а как «приложение не узнало мой Hostiq»:
 * человек идёт искать баг в приложении, а не строку в базе.
 *
 * Поэтому сырая строка показывается в кавычках и с сохранённым пробелом
 * (`white-space: pre`) — она объясняет себя сама. `label` при этом не тронут:
 * список, дедуп и поиск по-прежнему видят чистое имя.
 *
 * Тултип по-русски, хотя вокруг английские `Active`/`manual`: это единственное
 * место фичи, которое даёт ИНСТРУКЦИЮ, а не подпись, и адресат у неё ровно
 * один — тот, кто пришёл выяснять, почему его Hostiq считается ручным.
 * Инструкцию читают на языке интерфейса, а он у пользователя русский.
 */
export function ProviderLabel({ m }: { m: ProviderMeta }) {
  if (m.raw === m.raw.trim()) return <>{m.label}</>;
  return (
    <span
      title="В базе имя провайдера сохранено с пробелами по краям. Такую строку десктоп не распознаёт, поэтому аккаунт считается ручным: ни проверки соединения, ни полей ключа у него нет. Чинится только правкой значения в базе или пересозданием аккаунта."
      style={{ whiteSpace: "pre", fontFamily: "ui-monospace, SFMono-Regular, Menlo, monospace" }}
    >
      «{m.raw}»
    </span>
  );
}
