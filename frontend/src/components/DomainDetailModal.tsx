/**
 * Карточка домена — шапка и вкладки, собранные как ответ на вопрос «почему
 * домен не работает».
 *
 * Шапка (ярлык со статусом, имя домена, мета-ряд с состоянием SSL и правкой
 * срока) видна всегда; под ней вкладки. **Overview** — путь запроса к домену
 * (Registrar → Cloudflare → Server), наша запись о прошлых прогонах, сертификат
 * и делегирование. **Server** — живое чтение с сервера по SSH. **Logs** —
 * перечень лог-файлов сайта из ТОГО ЖЕ снимка (пути, наличие, размеры); их
 * содержимое пока не читает никто, и вкладка говорит это словами. **Backup** —
 * резервные копии сайта из того же снимка: список панели с явным ответом,
 * знаем ли мы его вообще. **Template** и **Custom** — заглушки: продукт не
 * знает ни шаблонов сайта, ни сохранённых многошаговых действий, и обе вкладки
 * называют это словом.
 *
 * Раньше верх карточки был двумя колонками «слева чем домен является, справа
 * что развёрнуто на сервере»: колонки не означали ничего (просто перенос строки
 * посреди списка), а правая ПОВТОРЯЛА поля вкладки Server — по нашей записи из
 * provision, тогда как вкладка читает те же поля с сервера вживую. Теперь всё
 * про сайт живёт только там, где оно измерено.
 *
 * Вкладок здесь шесть: пять из макета плюс Backup, которой в макете не было
 * вовсе (её место занимала карточка-заглушка внутри вкладки Server). Ни одна не
 * открывается в пустоту. Правило про содержимое от этого не отменилось, оно
 * уточнилось: запрещена не «вкладка без функции», а вкладка, которая функцию
 * ОБЕЩАЕТ, — пустая панель или, того хуже, живые с виду органы управления,
 * ничего не делающие. Overview, Server, Logs и Backup читают снимок сервера и
 * говорят словами то, чего в нём нет; Template и Custom — с одной
 * карточкой-заглушкой каждая (`COMING SOON` и фраза о том, чем вкладка
 * станет), той же формы, что заглушка DMCA на Overview — единственная теперь
 * заглушка внутри вкладок с данными. Незнание — состояние, названное словом, а
 * не пустое место (принцип №6 CLAUDE.md).
 *
 * Что этим НЕ вернулось: `db`, `ssl` и `nginx` из прежней карточки (и кнопка
 * «Create Site»). Разница принципиальная — то были вкладки-ДЕЙСТВИЯ, и их
 * кнопки били в роуты, которых на бэкенде не существует; заглушка не делает
 * вид, что действие есть. Вернуть их можно только новыми Tauri-командами с
 * SSH-логикой, это отдельная функция со своим планом.
 *
 * А аккаунт Cloudflare и nameservers вкладки НЕ разводят — оба стоят на
 * Overview, и это то самое свойство, ради которого прежние вкладки и были
 * сняты. Это один вопрос («куда домен делегирован и почему не туда»), и
 * разведённые по двум экранам они заставляют собирать ответ из двух мест: зона
 * резолвится на одном, а следствие — пустое поле NS и погасшая кнопка — видно
 * на другом.
 *
 * Про пароли — два разных ответа, и путать их нельзя. **Пароль БД** карточка не
 * показывает и показать не может: он существует ровно один раз, сразу после
 * provision, и нигде не хранится — поэтому пустого поля под него здесь тоже
 * нет, оно обещало бы значение, которого не будет никогда. **Пароль FTP**,
 * наоборот, хранится — непрозрачным блобом (`ftp_password_blob_id`), — и живёт
 * в карточке FTP на вкладке Server рядом с логином: там его показывает
 * `RevealSecret`, там же
 * его можно задать из десктопа. Плейнтекста в этой ветке нет ни в одном месте:
 * расшифровка идёт по кнопке и не проходит ни через пропсы, ни через стейт
 * карточки.
 */
export default function DomainDetailModal({
  domain,
  servers,
  onClose,
}: {
  domain: Domain;
  /**
   * Список серверов — чтобы назвать сервер домена ИМЕНЕМ, а не сырым id, и
   * отдать его IP карточке FTP на вкладке Server (адрес хоста). На странице `Domains` он уже
   * загружен и раздаётся другим детям — до модалки просто не доезжал.
   */
  servers: Server[];
  onClose: () => void;
}) {
  // Сервер домена: имя вместо id в шапке и адрес для карточки FTP.
  const server = servers.find((s) => s.id === domain.server_id);
  // Одно чтение часов на рендер карточки: два срока на одном экране обязаны
  // отвечать на «сейчас» одинаково.
  //
  // Именно `Date.now()`, а НЕ `useNow()` списка доменов, и это разные приёмы, а
  // не рассинхрон. Список перешёл на тик в минуту вынужденно: «сейчас» уезжает
  // там пропсом в каждую строку, и меняясь на каждый рендер, оно делает
  // `React.memo` строки бессмысленным по построению. У карточки строк нет —
  // есть два срока в одном поддереве, — и лишний таймер на открытую модалку
  // купил бы только стареющие сами по себе подписи, которых за время её жизни
  // никто не дождётся.
  const now = Date.now();

  /**
   * Состояние сертификата — ОДИН расчёт на всю карточку.
   *
   * Раньше та же `sslState` с теми же аргументами звалась дважды независимо (в
   * строке-сводке и в секции сервера), и совпадали два ответа ровно до тех пор,
   * пока совпадают аргументы: «сходится само» — не гарантия, а везение. Теперь
   * значение считается здесь и раздаётся вниз, а раздельные копии остаются
   * невозможны по построению (принцип №6 CLAUDE.md: непроверенный домен обязан
   * получить серое «Not checked» ВЕЗДЕ, а не зелёное в одном месте).
   *
   * Потребителей ровно два, и оба получают ЭТО значение: бейдж в шапке и
   * карточка SSL на вкладке Overview. Своего `sslState` на карточке домена не
   * считает больше никто — секция сервера отдала карточку SSL наружу вместе с
   * расчётом.
   */
  const ssl = sslState(domain.fp_facts?.ssl, domain.fp_facts_at, now);

  /**
   * Зоны аккаунта Cloudflare — одно чтение на всю карточку, и от него зависят
   * три её ответа: nameservers зоны (подстановка в поле), статус зоны
   * (подтвердил ли Cloudflare делегирование) и поиск зоны по ИМЕНИ (дорезолв в
   * `DomainCloudflareField`). Хуки-`select`-ы поверх той же записи кэша
   * (`useZoneDetails`) отвечают на один вопрос каждый — три из них были бы
   * тремя именами для одного чтения; здесь нужен сам список.
   *
   * Цена — поход в Cloudflare на открытие карточки, и она осознанная: без NS
   * зоны и её статуса на этом экране нечего показывать вовсе. Запись кэша общая
   * со страницей Cloudflare и с прогоном привязки (`staleTime` 60с), так что
   * общее число походов от этого не растёт. Вне десктопа запрос не запускается
   * (`useCloudflareZones`): зон в базе нет, их читает `cf_list_zones`.
   */
  const zonesQ = useCloudflareZones(domain.cloudflare_account_id);
  const zones = zonesQ.data;
  /**
   * Зона домена: `null` — привязки нет или сохранённой зоны в аккаунте не
   * оказалось (обе новости значат «сверять не с чем и пушить нечего»),
   * `undefined` — зоны ещё не прочитаны.
   */
  const zone: Zone | null | undefined = useMemo(() => {
    if (!domain.cloudflare_account_id || !domain.cloudflare_zone_id) return null;
    if (!zones) return undefined;
    return zones.find((z) => z.id === domain.cloudflare_zone_id) ?? null;
  }, [zones, domain.cloudflare_account_id, domain.cloudflare_zone_id]);
  const zoneNameservers = useMemo(() => zone?.name_servers ?? [], [zone]);

  // Провайдер аккаунта регистратора: строка домена знает только его id, а
  // «умеет ли этот регистратор менять NS через API» — вопрос к провайдеру
  // (`lib/registrarCaps`, зеркало `make_service` в десктопе).
  //
  // Тот же список читает и `DomainRegistrarField` в ряду связей — дубль ЗДЕСЬ
  // осознанный, а не недосмотр. Запись кэша у обоих одна (`registrarsKeys
  // .accounts`), поэтому ни второго похода в сеть, ни расхождения ответов
  // случиться не может; а пропсом провайдер сюда не приезжает потому, что
  // ходил бы он снизу вверх — от поля к панели через модалку, — то есть поле
  // отвечало бы за чужой вопрос («умеет ли регистратор писать NS»), от
  // которого само отказывается намеренно.
  const registrarAccountsQ = useRegistrarAccounts();
  const registrarProvider = registrarAccountsQ.data?.find((a) => a.id === domain.registrar_id)?.provider;

  /**
   * Настоящие NS домена — ИЗ РЕЕСТРА (RDAP), а не у регистратора.
   *
   * Единственный источник, который отвечает про любой домен: у Hostiq чтения NS
   * в API нет вовсе, у ручных провайдеров нет и самого API — то есть у
   * большинства доменов этой карточки сверять было не с чем, и бейдж был серым
   * по построению. Реестр не спрашивает ни про аккаунт регистратора, ни про
   * ключи, поэтому и запрос здесь не гейтится провайдером: домен у Dynadot
   * получает такой же живой бейдж, как домен у Namecheap.
   *
   * Гейт остался один и он про эталон: спрашиваем, только если сверять БУДЕТ С
   * ЧЕМ — у домена есть зона, названная его же именем, и у зоны есть NS. Без
   * этого правило всё равно ответит «не знаем» (`no-zone`,
   * `zone-name-mismatch`, `zone-nameservers-unknown`), а ответ реестра будет
   * выброшен — то есть имя нашего домена уехало бы в сторонний RDAP-редиректор
   * (`rdap.org`, названная цена компромисса) ни за чем, на каждое открытие
   * карточки. В вебе гейт глушит запрос сам собой: зоны там не читаются вовсе
   * (`useCloudflareZones`), так что до `requireDesktop` дело не доходит.
   *
   * ВАЖНО про соответствие правилу: гейт обязан быть НЕ УЖЕ, чем условия, при
   * которых `nsDelegation` доходит до ответа реестра. Каждое лишнее условие тут
   * (например «карточка в фокусе» или свой `isTauri()`) даёт бейдж, вечно
   * обещающий ответ, которого не будет: правило скажет «ответа ещё нет — ждите»
   * про запрос, который не запускался. Поэтому сверка имени — тем же
   * `normalizeZoneName`, что и в правиле, а не своим сравнением; а `length > 0`
   * здесь считается по СЫРОМУ списку зоны, тогда как правило — по
   * нормализованному, и сойтись они могут только в одну сторону (нормализация
   * лишь выбрасывает пустые имена, поэтому непустой нормализованный список
   * невозможен при пустом сыром).
   */
  const canCompareWithZone =
    zoneNameservers.length > 0 &&
    !!zone &&
    normalizeZoneName(zone.name) === normalizeZoneName(domain.domain_name);
  const registryNsQ = useRegistryNameservers(
    canCompareWithZone ? domain.domain_name : null,
  );
  /**
   * Провал самого запроса — это тоже «спросить не удалось», и приезжать он
   * обязан тем же состоянием, что отказ реестра.
   *
   * Иначе на упавшем запросе бейдж говорил бы «ответа ещё нет» — то есть
   * «подождите» про ответ, которого не будет. Команда в Rust отдаёт три исхода
   * без `Result` (`commands/rdap.rs`), так что сюда попадает только поломка
   * транспорта или запуск вне десктопа; и то и другое честно называется «не
   * смогли спросить», а текст ошибки становится причиной под бейджем.
   */
  const registryAnswer: RegistryNameservers | undefined = registryNsQ.error
    ? { state: "unavailable", reason: errorText(registryNsQ.error) }
    : registryNsQ.data;

  const delegation = nsDelegation({
    domainName: domain.domain_name,
    zone: zone
      ? { name: zone.name, nameservers: zone.name_servers ?? [], status: zone.status }
      : zone,
    registryNameservers: registryAnswer,
  });

  /**
   * Черновик поля nameservers живёт ЗДЕСЬ, а не в панели, которая его рисует.
   *
   * `Tabs` держит смонтированной ровно активную вкладку (иначе четыре чужих
   * поддерева считались бы вхолостую на каждый рендер), поэтому дорога Overview → Server →
   * Overview размонтирует панель NS. Оставь состояние внутри — и набранный
   * руками список исчезал бы молча по пути на соседнюю вкладку; правила же
   * («зеркалим зону, пока не печатали», «правка выключает зеркало») остались в
   * `useNsDraft` рядом с панелью, наверх уехала только ЖИЗНЬ состояния.
   *
   * Список зоны отдаётся ТОЛЬКО сюда: панель получает его из самого черновика,
   * а не вторым пропом, — иначе «что зеркалим» и «с чем сверяем» стали бы двумя
   * значениями, которые ничто не заставляет совпадать.
   */
  const nsDraft = useNsDraft({ zoneNameservers, zoneId: domain.cloudflare_zone_id });

  /**
   * Активная вкладка. Состояние экрана, а не строки кнопок (`ui/Tabs` управляем
   * снаружи): однажды выбор поедет в ссылку `sdmp://`, и второй хозяин у него
   * появиться не должен.
   */
  const [tab, setTab] = useState("overview");

  // 920 — ширина карточки по макету: её содержимое раскладывается рядами по
  // две-три колонки, и на 760 такой ряд сминается в нечитаемые полосы.
  // Дисциплина `minmax(0,1fr)`/`minWidth:0` от этого не отменяется: `Modal`
  // держит `overflowY:auto`, из-за чего `overflow-x` вычисляется в `auto`, и
  // распёртая строка даёт горизонтальную прокрутку, а не обрезку.
  return (
    <Modal
      onClose={onClose}
      width={920}
      // Шапка вместо штатной строки «title + ✕»: имя домена там 24/700, а
      // рядом с ним живут бейдж статуса, бейдж SSL и правка срока. Слот
      // заменяет строку целиком, поэтому крестик — внутри шапки, и `onClose`
      // уезжает туда же.
      header={<DomainModalHeader domain={domain} ssl={ssl} now={now} onClose={onClose} />}
    >
      {/* Порядок вкладок — из макета и означает путь сужения вопроса: что
          домен есть → что развёрнуто → что он пишет в логи → что с него снято
          копиями → чем он застроен → что на нём можно запускать.

          Backup стоит четвёртой, а не последней: слева живые данные из снимка,
          справа заглушки, и граница между ними — свойство строки, по которому
          человек перестаёт открывать вкладки. Вкладка с данными, поставленная
          за эту границу, туда и провалилась бы. */}
      <Tabs
        items={[
          { id: "overview", label: "Overview" },
          { id: "server", label: "Server" },
          { id: "logs", label: "Logs" },
          { id: "backup", label: "Backup" },
          { id: "template", label: "Template" },
          { id: "custom", label: "Custom" },
        ]}
        value={tab}
        onChange={setTab}
        label="Domain card sections"
        tablistStyle={{ marginTop: 22 }}
      >
        {tab === "overview" ? (
          <DomainOverviewTab
            domain={domain}
            server={server}
            zone={zone}
            zones={zones}
            zonesError={zonesQ.error}
            ssl={ssl}
            now={now}
            delegation={delegation}
            nsDraft={nsDraft}
            registrarProvider={registrarProvider}
          />
        ) : null}
        {/* Единственный ответ на вопрос «что с сайтом»: значением поля там
            всегда факт с сервера, а наша запись из provision всплывает только
            строкой расхождения либо там, где факта нет вовсе
            (`lib/domainDrift`). Свежесть у вкладки честная и своя — снимок
            снимается по кнопке, которая стоит здесь же; карточка SSL на
            Overview читает ТОТ ЖЕ снимок и печатает его возраст у себя в
            шапке, чтобы не выдать протухшее измерение за свежее. */}
        {tab === "server" ? <DomainServerTab domain={domain} server={server} now={now} /> : null}
        {/* Логи читаются из ТОГО ЖЕ снимка, что и вкладка Server, и потому
            получают то же «сейчас»: возраст снимка на двух вкладках обязан
            совпадать. Сервер вкладке не нужен вовсе — пути логов приезжают в
            снимке готовыми, а адрес хоста спрашивает только FTP. */}
        {tab === "logs" ? <DomainLogsTab domain={domain} now={now} /> : null}
        {/* Копии читаются из ТОГО ЖЕ снимка и потому получают то же «сейчас»:
            возраст снимка на четырёх вкладках обязан совпадать. Сервер вкладке
            не нужен — список приезжает в снимке готовым, а создание архива (и
            адрес хоста для него) резолвит десктоп сам по `server_id` из
            локального кэша. */}
        {tab === "backup" ? <DomainBackupTab domain={domain} now={now} /> : null}
        {/* Заглушки. Пропов у обеих нет ни одного — и это не забывчивость:
            показывать про КОНКРЕТНЫЙ домен им нечего, а `domain`, отданный «на
            будущее», был бы пропом без потребителя. Приедет содержимое —
            приедет и то, из чего оно читается. */}
        {tab === "template" ? <DomainTemplateTab /> : null}
        {tab === "custom" ? <DomainCustomTab /> : null}
      </Tabs>
    </Modal>
  );
}
