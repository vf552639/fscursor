import React from "react";

import { desktopOnly } from "../lib/runtime";

/**
 * «Это умеет только десктоп» на месте убранного контрола. Одна фраза —
 * `desktopOnly` — уже была одна на весь продукт, а вид у неё за два экрана
 * успел стать трёх сортов; впереди ещё четыре формы с секретами.
 *
 * Стиль намеренно нейтральный: место подстановки бывает и полем формы, и рядом
 * кнопок, и жёлтым баннером, и подгонять его под фон каждый раз значит опять
 * развести три варианта.
 *
 * Это НЕ замена `OpenInDesktop`: там, где у действия есть разбираемый
 * `sdmp://`-хост, веб отдаёт ссылку. Заметка — для действий, ссылки на которые
 * нет (`parseDeepLinkAction` вернул бы `null`, и ссылка бы только тостила).
 *
 * Канонический ответ на «почему в вебе поля секрета нет вовсе, а не выключено»:
 * секрет шифрует Rust ключом хранилища из системного keychain, так что записать
 * его из браузера физически невозможно. Поле, в которое дали набрать пароль,
 * обещало бы сохранение — и обмануло бы уже ПОСЛЕ того, как секрет набран.
 * Заметка объясняет это до ввода. Формам достаточно сослаться сюда.
 */
export function DesktopOnlyNote({ what }: { what: string }) {
  return (
    <div
      style={{
        fontSize: 12.5,
        color: "#6b7280",
        background: "#f9fafb",
        border: "1px solid #e5e7eb",
        borderRadius: 8,
        padding: "8px 12px",
      }}
    >
      {desktopOnly(what)}
    </div>
  );
}
