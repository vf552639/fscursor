import React from "react";

import { Badge, SectionCard } from "../../ui/Primitives";
import { TabBody } from "./TabLayout";

/**
 * Вкладка Template — заглушка, и сегодня это её единственная честная форма.
 *
 * О шаблонах сайта продукт не знает НИЧЕГО, и это не «ещё не вывели на экран».
 * Слова `template` нет во всём Python-коде бэкенда: у модели `Domain` нет ни
 * колонки под выбор, ни свободного текста под заметку. В снимке сервера
 * (`lib/domainFacts`) шаблон не измеряется, и ни одна команда десктопа его не
 * ставит. То есть показывать здесь нечего и записывать выбор некуда — ни на
 * сервере, ни у нас.
 *
 * Макет рисует на этой вкладке карточку «Site template»: пилюлю `NOT SET` /
 * `INSTALLED`, селект из пяти шаблонов, кнопку «Save» с правилом «выбрать можно
 * ровно один раз», фальшивое окно браузера с превью и поле заметки с кнопкой
 * «Save comment». Ни один из этих органов управления сюда не приехал, и причина
 * у всех одна: селект и обе кнопки не могут сохранить выбор никуда, а пилюля
 * `NOT SET` — это ещё и утверждение о состоянии домена, которого никто не
 * измерял (принцип №6 CLAUDE.md: незнание называется словом, а не бейджем).
 * Превью же нарисовало бы сайт, которого на сервере может не быть вовсе.
 *
 * Поэтому — та же форма, что у заглушек DMCA (Overview) и Backups (Server):
 * пилюля `COMING SOON` и одна фраза о том, чем вкладка станет.
 *
 * Копий этой формы в карточке теперь четыре, и в один компонент они намеренно
 * не сведены. Разметки в ней три строки без единой ветки, а ценное в каждой
 * заглушке — свой комментарий о том, чего в продукте нет; общим он быть не
 * может. Главное же: заглушки живут до своей функции и умирают по одной —
 * абстракция, у которой места вызова исчезают поштучно, переживёт всех своих
 * потребителей. Понадобится менять саму форму (например, когда цвета уедут в
 * токены редизайна) — тогда все четыре и поедут вместе, и тогда же её и стоит
 * завести.
 */
export default function DomainTemplateTab() {
  return (
    <TabBody>
      <SectionCard title="Site template" right={<Badge variant="gray">COMING SOON</Badge>}>
        <div style={{ fontSize: 13, color: "#94a3b8" }}>
          The site template this domain is built from will be chosen and shown here in a future update.
        </div>
      </SectionCard>
    </TabBody>
  );
}
