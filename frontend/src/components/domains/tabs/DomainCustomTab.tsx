import React from "react";

import { Badge, SectionCard } from "../../ui/Primitives";
import { TabBody } from "./TabLayout";

/**
 * Вкладка Custom — заглушка про пресеты: сохранённые многошаговые действия,
 * которые можно запустить на домене.
 *
 * Сохранять их сегодня негде и запускать нечем: ни модели, ни таблицы, ни
 * роутов на бэкенде, а прогоны, которые продукт умеет (provision в десктопе),
 * — свои и фиксированные: исполнять цепочку шагов, составленную человеком,
 * нечему. То есть все девять карточек макета были бы девятью кнопками «Run»,
 * которым нечего звать, а форма «+ New preset» сохраняла бы набранное в никуда.
 *
 * ОСТОРОЖНО с совпадением слов, оно тут обманчивое. В продукте есть
 * `nginx_presets` — JSON-колонка у домена (`backend/app/models/domain.py:61`,
 * схемы `backend/app/schemas/domain.py:75,116`, миграция `010`), которая
 * доезжает даже до типа `Domain` во фронте (`api/domains.ts`). Это НЕ то, о чём
 * вкладка: там четыре булевых флажка конфига nginx (`force_https`,
 * `www_redirect`, `custom_404`, `basic_auth`), которые Rust разворачивает в
 * кусок конфига (`desktop/src-tauri/src/ssh/fastpanel.rs:876`
 * `render_nginx_snippet`), а здесь — «сменить NS», «перевыпустить SSL» и прочие
 * цепочки из нескольких шагов. Совпадает одно слово. Поэтому заглушка эту
 * колонку не читает и не упоминает: обещать «скоро включим то, что уже лежит в
 * базе» значило бы соврать дважды — и про предмет, и про готовность. Про
 * готовность — потому что колонку сегодня не читает вообще никто: развернуть
 * флажки в конфиг умеет только `apply_nginx_override`, а его самого не зовёт ни
 * одна команда десктопа.
 *
 * Форма заглушки — та же, что у DMCA (Overview) и Template; почему эти три
 * копии намеренно не сведены в общий компонент — в `TabLayout`. Копий было
 * четыре: четвёртая, Backups на вкладке Server, дожила до своей функции и
 * заменена вкладкой Backup.
 *
 * Пропов у вкладки нет ни одного: показывать про КОНКРЕТНЫЙ домен ей нечего, а
 * `domain`, взятый «на будущее», был бы пропом без потребителя. Появится
 * содержимое — приедет и `domain`, из которого оно читается (и `now`, если у
 * показанного будет возраст измерения).
 */
export default function DomainCustomTab() {
  return (
    <TabBody>
      <SectionCard title="Presets" right={<Badge variant="gray">COMING SOON</Badge>}>
        <div style={{ fontSize: 13, color: "#94a3b8" }}>
          Presets - saved multi-step actions you can run on this domain - will appear here in a
          future update.
        </div>
      </SectionCard>
    </TabBody>
  );
}
