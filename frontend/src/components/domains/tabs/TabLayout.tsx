import React from "react";

/**
 * Раскладка, общая для ВСЕХ вкладок карточки домена.
 *
 * Заведена не ради двух сегодняшних вкладок, а ради пяти завтрашних: макет
 * кладёт на карточку Overview, Server, Logs, Template и Custom, и первые две
 * успели развести две копии одного и того же — корень «колонка с зазором 14» и
 * восьмистрочный абзац про `minmax(0, 1fr)` над одинаковым двухколоночным
 * гридом. Пока копий две, это терпимо; на пяти это пять мест, где чинить
 * `gap: 14`, и пять копий обоснования, которое начнёт расходиться с первой же
 * правкой — ровно так в этом проекте расходились лестницы состояний, пока их не
 * свели в один модуль.
 *
 * Слотов под переопределение здесь нарочно нет: ни одной вкладке пока не
 * понадобился другой зазор или другое число колонок, а проп без потребителя —
 * приглашение развести их обратно.
 */

/** Зазор между блоками вкладки — 14px по макету. */
const TAB_GAP = 14;

/** Столбец блоков — одна раскладка на тело вкладки и на группы внутри него. */
const COLUMN: React.CSSProperties = { display: "flex", flexDirection: "column", gap: TAB_GAP };

/**
 * Тело вкладки: колонка блоков.
 *
 * Отступа сверху здесь нет намеренно — его держит панель `ui/Tabs`
 * (`PANEL_PADDING_TOP`), и там же объяснено почему. Вкладке, компенсирующей его
 * у себя, пришлось бы знать чужое число.
 */
export function TabBody({ children }: { children: React.ReactNode }) {
  return <div style={COLUMN}>{children}</div>;
}

/**
 * Названная область внутри вкладки — тот же столбец, но со своим именем.
 *
 * Нужна там, где часть вкладки говорит об одном предмете, а подпись к нему
 * стоит отдельной строкой: глазами близость всё объясняет, на слух — нет.
 * Скринридер объявляет вход в такую область по имени, и подпись, стоящая
 * первой внутри неё, наконец относится к тому, что за ней следует.
 *
 * `<section>` без имени — обычный `div` по ролям, поэтому имя обязательно: без
 * него область не объявляется вовсе, и обёртка была бы украшением.
 */
export function TabGroup({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <section aria-label={label} style={COLUMN}>
      {children}
    </section>
  );
}

/**
 * Ряд карточек: две колонки одинаковой ширины.
 *
 * `minmax(0, 1fr)`, а не `1fr`: голый `1fr` — это `minmax(auto, 1fr)`, и минимум
 * трека равен ширине содержимого, поэтому один неразрывный токен (путь, логин,
 * имя издателя, чужая ошибка) распирает колонку за ширину модалки. У `Modal`
 * стоит `overflowY: auto`, из-за чего `overflow-x` вычисляется в `auto` —
 * распёртая колонка даёт КАРТОЧКЕ горизонтальную полосу, запрещённую
 * `design-brief.md` §11.
 *
 * Вторая половина той же дисциплины живёт у карточек: `SectionCard` ставит себе
 * `minWidth: 0`, потому что у grid-элемента он по умолчанию равен содержимому —
 * без него в трек упрётся не текст, а сам столбец.
 */
export function CardRow({ children }: { children: React.ReactNode }) {
  return (
    <div style={{ display: "grid", gridTemplateColumns: "repeat(2, minmax(0, 1fr))", gap: TAB_GAP }}>
      {children}
    </div>
  );
}
