/** Один файл из снимка — то, что о нём знает провод (`lib/domainFacts`). */
type LogFile = DomainFacts["logs"][number];

/**
 * Вкладка Logs — перечень лог-файлов сайта из того же снимка сервера, что и
 * вкладка Server, и честный ответ о том, чего мы про них НЕ знаем.
 *
 * Показываем ровно то, что измерено: путь каждого файла, есть ли он, сколько
 * весит — и по кнопке Refresh последние строки выбранного файла. Макет рисует
 * здесь ещё три вещи, и они сюда не приехали — это не упрощение вёрстки, а
 * отказ печатать выдуманное:
 *
 * - **Число строк в бейдже чипа.** Мы его не считали: команда снимка делает
 *   `test -f` и `stat -c %s` (`ssh/fastpanel_facts.rs`), то есть знает
 *   существование и РАЗМЕР. Он в бейдже и стоит. Свежий размер из чтения
 *   хвоста печатается в шапке консоли, а не в бейдже: один обновлённый чип
 *   рядом с тремя из старого снимка врал бы про общий возраст, а возраст у
 *   чипов один на всех и назван `SnapshotLine`.
 * - **Таблица access-лога и тёмная консоль ошибок с разобранными полями.**
 *   Строки мы теперь читаем — но показываем СЫРЫМИ, моноширинным, без разбора
 *   в колонки и без раскраски. Формат access-лога не сверен ни с одной
 *   директивой на сервере (`grep` за ними вернул пустоту), а колонка «status»,
 *   собранная по угаданной позиции поля, — это выдуманный диагноз (принцип №6
 *   CLAUDE.md), причём выдуманный убедительно.
 * - **Кнопка «Download».** Её нет и сегодня: `SshSession::exec` буферизует весь
 *   вывод в память, и `cat` над логом в полгигабайта убил бы десктоп. Честная
 *   выгрузка — поток по SFTP прямо в файл, то есть отдельная работа, а не
 *   вторая кнопка рядом. Кнопка, которая роняет приложение, хуже отсутствующей.
 *
 * Кнопка снятия снимка тут ОДНА и только в состоянии «ни разу не читали»; её
 * исход виден на месте — провал последней попытки печатает общая шапка снимка
 * (`facts/SnapshotLine`), потому что единственное действие вкладки обязано
 * оставлять на экране след.
 * Правило карточки — «читает с сервера вкладка Server», и рядом с показанными
 * данными эта вкладка его не нарушает: свежесть у неё общая с Server, снимок
 * один, и второй кнопкой «Проверить» они бы только спорили, кто из них главный.
 * Но без снимка здесь нет ни чипов, ни путей — пустой экран со словами «Never
 * checked» и без единого способа это изменить. Кнопка и есть выход из него;
 * прогон у неё тот же (`useReadDomainFacts`), поэтому разойтись с кнопкой
 * Server она не может по построению.
 */
export interface DomainLogsTabProps {
  domain: Domain;
  /**
   * «Сейчас» карточки: один раз на рендер, общее для всех её сроков — возраст
   * снимка здесь обязан совпадать с тем, что печатают Server и карточка SSL.
   */
  now: number;
}


/**
 * Чип одного файла: подпись, бейдж и выбор.
 *
 * Вынесен из `map`, потому что почти весь он — стили: тридцать строк инлайна в
 * теле цикла прятали за собой три строки логики, и вкладка, которая возьмёт этот
 * файл образцом, скопировала бы вместе с ними и это.
 *
 * Про честность бейджа. Состояний у файла три, и в бейдже у них ТРИ РАЗНЫХ
 * ответа, а не два ответа и цвет:
 *
 * - файла на сервере нет — `missing` прямо в бейдже. План писал «`exists ? size
 *   : —`», но прочерк там значил бы сразу две разные вещи (нет файла / не
 *   прочитали размер), а различал бы их только приглушённый цвет — то есть
 *   канал, которого нет ни у скринридера, ни у чёрно-белой печати, ни у
 *   дальтоника. Отступление осознанное — №9 в списке отступлений
 *   `plans/2026-08-18-kartochka-domena-vkladki.md`;
 * - файл есть, размер не прочитан (`size_bytes: null` при `exists: true`) —
 *   прочерк, и теперь он однозначен. Глазами однозначен: сам глиф на слух не
 *   звучит вовсе (пунктуацию скринридеры по умолчанию не читают), поэтому у
 *   бейджа в этом состоянии есть `aria-label` — иначе чип объявлялся бы просто
 *   «Backend access», и «размер не прочитан» пришлось бы выводить из ОТСУТСТВИЯ
 *   размера, то есть из тишины;
 * - файл есть и измерен — размер, включая честный «0 B» у пустого лога.
 *
 * Приглушённый цвет у несуществующего остаётся, но теперь он ДУБЛИРУЕТ слово, а
 * не несёт смысл в одиночку. `title` с полным путём — тоже дубль, и полезен он
 * не как канал состояния, а как ответ на «какой файл за этой подписью»: путь на
 * экране напечатан только у выбранного чипа.
 */
function LogChip({
  file,
  domainName,
  active,
  pathId,
  onSelect,
}: {
  file: LogFile;
  /** Имя домена — из него выводится подпись файла (`lib/logFiles`). */
  domainName: string;
  active: boolean;
  /** Id строки с полным путём — её читает `aria-describedby` выбранного чипа. */
  pathId: string;
  onSelect: () => void;
}) {
  return (
    <button
      // Модалка домена содержит формы; кнопка без `type` в форме — это submit.
      type="button"
      aria-pressed={active}
      // Полный путь напечатан отдельной строкой, и глазами он связан с чипом
      // соседством; на слух связи нет никакой, пока её не назвать — та же
      // болезнь, которую на вкладке Server лечит `TabGroup`.
      aria-describedby={active ? pathId : undefined}
      title={file.path}
      onClick={onSelect}
      style={{
        display: "inline-flex",
        alignItems: "center",
        gap: 8,
        border: `1px solid ${active ? "#0f172a" : "#e2e8f0"}`,
        background: active ? "#0f172a" : "#fff",
        // Три цвета вместо двух: приглушённый — это «файла на сервере нет», и
        // он обязан быть виден и на выбранном чипе тоже, иначе выбор файла
        // стирал бы новость о нём.
        color: !file.exists ? "#94a3b8" : active ? "#fff" : "#475569",
        // Шрифт задаётся явно, как у `Btn` и у вкладок `ui/Tabs`: без него
        // кнопка берёт системный шрифт формы и выпадает из строки набранного
        // Inter.
        fontFamily: "'Inter',sans-serif",
        fontSize: 13,
        fontWeight: active ? 600 : 500,
        padding: "6px 12px",
        borderRadius: 99,
        cursor: "pointer",
      }}
    >
      {logFileLabel(file.path, domainName)}
      <span
        // Слово вместо прочерка — только на слух: `aria-label` заменяет
        // СОДЕРЖИМОЕ этого узла в доступном имени кнопки, но на экране остаётся
        // тот же короткий глиф, ради которого бейдж и сделан узким. У остальных
        // состояний метки нет: там содержимое читается как есть («missing»,
        // «2 KB»), и вторая формулировка рядом только разошлась бы с первой.
        aria-label={file.exists && file.size_bytes === null ? "size not read" : undefined}
        style={{
          fontSize: 11,
          fontWeight: 600,
          color: active ? "#cbd5e1" : "#64748b",
          background: active ? "#1e293b" : "#f1f5f9",
          borderRadius: 99,
          padding: "1px 7px",
        }}
      >
        {badgeText(file)}
      </span>
    </button>
  );
}

/** Что стоит в бейдже чипа: размер, «нет файла» или «размер не прочитан». */
function badgeText(f: LogFile): string {
  if (!f.exists) return "missing";
  // `null` — это не ноль: `stat` не разобрался, и печатать его нулём значило бы
  // выдумать пустой файл. Ноль настоящий (пустой лог) печатается как «0 B».
  //
  // Ветку держит ТИП, а не тест: `formatBytes` принимает `number`, и без этой
  // строки файл не соберётся. Мутационная проверка это подтвердила иначе —
  // сняв её, поведение не меняется (тот же прочерк вернул бы страж
  // `Number.isFinite` внутри `formatBytes`), падает только `tsc`.
  if (f.size_bytes === null) return "—";
  return formatBytes(f.size_bytes);
}

/**
 * Сколько строк читает команда — то же число, что `LOG_TAIL_LINES` в Rust
 * (`ssh/fastpanel_logs.rs`). Копия константы, а не импорт: провод отдаёт
 * СТРОКИ, а не свой лимит, и связать их можно только словом. Здесь она нужна
 * ровно затем, чтобы обещание кнопки («last 200 lines») называло то же число,
 * которое приедет.
 */
const TAIL_LINES = 200;

/**
 * Консоль с сырыми строками лога.
 *
 * Моно — СИСТЕМНЫЙ (`ui-monospace`), как у пути под чипами и как везде в
 * приложении: вебфонт из макета (`IBM Plex Mono`) ради одной модалки не
 * подключаем — это вопрос уровня всего приложения (`design-brief.md` §5) и
 * лишняя сетевая зависимость в Tauri.
 *
 * `white-space: pre` — потому что в логе значима КАЖДАЯ позиция: перенос по
 * словам склеил бы столбцы стек-трейса и превратил бы одну строку файла в
 * несколько строк экрана, то есть соврал бы про сам предмет. Отсюда и
 * `overflow-x: auto`, и он стоит ВНУТРИ этого блока: горизонтальную полосу
 * `design-brief.md` §11 запрещает странице, а не блоку, — а у `Modal` стоит
 * `overflowY: auto`, из-за чего неограниченная консоль дала бы полосу всей
 * карточке.
 *
 * Высота фиксированная, прокрутка — к низу после каждой загрузки: свежие
 * строки лога лежат в конце файла, и открывать его на первой строке значило бы
 * прятать ровно то, ради чего пришли. Ровно то же делает терминал.
 *
 * Строки не подсвечиваем и не раскрашиваем: см. шапку файла — формат access-лога
 * не сверен, и раскраска по угаданной позиции поля была бы диагнозом, а не
 * измерением.
 */
function LogConsole({ tail }: { tail: LogTail }) {
  const box = useRef<HTMLPreElement>(null);

  // Прокрутка — работа над УЗЛОМ, а не над состоянием, поэтому здесь эффект
  // уместен (в отличие от сброса прочитанного при смене чипа: тот отработал бы
  // на такт позже показа и один кадр держал бы строки под чужой подписью).
  useEffect(() => {
    const el = box.current;
    if (el) el.scrollTop = el.scrollHeight;
  }, [tail]);

  return (
    <div style={{ display: "flex", flexDirection: "column", gap: 6 }}>
      <div style={{ display: "flex", alignItems: "center", gap: 8, fontSize: 12, color: "#94a3b8" }}>
        {/* Число строк — НАПЕЧАТАННОЕ, а не лимит: «last 200 lines» под файлом
            из семи строк было бы обещанием, а не отчётом. Совпадает с лимитом
            ровно тогда, когда лимит и сработал.

            Размер — свежий, снятый той же командой рядом с чтением, а не взятый
            из снимка: снимок бывает недельной давности, и именно этим размером
            меряется, сработал ли байтовый кап. */}
        <span>
          {`last ${tail.lines.length} lines`}
          {tail.size_bytes === null ? "" : ` · ${formatBytes(tail.size_bytes)}`}
        </span>
        {tail.truncated ? (
          <span
            title="The file is larger than one read: the first shown line is not the beginning of the file"
            style={{
              fontSize: 11,
              fontWeight: 600,
              color: "#92400e",
              background: "#fef3c7",
              borderRadius: 99,
              padding: "1px 7px",
            }}
          >
            truncated
          </span>
        ) : null}
      </div>
      <pre
        ref={box}
        // Прокручиваемая область — не читается клавиатурой, пока не станет
        // фокусируемой; `tabIndex` даёт стрелки и PageDown внутри неё.
        tabIndex={0}
        aria-label="Log contents"
        style={{
          margin: 0,
          height: 260,
          overflowX: "auto",
          overflowY: "auto",
          fontFamily: "ui-monospace, monospace",
          fontSize: 12,
          lineHeight: 1.5,
          whiteSpace: "pre",
          color: "#334155",
          background: "#f8fafc",
          border: "1px solid #e2e8f0",
          borderRadius: 12,
          padding: 12,
        }}
      >
        {tail.lines.join("\n")}
      </pre>
    </div>
  );
}

export default function DomainLogsTab({ domain, now }: DomainLogsTabProps) {
  /**
   * Разбор снимка — общий (`lib/domainFacts`), а не свой: гейт `fp_facts_at` над
   * `fp_facts` и порог свежести обязаны быть теми же, что на вкладке Server и в
   * карточке SSL, потому что снимок у всех троих ОДИН. Свежесть считается от
   * `fp_facts_at` (когда сняли), а не от `fp_checked_at` (когда пытались), —
   * иначе провалившаяся проверка молодила бы перечень логов.
   */
  const snapshot = snapshotOf(domain.fp_facts, domain.fp_facts_at, now);
  const { facts, noSnapshot } = snapshot;
  /**
   * `?? []` глотает и отсутствие поля, а не только пустой массив: снимок,
   * снятый до появления `logs` в контракте, приезжает без него. Отдельного
   * состояния у этого нет намеренно — ответ на экране один и тот же и одинаково
   * честный: путей мы не знаем (см. пустое состояние внизу файла).
   */
  const logs = facts?.logs ?? [];
  const desktop = isTauri();
  const read = useReadDomainFacts(domain.id);

  /**
   * Выбранный чип хранится ПУТЁМ, а не индексом, и путь этот проверяется по
   * списку на каждом рендере.
   *
   * Список приезжает из снимка и переснимается кнопкой: после чтения в нём
   * может не оказаться прежнего файла (сайт переехал, владелец сменился). Тогда
   * индекс молча показал бы соседний файл под прежним номером, а «висящий» путь
   * — строку под чипами, которой в перечне уже нет. Не нашли — берём первый.
   */
  const [selectedPath, setSelectedPath] = useState<string | null>(null);
  const selected: LogFile | null = logs.find((f) => f.path === selectedPath) ?? logs[0] ?? null;

  /**
   * Id строки с полным путём: на неё ссылается `aria-describedby` выбранного
   * чипа. `useId`, а не константа, — таких карточек на экране может быть
   * несколько, и статический id связал бы все чипы с первой строкой.
   */
  const pathId = useId();

  /**
   * Чтение хвоста ВЫБРАННОГО файла. Путь уходит в хук, и хук же отдаёт результат
   * только для него: содержимое одного файла под подписью другого — не мелочь
   * вёрстки, а неверный ответ на вопрос «что в этом логе». Переключение чипа
   * поэтому стирает прочитанное само собой, без сбрасывающего эффекта.
   */
  const { tail, error: tailError, pending: tailPending, run: readTail } = useReadLogTail(
    domain.id,
    selected?.path ?? null,
  );

  return (
    <TabBody>
      {/* Отдельной названной области (`TabGroup`), как на вкладке Server, здесь
          нет намеренно: там она отделяла прочитанное с сервера от заглушки
          Backups, стоящей рядом, — а тут ВСЁ содержимое панели про один снимок,
          и панель уже названа своей вкладкой (`role="tabpanel"` +
          `aria-labelledby` в `ui/Tabs`). Вторая обёртка добавила бы к «Logs»
          ещё один заголовок про то же самое. */}

      {/* Возраст снимка, провал последней попытки и кнопка чтения — общая шапка
          снимка (`facts/SnapshotLine`), та же, что на вкладке Server. Возраст
          нужен потому, что размеры файлов — измерение и без возраста читаются
          как сегодняшние; при `noSnapshot` эта же строка и есть требуемое
          планом «Never checked». Ошибка последней попытки — потому что кнопка
          ниже единственная на вкладке: без неё провалившееся чтение оставляло
          бы экран ровно таким же, каким он был до клика. */}
      <SnapshotLine
        snapshot={snapshot}
        error={domain.fp_check_error}
        right={
          /* Только десктоп: чтение идёт по SSH, веб этого не умеет (принцип
             №3). И только без снимка — см. объяснение у компонента. */
          noSnapshot && desktop ? (
            <Btn
              size="sm"
              variant="secondary"
              onClick={read.run}
              disabled={read.pending}
              title="Read the server snapshot over one SSH session — log file paths and sizes come with it"
            >
              {read.pending ? "Checking…" : "Проверить на сервере"}
            </Btn>
          ) : null
        }
      />

      {logs.length > 0 && selected ? (
        <>
          {/* Чипы — кнопки с `aria-pressed` в именованной группе.
              Рассматривались и отвергнуты два соседних варианта:

              - **вложенный `tablist`** — панель вкладки уже внутри `tablist`
                карточки, и вторая строка вкладок внутри первой читается как
                вкладки той же карточки;
              - **`radiogroup` + `aria-checked`** — семантически он точнее
                (выбран ровно один) и дал бы стрелки с одной остановкой Tab.
                Отвергнут не поэтому: радиогруппа обещает ВВОД — значение,
                которое человек задаёт и которое куда-то поедет, — а здесь выбор
                ничего не меняет ни на сервере, ни в нашей записи; он просто
                показывает другой путь. Появится чтение содержимого (Tauri-`tail`)
                — вопрос стоит открыть заново вместе с ним: тогда у выбора
                появится последствие, и цена лишних четырёх остановок Tab станет
                видна. */}
          <div role="group" aria-label="Log files" style={{ display: "flex", gap: 6, flexWrap: "wrap" }}>
            {logs.map((f) => (
              <LogChip
                key={f.path}
                file={f}
                domainName={domain.domain_name}
                active={f.path === selected.path}
                pathId={pathId}
                onSelect={() => setSelectedPath(f.path)}
              />
            ))}
          </div>

          {/* Полный путь выбранного файла. Моно — потому что путь читают
              посимвольно; `overflowWrap` — потому что текст ЧУЖОЙ и длинный, а
              `Modal` держит `overflowY: auto`, из-за чего `overflow-x`
              вычисляется в `auto`: неразрывный путь дал бы карточке
              горизонтальную полосу, запрещённую `design-brief.md` §11.

              Моно — СИСТЕМНЫЙ (`ui-monospace`, как у остальных путей и айди в
              приложении), а не `IBM Plex Mono` из макета: подключать вебфонт
              ради одной модалки — вопрос уровня всего приложения
              (`design-brief.md` §5) и лишняя сетевая зависимость в Tauri.
              Названный, но не подключённый, он всё равно откатился бы к
              системному — то есть был бы строкой, которая ничего не делает. */}
          <div style={{ display: "flex", alignItems: "center", gap: 12 }}>
            <div
              id={pathId}
              style={{
                flex: 1,
                minWidth: 0,
                fontFamily: "ui-monospace, monospace",
                fontSize: 12,
                color: "#94a3b8",
                overflowWrap: "anywhere",
              }}
            >
              {selected.path}
            </div>

            {/* Refresh стоит ЗДЕСЬ, в ряду с путём, а не в `SnapshotLine`: та
                строка про снимок (возраст, ошибка последней попытки, размеры
                чипов), а эта кнопка — про содержимое одного файла. Поставь её
                в шапку снимка, и она обещала бы, что от неё обновятся и бейджи
                чипов, — а они остаются со своим прежним возрастом.

                Только десктоп: чтение идёт по SSH (принцип №3). Гаснет на
                несуществующем файле — на сервер за ним ходить незачем, и это
                же говорит тело вкладки словами. */}
            {desktop ? (
              <Btn
                size="sm"
                variant="secondary"
                onClick={readTail}
                disabled={tailPending || !selected.exists}
                title={
                  selected.exists
                    ? `Read the last ${TAIL_LINES} lines of this file over SSH`
                    : "This file was not on the server when the snapshot was taken"
                }
              >
                {tailPending ? "Reading…" : "Refresh"}
              </Btn>
            ) : null}
          </div>
        </>
      ) : null}

      {/* Ошибка чтения хвоста — НАД телом и отдельно от `fp_check_error` в
          шапке: это разные измерения. Провал чтения содержимого не двигает
          снимок (ни `fp_checked_at`, ни `fp_check_error` команда не трогает),
          и печатать его в строке снимка значило бы приписать снимку попытку,
          которой не было. Ниже консоль при этом остаётся: «прочитать не
          удалось» не отменяет того, что уже прочитано раньше. */}
      {tailError ? (
        <div
          role="alert"
          style={{
            fontSize: 12,
            color: "#b91c1c",
            background: "#fef2f2",
            border: "1px solid #fecaca",
            borderRadius: 8,
            padding: "6px 10px",
            overflowWrap: "anywhere",
          }}
        >
          {tailError}
        </div>
      ) : null}

      {/* Состояния тела — строго по порядку проверки: сначала то, чего мы не
          знаем (снимка нет, путей нет), потом то, чего не можем (веб), потом
          то, чего нет на сервере, и только затем содержимое. Порядок и есть
          смысл: «файл пуст» под отсутствующим снимком было бы измерением,
          которого никто не делал. */}
      {noSnapshot ? (
        <EmptyPanel>Log files are listed from the server snapshot, and none has been taken yet.</EmptyPanel>
      ) : logs.length === 0 || !selected ? (
        /* Снимок есть, а список путей пуст — и это НЕ «логов у сайта нет».
           Причин у пустоты как минимум четыре, и НИ ОДНУ из них экран назвать
           не может, потому что ни одна не доезжает сюда отличимой от других:

           1. владелец сайта не найден — пути строить не от чего
              (`ssh/fastpanel_facts.rs:615`, `match owner_home { None => vec![] }`);
           2. владелец найден, но его домашний каталог пуст — там же, `:537`;
           3. **команда на сервере не сработала**: `read_log_paths` намеренно
              выбрасывает код возврата (`let (_, out) = s.run(...)`, `:542-544`),
              а `parse_log_stats` (`:502-528`) на неразобранном выводе отдаёт
              пустой список — внутри УДАЧНОГО в остальном снимка;
           4. снимок снят до появления поля `logs` в контракте — тогда его тут
              нет вовсе, и `?? []` наверху приводит это к той же пустоте.

           Найдись владелец и сработай команда — приехали бы все четыре пути, и
           найденные, и ненайденные файлы. Поэтому фраза ниже говорит ровно о
           нашем незнании и НЕ называет причину: назвать «владельца не нашли» на
           упавшей команде значило бы придумать диагноз (принцип №6 CLAUDE.md).
           Ровно то же различие, ради которого у полей-списков заведён `list` в
           `FactRow`: прочерк там читался бы как «спросили, там пусто». */
        <EmptyPanel>
          The last snapshot brought no log paths for this site, so we do not know where its logs are.
        </EmptyPanel>
      ) : !desktop ? (
        /* Веб — читалка (принцип №3): SSH-пароль здесь непрозрачный блоб, и
           расшифровать его может только десктоп. Фраза называет ровно это, а не
           «пока не готово»: функция есть, её просто нет ЗДЕСЬ. */
        <EmptyPanel>Reading log contents requires the desktop app.</EmptyPanel>
      ) : !selected.exists ? (
        /* Файла нет по снимку — на сервер не ходим вовсе. Гейт пути в Rust
           отверг бы и такой запрос, но отвергнутый запрос стоил бы SSH-сессии
           и секунд ожидания ради ответа, который уже лежит на экране в бейдже. */
        <EmptyPanel>This file does not exist on the server.</EmptyPanel>
      ) : !tail ? (
        /* Ещё не читали. Ошибка при пустом результате уже напечатана выше —
           повторять под ней приглашение «нажмите Refresh» незачем: экран и так
           говорит, что делать, а два сообщения об одном спорили бы. */
        tailError ? null : <EmptyPanel>Press Refresh to read the last {TAIL_LINES} lines.</EmptyPanel>
      ) : !tail.exists ? (
        /* Файл исчез МЕЖДУ снимком и чтением (сайт переехал, владелец
           сменился). Чип при этом ещё показывает старый размер — это не
           противоречие: размер помечен возрастом снимка, а это ответ сервера
           только что. */
        <EmptyPanel>This file does not exist on the server.</EmptyPanel>
      ) : tail.lines.length === 0 ? (
        /* Пустой файл — это ИЗМЕРЕНИЕ, а не отсутствие ответа: пустая консоль
           на его месте читалась бы как «не загрузилось». */
        <EmptyPanel>Log file is empty.</EmptyPanel>
      ) : (
        <LogConsole tail={tail} />
      )}
    </TabBody>
  );
}
