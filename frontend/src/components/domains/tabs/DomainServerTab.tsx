import React from "react";

import { Domain, useReadDomainFacts } from "../../../api/domains";
import { Server } from "../../../api/servers";
import { anyRecordedOnly } from "../../../lib/domainDrift";
import { snapshotOf } from "../../../lib/domainFacts";
import { isTauri } from "../../../lib/runtime";
import { Btn } from "../../ui/Primitives";
import DomainFtpCard from "../DomainFtpCard";
import DomainSiteCard from "../DomainSiteCard";
import { HasSnapshot, RecordedNoteInLegend } from "../facts/fields";
import { SnapshotLine } from "../facts/SnapshotLine";
import { CardRow, TabBody, TabGroup } from "./TabLayout";

/**
 * Вкладка Server — ЕДИНСТВЕННОЕ место карточки, отвечающее на вопрос «что
 * развёрнуто на сервере»: доступ по FTP и сам сайт (путь, владелец, PHP, базы).
 * Сертификат отвечает на свой вопрос и живёт своей карточкой на Overview
 * (`DomainSslCard`) — из того же снимка, но не здесь.
 *
 * Сама вкладка — раскладка плюс четыре вещи, которые обязаны быть ОДНИМИ на
 * весь снимок, а не своими у каждой карточки; и все четыре про честность
 * измерения, а не про вёрстку:
 *
 * 1. **Свежесть и кнопка чтения.** Снимок ОДИН на всю карточку домена, снимает
 *    его кнопка отсюда, и его возраст печатается здесь же строкой слева.
 *    Карточка SSL на Overview читает тот же снимок и печатает его возраст у
 *    себя в шапке, чтобы не выдать протухшее измерение за свежее.
 * 2. **Провал последней попытки** (`fp_check_error`) — тоже один на снимок и
 *    стоит рядом с его возрастом: «проверка упала» и «данные устарели» — разные
 *    новости, и различить их можно, только когда они в одном месте.
 * 3. **Легенда «Сервер ещё не читали»** — один раз словами вместо решётки
 *    прочерков в полях. Вторая её фраза — про приглушённые значения — печатается
 *    только когда такие значения на экране ЕСТЬ, и то же условие гасит приписку
 *    «из provision, на сервере не проверено» под полями
 *    (`RecordedNoteInLegend`), потому что легенда несёт те же слова.
 * 4. **Разбор снимка — один** (`lib/domainFacts`) и уезжает в обе карточки
 *    пропом, причём урезанным: возраст и протухание карточкам не отдаются
 *    вовсе. Второй разбор внутри карточки совпадал бы с этим ровно до
 *    ближайшей правки.
 *
 * Пятого здесь больше нет. Им стояла заглушка Backups — карточка `COMING SOON`
 * про резервные копии, — и она дожила до своей функции: копии переехали на
 * собственную вкладку Backup (`DomainBackupTab`), которая читает их из того же
 * снимка. Осталась вкладка ровно про то, чем она названа.
 *
 * Зато прибавилось шестое, и не про снимок: кнопка **Provision**. Она стоит в
 * той же строке, что и «Проверить на сервере», потому что отвечает на тот же
 * вопрос с другой стороны — «что на этом сервере развёрнуто» против «что на нём
 * развернуть». Приехала она из строки списка доменов, где была иконкой ⚙ и
 * единственным входом в диалог с галочкой «создать БД»; сам запуск при этом
 * остался на странице — почему именно, разобрано у пропа `onProvision`.
 *
 * Правил о состоянии домена вкладка не заводит: порог протухания — в
 * `lib/domainFacts`, правило расхождения нашей записи с фактом — в
 * `lib/domainDrift`, его показ — в `domains/facts/fields`. Три экрана про
 * сервер уже разъезжались, когда правило жило в компоненте.
 *
 * Про язык подписей: проза вкладки английская, но три строки — «при
 * развёртывании: X», «из provision, на сервере не проверено» и «Сервер ещё не
 * читали» — оставлены по-русски дословно, как их задаёт план и повторяют его
 * acceptance criteria. Они один смысловой блок и приезжают вместе; вкладка к
 * тому же двуязычна и без них (кнопки «Проверить на сервере», «Задать
 * пароль»). Выравнивание языка — отдельный записанный долг плана, не эта
 * работа.
 */
export interface DomainServerTabProps {
  domain: Domain;
  /** Сервер домена, найденный в списке страницы; `undefined` — не найден. */
  server: Server | undefined;
  /**
   * «Сейчас» карточки: один раз на рендер, общее для всех её сроков. Пропом, а
   * не `Date.now()` внутри: возраст снимка и порог протухания обязаны считаться
   * от одного момента на всей карточке, иначе шапка, эта строка и карточка SSL
   * отвечают про один снимок по-разному — и тест не может задать «сейчас».
   */
  now: number;
  /**
   * Открыть диалог запуска provision. Именно ОТКРЫТЬ, а не запустить: диалог
   * рисует страница, она же и зовёт команду.
   *
   * Ниже — КАНОН этого разделения: карточка (`DomainDetailModal`), страница
   * (`pages/Domains.tsx`) и тесты ссылаются сюда, а не повторяют довод. Четыре
   * копии одного абзаца разошлись бы раньше, чем код под ними.
   *
   * Разделение выглядит лишним ровно до первого прогона. В ответе
   * `provision_domain` приезжают пароли БД и FTP, и существуют они там
   * один-единственный раз — на сервере их нет по определению. Показывает их
   * модалка показа-один-раз, которой владеет `DesktopWorkspace` (страница лишь
   * передаёт результат наверх через `onProvisionResult`), и владеет она ими
   * потому, что прогон идёт минутами SSH и certbot, а карточка домена за это
   * время закроется — её закрывает клик по подложке. Прими результат сюда, и
   * пароли к уже созданным на сервере аккаунтам терялись бы вместе с карточкой.
   * Поэтому кнопка здесь, а запуск остался там же, где и был.
   */
  onProvision: () => void;
  /**
   * Идёт ли provision ЭТОГО домена. Готовым булевым ответом, а не предикатом:
   * гейт читает `MutationCache` по `PROVISION_DOMAIN_KEY` и принадлежит
   * странице — она видит и запуск по `sdmp://`-ссылке, и массовый прогон, о
   * которых карточка знать не может и не должна.
   */
  isProvisioning: boolean;
}

export default function DomainServerTab({ domain, server, now, onProvision, isProvisioning }: DomainServerTabProps) {
  /**
   * Разбор снимка — общий (`lib/domainFacts`), а не свой: гейт `fp_facts_at` над
   * `fp_facts` и порог свежести обязаны быть одинаковыми у этой вкладки и у
   * карточки SSL на Overview, потому что снимок у них ОДИН.
   *
   * `noSnapshot` значит «удачного снимка не было ни разу», и тогда решётка
   * прочерков — враньё: прочерк в поле читается как «сервер спросили, там
   * пусто», а спрашивать мы ещё не ходили. Поэтому поля, которым нечего
   * сказать, прячутся целиком, а вместо них вкладка говорит это ОДИН раз
   * словами.
   */
  const snapshot = snapshotOf(domain.fp_facts, domain.fp_facts_at, now);
  const { noSnapshot } = snapshot;
  /**
   * Печатать ли ВТОРУЮ фразу легенды — и то же выражение гасит приписки под
   * полями: связка ровно та, что у карточки SSL на Overview (`DomainSslCard`),
   * и разведённые на два условия они разъехались бы в одну из двух сторон —
   * легенда без единого приглушённого значения либо приписка вдобавок к
   * легенде, говорящей то же самое.
   *
   * Условие не сводится к `noSnapshot`: у домена, ПЕРЕЕХАВШЕГО на другой
   * сервер, снимка нет и колонок provision тоже нет — бэкенд гасит их все при
   * смене `server_id`, — и обещать приглушённые значения было бы не о чем.
   * Первая фраза при этом остаётся: «сервер ещё не читали» объясняет пустые
   * карточки и верна независимо от provision.
   */
  const recordedShown = noSnapshot && anyRecordedOnly(domain, snapshot.facts);
  const desktop = isTauri();
  const read = useReadDomainFacts(domain.id);

  return (
    <TabBody>
      {/* Всё, что читается ИЗ СНИМКА, — одна названная область, и подпись его
          возраста стоит первой внутри неё.

          Иначе связи между ними нет никакой: глазами строка «Checked 8d ago ·
          stale» стоит над карточками и потому к ним относится, а на слух она
          отдельная реплика ниоткуда — войдя в «FTP Access» или «Site», человек
          не узнает, что данные недельной давности, а услышав саму строку, не
          узнает, что именно проверялось. Карточка SSL на Overview решает это
          иначе — кладёт возраст в свою шапку, — но здесь снимок один на две
          карточки, и повторить подпись в каждой значило бы завести два ответа
          про один снимок.

          Область названа, хотя сегодня она — всё содержимое вкладки: рядом с
          ней стояла заглушка Backups, и «Server snapshot» отделяло измеренное
          от неё. Имя остаётся не по инерции — оно и есть то, что связывает
          подпись возраста с карточками под ней на слух. */}
      <TabGroup label="Server snapshot">
        {/* Возраст снимка, провал последней попытки и кнопка чтения — общая
            шапка снимка (`facts/SnapshotLine`), одна на все вкладки, которые
            его показывают. Своя копия этих восьми строк была здесь и на Logs, и
            вторая уже успела потерять `fp_check_error`: провалившаяся проверка
            там не оставляла на экране ни следа. */}
        <SnapshotLine
          snapshot={snapshot}
          error={domain.fp_check_error}
          right={
            /* Обе кнопки — только десктоп: и чтение, и развёртывание идут по
               SSH, а веб на этом продукте не выполняет ничего (принцип №3
               CLAUDE.md). Раньше в вебе на месте provision стояла ссылка
               `sdmp://provision` из строки списка; здесь её нет намеренно —
               хост `provision` у `parseDeepLinkAction` знает один параметр
               `domainId`, `with_db` он не принимает, и ссылка, поставленная
               рядом с галочкой «создать БД», обещала бы выбор, который десктоп
               молча проглотит.

               Чего это стоит вебу, названо честно: одиночной ссылки в десктоп
               по домену там больше нет. Не осталось ничего — тоже неправда:
               выделив домен в списке, веб-пользователь получает
               `sdmp://bulk-provision` в панели массовых действий
               (`BulkActionToolbar`), и по одному домену она работает. Вернуть
               одиночную ссылку — отдельная правка, и делать её надо на
               карточке, а не в строке.

               Стоят они рядом, и это тот же вопрос, а не соседний: «что
               прочитано с сервера» и «что на сервере развернуть». Кнопка
               чтения первой — она дешёвая, безопасная и почти всегда нужна
               раньше; provision второй — он на минуты и создаёт сущности. */
            desktop ? (
              <div style={{ display: "flex", alignItems: "center", gap: 8 }}>
                <Btn
                  size="sm"
                  variant="secondary"
                  onClick={read.run}
                  disabled={read.pending}
                  title="Read SSL, FTP, PHP, site and databases from the server over one SSH session"
                >
                  {read.pending ? "Checking…" : "Check on server"}
                </Btn>
                {/* Второй клик стартовал бы вторую SSH-сессию с
                    create_site/create_ftp_account/certbot по тому же домену —
                    поэтому на время прогона кнопка и гаснет, и называется тем,
                    что происходит. `isProvisioning` приезжает со страницы, так
                    что гаснет она и от запуска по `sdmp://`-ссылке, и от
                    массового прогона, которых карточка не видит. */}
                <Btn
                  size="sm"
                  variant="secondary"
                  onClick={onProvision}
                  disabled={isProvisioning}
                  title="Create the site, its FTP account and its SSL certificate on the server over SSH"
                >
                  {isProvisioning ? "Provisioning…" : "Provision"}
                </Btn>
              </div>
            ) : null
          }
        />

        {/* Снимка не было ни разу — говорим это словами ОДИН раз, вместо того
            чтобы повторять прочерком в каждом поле, а подписью «из provision, на
            сервере не проверено» — под каждым из них. Вторая фраза несёт ту же
            подпись дословно и связывает её с приглушённым цветом значений; она
            же и гасит приписки у полей (`RecordedNoteInLegend` ниже) — приём,
            который карточка SSL на Overview повторяет своей легендой,
            англоязычной и своей. Печатается вторая фраза только при живых
            приглушённых значениях (`recordedShown`): у переехавшего домена
            колонок provision нет вовсе, и объяснять было бы нечего. Кнопка
            чтения — в строке выше (и только в десктопе: SSH в вебе нет). */}
        {noSnapshot ? (
          <div style={{ fontSize: 12.5, color: "#6b7280" }}>
            This server has not been read yet.{recordedShown ? " Dimmed values come from provision and were not verified on the server." : ""}
          </div>
        ) : null}

        {/* Два контекста, а не один: «снимка нет» прячет пустые поля, а гашение
            приписки «из provision, на сервере не проверено» объявляет ровно тот,
            кто печатает легенду с этими же словами — она стоит строкой выше и
            только под `noSnapshot`. Слитые в один, они гасили приписку и на
            карточке SSL (Overview), где никакой легенды нет. */}
        <HasSnapshot.Provider value={!noSnapshot}>
          <RecordedNoteInLegend.Provider value={recordedShown}>
            <CardRow>
              <DomainFtpCard domain={domain} server={server} snapshot={snapshot} />
              <DomainSiteCard domain={domain} snapshot={snapshot} />
            </CardRow>
          </RecordedNoteInLegend.Provider>
        </HasSnapshot.Provider>
      </TabGroup>
    </TabBody>
  );
}
