import React from "react";

import { STATUS_PILL, tokens } from "../../lib/designTokens";
import { domainStatusHint, domainStatusLabel, domainStatusVariant } from "../../lib/domainStatus";

/**
 * Бейдж статуса домена. Своей карты статусов у него больше нет: она была одной
 * из двух копий лестницы, и обе разошлись с бэкендом на `ns_ok` — домен в
 * штатном статусе получал серый бейдж «мы такого не знаем». Список живёт в
 * `lib/domainStatus`, здесь остаётся только показ.
 *
 * Имя и место — доменные, а не общие: карта статусов у него ровно одна, из
 * `lib/domainStatus`. `StatusBadge` в общем `components/` звал повесить его на
 * сервер или на задачу, а там любой валидный статус получил бы серый бейдж «мы
 * такого не знаем» — то есть ту самую поломку, из-за которой лестница и
 * заведена.
 *
 * Рисует он теперь СВОЮ пилюлю, а не общий `Badge`, и это не дубль примитива.
 * `Badge` держит старую палитру приложения и остаётся на ней намеренно: его
 * рисуют Servers, Cloudflare, Settings и ещё полдесятка экранов, и перекрасить
 * его значило бы протащить редизайн вкладки Domains на всё приложение заодно.
 * Форма же у пилюли макета своя (полная капля `radius.pill` против 6 у `Badge`
 * и у обеих пилюль строки, свой шрифт и разрядка), и пропсом её в общий
 * примитив не занести — это был бы `Badge` с переключателем «выглядеть как
 * другой Badge». Радиус — из палитры, а не числом: 99 стояло здесь литералом
 * при готовом `radius.pill` ровно с тем же значением, то есть третьей копией
 * знания о форме на одной странице.
 *
 * Цвета — из `STATUS_PILL` (`lib/designTokens`), и ключи там выведены из самой
 * лестницы: добавят вариант — карта перестанет собираться, пока в неё не
 * допишут цвета. Восемь статусов продукта раскладываются по пяти вариантам, и
 * все восемь пилюлю получают — макет назвал цветом три, но домен, чей статус
 * макет не нарисовал, не перестаёт от этого существовать.
 *
 * ПОДСКАЗКА ставится сама, из той же лестницы: пилюля называет ступень
 * настройки внутри SDMP, а не здоровье сайта, и различить эти два смысла по
 * одному слову («Deployed») нельзя. Ставить `title` у каждого вызывающего
 * значило бы получить два объяснения одному бейджу — ровно то расхождение,
 * ради запрета которого заведена сама лестница.
 *
 * Пропа `title`, которым подсказку можно было ПЕРЕБИТЬ, у бейджа больше нет —
 * и это то же правило абзацем выше, доведённое до конца: запрет на второе
 * объяснение был записан комментарием, а механизм его обхода оставался
 * включённым, то есть следующий вызывающий заводил бы расхождение одной
 * строкой, не дочитав до довода. Перебивала подсказку строка списка — текстом
 * провалившегося прогона, и размен сходился, пока тот текст был обрезан до
 * одного слова в колонке шириной 110 пикселей: подсказка бейджа была
 * единственным местом, где он читался целиком. Колонка ушла, текст переехал
 * под имя домена, виден там двумя строками и несёт свой полный `title`. Теперь
 * «одно объяснение на бейдж» — свойство сигнатуры, а не обещание в тексте.
 *
 * `cursor: help` — по той же причине, по какой он стоит у меток строки
 * (`RowBadge`): пилюля показывает ОДНО слово из чужого словаря, и о том, что
 * под ней есть объяснение, нельзя догадаться иначе как по курсору. Соседство
 * это ещё и уравнивает: без него о наличии подсказки заявляли бы как раз те
 * две метки, чьи подсказки менее ценны.
 */
export default function DomainStatusBadge({ status }: { status: string }) {
  const c = STATUS_PILL[domainStatusVariant(status)];
  return (
    <span
      title={domainStatusHint(status)}
      style={{
        display: "inline-block",
        cursor: "help",
        padding: "3px 10px",
        borderRadius: tokens.radius.pill,
        fontSize: 11,
        fontWeight: 600,
        letterSpacing: ".03em",
        whiteSpace: "nowrap",
        color: c.color,
        background: c.bg,
        border: `1px solid ${c.border}`,
      }}
    >
      {domainStatusLabel(status)}
    </span>
  );
}
