import React from "react";

import { type FieldSource } from "../../../lib/domainDrift";

/**
 * Показ полей, у которых ДВА источника: факт с сервера и наша запись из
 * provision.
 *
 * Всё это жило внутри секции сервера (сегодня — `tabs/DomainServerTab`) и было
 * там приватным ровно до тех пор, пока секция была одна. Вкладки развели её
 * содержимое по двум экранам —
 * SSL уехал на Overview, остальное осталось на Server, — и правило расхождения
 * стало нужно обоим. Скопировать его во второе место значило бы завести вторую
 * лестницу состояний рядом с первой: этот проект уже чинил такое трижды
 * (`lib/serverStatus`, `lib/domainFacts`, `lib/domainDrift` — все три сведены в
 * один модуль после того, как разъехались), и вторая копия `DRAW` разъехалась
 * бы так же молча.
 *
 * Само ПРАВИЛО («факт против записи») здесь не живёт — оно в `lib/domainDrift`.
 * Здесь только его показ: как выглядит каждый из трёх исходов.
 */

const NONE = "—";

/** Приглушённый серый — им набраны и приписки, и значения «только из provision». */
export const MUTED = "#9ca3af";

/** Ширина колонки подписи; приписка выравнивается под значение по ней же. */
export const KEY_WIDTH = 84;
export const KEY_GAP = 6;

/** Строка «подпись: значение» в стиле карточки; пустое — прочерк, а не пустота. */
export function Row({ k, v }: { k: string; v: React.ReactNode }) {
  const empty = v === null || v === undefined || v === "";
  return (
    <div style={{ display: "flex", gap: KEY_GAP, fontSize: 13, color: "#374151" }}>
      <b style={{ color: "#6b7280", fontWeight: 600, minWidth: KEY_WIDTH }}>{k}</b>
      <span style={{ wordBreak: "break-all" }}>{empty ? NONE : v}</span>
    </div>
  );
}

/**
 * Серая приписка под значением поля (12px, #9ca3af — как задано планом).
 *
 * Отступ считается от `KEY_WIDTH`, а колонка подписи задана `minWidth`, так что
 * выравнивание держится ровно пока ни одна подпись не шире 84px. Сегодня самая
 * длинная — «Databases»; заведёте длиннее — приписка съедет, и чинить это надо
 * будет здесь, а не подгонкой числа.
 */
function Note({ children }: { children: React.ReactNode }) {
  return (
    <div style={{ fontSize: 12, color: MUTED, paddingLeft: KEY_WIDTH + KEY_GAP, wordBreak: "break-all" }}>
      {children}
    </div>
  );
}

/**
 * Есть ли у блока снимок сервера. Контекст, а не проп у каждого поля.
 *
 * Проп пришлось бы повторять у каждого поля, и он необязателен по природе:
 * новое поле, заведённое через год без него, молча вернуло бы прочерк под
 * доменом, который ни разу не читали, — тип этого не поймает, а теста на новое
 * поле никто не напишет. Ответ же тут один на весь блок, и держать его в одном
 * месте честнее, чем повторять у каждого (та же причина, по которой три исхода
 * рисует одна карта `DRAW`, а не ветвление в каждом поле).
 */
export const HasSnapshot = React.createContext(true);

/**
 * Над сеткой уже стоит легенда, дословно говорящая «из provision, на сервере не
 * проверено». Ставит ЕЁ ЖЕ автор — тот, кто эту легенду рисует.
 *
 * Раньше приписку гасил `HasSnapshot`, и это был один контекст на два разных
 * вопроса. «Снимка нет» — свойство ДОМЕНА, одинаково верное на любом экране;
 * «эти слова уже сказаны выше» — свойство ОДНОГО места показа, верное только
 * там, где легенда нарисована. Пока потребитель был один, разница не стоила
 * ничего; с приездом карточки SSL на Overview слитый контекст молча погасил
 * приписку и там, где никакой легенды нет, — то есть смысл приглушённого
 * значения держался на одном сером цвете (а его ещё переназначит миграция на
 * токены). Поэтому вопроса теперь два, и второй по умолчанию `false`: экран,
 * который легенду не рисует, ничего не гасит.
 */
export const RecordedNoteInLegend = React.createContext(false);

/** Значение поля и приписка под ним — то, что отличает три исхода `FieldSource`. */
type Drawn = { value: React.ReactNode; note: React.ReactNode };

/**
 * Как выглядит поле при КАЖДОМ из трёх исходов — карта, а не ветвление по месту
 * в JSX.
 *
 * Ветвление по месту здесь было бы дырой в каждом поле: `FieldSource` —
 * размеченное объединение, но читателя ничто не заставляет разобрать все ветки,
 * и `src.kind === "drift" ? … : null` компилируется молча, превращая незнание
 * (`recorded-only`) в прочерк — ровно то, что запрещает принцип №6 CLAUDE.md.
 * `Record<FieldSource["kind"], …>` же не даст завести четвёртый исход, забыв его
 * нарисовать: пропуск станет ошибкой типов (тот же приём, что у `SSL_BADGE`).
 */
const DRAW: Record<FieldSource["kind"], (fact: React.ReactNode, recorded: React.ReactNode) => Drawn> = {
  // Факт есть, наша запись с ним совпала — дорисовывать нечего.
  agree: (fact) => ({ value: fact, note: null }),
  // Факт есть, наша запись другая — значением остаётся факт (он измерен), а
  // наша запись уходит вниз серой строкой.
  drift: (fact, recorded) => ({ value: fact, note: <Note>при развёртывании: {recorded}</Note> }),
  // Факта нет — значением становится наша запись, но приглушённо и с подписью:
  // выдать её за прочитанное с сервера нельзя.
  "recorded-only": (_fact, recorded) => ({
    value: <span style={{ color: MUTED }}>{recorded}</span>,
    note: <Note>из provision, на сервере не проверено</Note>,
  }),
};

/** Печать нашей записи по умолчанию — как есть, без переформатирования. */
const AS_IS = (recorded: string) => recorded;

/**
 * Поле секции: факт с сервера плюс то, что о нём говорит наша запись.
 *
 * Поведений ТРИ, и все три про честность, а не про вёрстку. Два приходят
 * контекстами — их вопросы про домен и про место показа, они не совпадают (см.
 * `HasSnapshot` и `RecordedNoteInLegend` выше); третье приходит пропом, потому
 * что его вопрос про КОНКРЕТНОЕ поле и ответ на него разный у соседних строк
 * одной карточки:
 *
 * 1. **Пустое поле прячется целиком** — под `HasSnapshot={false}`. Прочерк
 *    читается как «сервер спросили, там пусто», а спрашивать мы не ходили.
 * 2. **Приписка `recorded-only` не печатается** — под
 *    `RecordedNoteInLegend={true}`, то есть ровно там, где те же слова уже
 *    стоят легендой над сеткой. Повторённая под каждым полем на самом частом
 *    экране продукта (только что развёрнутый домен), она была бы теснотой без
 *    нового знания (принцип №2 CLAUDE.md), а приглушённый цвет значения
 *    связывает поле с легендой. Где легенды нет — приписка печатается: там она
 *    несёт то, чего больше нигде не сказано.
 *
 * 3. **Пустой список под снимком — «not read»** — под `list`. Это третье
 *    поведение и третья половина той же честности, только вопрос у него не
 *    «есть ли снимок», а «что значит пустота ИМЕННО ЗДЕСЬ»: у поля, факт
 *    которого список (аккаунты FTP, базы), пустота — незнание, а не измерение.
 *    `compareInList` в `lib/domainDrift` выносит ей ровно тот же вердикт, и
 *    провод два положения не различает вовсе (`ssh/fastpanel_facts.rs`
 *    схлопывает в `[]` и упавшую команду, и слабый mysql-фолбэк, про который
 *    его же комментарий говорит, что тот скорее всего не поймает ничего).
 *    Прочерк же читается как «спросили, там пусто»: одно свидетельство —
 *    один вердикт в правиле и на экране (принцип №6 CLAUDE.md), иначе
 *    импортированный домен с пустым `db_name` увидит уверенный прочерк там,
 *    где мы ничего не знаем.
 *
 *    Живёт здесь, а не отдельной функцией у карточек, ровно потому, что вторым
 *    аргументом такой функции приходилось бы передавать `!HasSnapshot` руками —
 *    флаг-близнец контекста, который уже читает эта строка. Перепутанный
 *    местами (`listFact(x, hasSnapshot)` вместо `!hasSnapshot`) он исправно
 *    компилируется и молча переворачивает правило; здесь же гейт читается из
 *    контекста, и перепутать его нечем.
 *
 * @param fact         значение, прочитанное с сервера (уже готовое к показу).
 * @param src          ответ `lib/domainDrift`; по умолчанию — «сказать нечего».
 * @param showRecorded как печатать нашу запись (даты — по-человечески).
 * @param hideEmpty    прятать пустое поле ДАЖЕ под снимком. Нужно там, где
 *                     факта не бывает по построению (`DB user`): прочерк в нём
 *                     обещал бы измерение, которого не будет никогда.
 * @param list         факт этого поля — СПИСОК: пустой под снимком печатается
 *                     как «not read» (см. пункт 3), без снимка — прячется, как
 *                     и всё остальное.
 */
export function FactRow({
  k,
  fact,
  src = { kind: "agree" },
  showRecorded,
  hideEmpty = false,
  list = false,
}: {
  k: string;
  fact?: React.ReactNode;
  src?: FieldSource;
  showRecorded?: (recorded: string) => React.ReactNode;
  hideEmpty?: boolean;
  list?: boolean;
}) {
  const hasSnapshot = React.useContext(HasSnapshot);
  const noteSaidInLegend = React.useContext(RecordedNoteInLegend);
  const recorded = src.kind === "agree" ? null : (showRecorded ?? AS_IS)(src.recorded);
  const drawn = DRAW[src.kind](fact, recorded);
  const shownNote = noteSaidInLegend ? null : drawn.note;
  // Подмена стоит ПОСЛЕ `DRAW`, и это единственное место, где она равносильна
  // прежней подмене до него: `recorded-only` рисует нашу запись, игнорируя
  // `fact` вовсе, а `drift` без факта невозможен по построению правила — то
  // есть пустым сюда доезжает ровно `agree`, ровно тот исход, которому «not
  // read» и адресован.
  const empty0 = drawn.value === null || drawn.value === undefined || drawn.value === "";
  const value =
    list && empty0 && hasSnapshot ? <span style={{ color: MUTED }}>not read</span> : drawn.value;
  const empty = value === null || value === undefined || value === "";
  // Прячем, только когда сказать нечего ВООБЩЕ: приписка без значения
  // невозможна по построению правила, но если бы стала возможной, она не должна
  // уехать с экрана вместе с пустотой.
  if ((hideEmpty || !hasSnapshot) && empty && shownNote === null) return null;
  return (
    // `data-source` — исход правила, ставший видимым: по нему тест отличает
    // «показано как факт» от «показано как наша запись», не привязываясь к
    // инлайн-цвету (тот уедет в токены вместе с редизайном).
    <div data-source={src.kind} style={{ display: "grid", gap: 2 }}>
      <Row k={k} v={value} />
      {shownNote}
    </div>
  );
}
