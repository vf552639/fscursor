import React from "react";

import { STALE_TEXT } from "../../ui/Primitives";
import { type Snapshot } from "./snapshot";

/**
 * Шапка снимка на вкладке: сколько ему лет, провалилась ли последняя попытка и
 * чем эту попытку повторить.
 *
 * Собрана из двух дословных копий (вкладки Server и Logs), и собрана не ради
 * восьми строк вёрстки, а ради трёх решений, которые обязаны быть одинаковыми
 * везде, где показан ОДИН И ТОТ ЖЕ снимок:
 *
 * 1. **Возраст печатается всегда.** Показание без возраста читается как
 *    сегодняшнее, каким бы старым ни было (принцип №6 CLAUDE.md).
 * 2. **Протухшее отличается цветом, а не только словом «· stale».** Цвет —
 *    общий `STALE_TEXT`, а не третий инлайн-литерал: он уже был скопирован в
 *    три места, а его смысл («данные есть, но старые», в отличие от серого
 *    «данных нет») объяснён ровно там, где он объявлен.
 * 3. **Провал последней ПОПЫТКИ стоит рядом с возрастом снимка.** «Проверка
 *    упала» и «данные устарели» — разные новости: сам снимок при провале не
 *    меняется (сервер не трогает `fp_facts`), и различить их можно, только
 *    когда они в одном месте. Вкладка, забывшая напечатать `fp_check_error`
 *    рядом со своей кнопкой чтения, выглядит после провала ровно так же, как до
 *    клика, — то есть молча съедает единственный ответ, который у неё был.
 *
 * Кнопка приходит слотом `right`, а не пропами: вкладки решают ПО-РАЗНОМУ, когда
 * её показывать (Server — всегда в десктопе, Logs — только пока снимка нет, см.
 * её файл), и это их решение, а не общее. Общее — где кнопка стоит и что рядом
 * с ней напечатано.
 *
 * Живёт в `facts/`, а не в `tabs/TabLayout`: `TabLayout` знает только про
 * геометрию вкладки (столбец, зазор, число колонок) и ни про какие данные, а
 * это — показ САМОГО снимка, сосед `snapshot.ts` и `fields.tsx`.
 */
export function SnapshotLine({
  snapshot,
  error,
  right,
}: {
  /** Разобранный снимок; отсюда берутся возраст и протухание. */
  snapshot: Pick<Snapshot, "stale" | "freshness">;
  /** `fp_check_error` домена — провал ПОСЛЕДНЕЙ попытки, не снимка. */
  error?: string | null;
  /** Кнопка чтения (или что угодно другое) в правом краю строки. */
  right?: React.ReactNode;
}) {
  return (
    <>
      <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", gap: 12 }}>
        <span style={{ fontSize: 13, color: snapshot.stale ? STALE_TEXT : "#6b7280" }}>
          {snapshot.freshness}
        </span>
        {right}
      </div>
      {error ? (
        // `overflowWrap` — текст ЧУЖОЙ: это ответ ssh или FastPanel, и в нём
        // сидит неразрывный токен (путь, ключ хоста, URL). Без переноса он
        // распирает модалку и даёт ей горизонтальную полосу, запрещённую
        // `design-brief.md` §11. Тот же приём и той же формулировкой одет
        // `Last error` в карточке и ошибки записи в полях ряда связей.
        <div role="alert" style={{ fontSize: 12, color: "#b91c1c", overflowWrap: "anywhere" }}>
          Last check failed: {error}
        </div>
      ) : null}
    </>
  );
}
