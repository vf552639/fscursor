import React, { useState } from "react";

import { clip, errorText } from "../../api/cfAutoBind";
import { Domain, useUpdateDomain } from "../../api/domains";
import {
  expiryState,
  expiryTextColor,
  expiryTextWeight,
  formatExpiry,
  formatExpiryDate,
} from "../../lib/domainExpiry";

/** Тот же тон отказа, что у полей ряда связей. */
const ERROR_TEXT = "#991b1b";

/**
 * Срок домена в шапке карточки — и правка его на месте.
 *
 * Считает и печатает здесь только `lib/domainExpiry`: дата — `formatExpiryDate`,
 * остаток словами — `formatExpiry`, цвет и начертание — `expiryTextColor` и
 * `expiryTextWeight`. Общий `fmtDate` из `ui/Primitives` для этого поля НЕ
 * годится, и это не вкусовщина: `expiry_date` приходит датой без времени, а
 * `fmtDate` печатает её в зоне читателя — западнее UTC карточка называла бы
 * предыдущий день и расходилась бы с колонкой списка (`DomainRow`), которая
 * печатает ту же дату этим же модулем. Подробности — над `formatExpiryDate`.
 *
 * Пустое состояние — «set date», а не общий прочерк `NO_VALUE`. Прочерк —
 * ответ «мы не знаем» там, где значение только ПОКАЗЫВАЮТ; здесь же оно ещё и
 * правится, и прочерк на кнопке читается как «тут делать нечего». Название
 * пробела вместе с лекарством — то же правило, по которому в карточке завёлся
 * селект регистратора: диагноз без лекарства отправляет человека искать, чем
 * починить то, что он видит.
 *
 * Своего контейнера у поля нет — оно отдаёт фрагмент: значение (кнопка либо
 * инпут) и, отдельным узлом, строку ошибки записи. Отсюда требование к месту
 * вставки, и оно НЕ подразумевается само: вставлять поле можно только в
 * контейнер с переносом (`display: inline-flex` + `flexWrap: "wrap"`, как в
 * мета-ряду шапки). В обычной строке ошибка встанет в одну линию со значением
 * и распрёт ряд, а перенести её будет нечем.
 *
 * Цвет пустого состояния взят у модуля (`unknown` → `#9ca3af`), а не из макета
 * (`#94a3b8`): рядом в той же строке стоят подписи и бейджи, крашенные общей
 * лестницей, и третий почти совпадающий серый читался бы не как решение, а как
 * поломка вёрстки (см. комментарий над `expiryTextColor`).
 */
export default function DomainExpiryField({ domain, now }: { domain: Domain; now: number }) {
  const update = useUpdateDomain(domain.id);
  /**
   * Текст в открытом поле — СВОЙ, а не привязка к показанному значению.
   *
   * Привязка (`value={shown}`) заставляла поле драться с тем, кто правит дату
   * с клавиатуры. Нативный `<input type="date">` отдаёт `""` за любой
   * незаконченный набор, а React после события, не изменившего состояние,
   * ВОССТАНАВЛИВАЕТ значение управляемого инпута из пропса — то есть посреди
   * набора поле прыгало обратно на прежнюю дату, и снять срок было нельзя
   * вовсе: пустое поле не доживало до `blur`, на котором снятие
   * подтверждается. `null` — поле закрыто, черновика нет.
   */
  const [draft, setDraft] = useState<string | null>(null);
  const editing = draft !== null;
  /**
   * Правка в полёте: что человек выбрал и КАКОЙ была строка домена в тот
   * момент. `null` — правки не было.
   *
   * Своя память нужна ровно потому, что своей строки домена у карточки нет:
   * `domain` приезжает пропсом и обновляется только после того, как доедет
   * рефетч по инвалидации. Без неё поле возвращалось бы к СТАРОЙ дате сразу
   * после выбора — то есть выглядело бы так, будто правку потеряли.
   *
   * `base` — не украшение. Без него условие «показывать выбранное» пришлось бы
   * писать как «строка домена не равна выбранному», а это ДРУГОЙ вопрос: он
   * отвечает «да» и тогда, когда сервер сохранил не ровно присланную строку, и
   * тогда, когда `expiry_date` через полчаса поменял кто-то ещё (синк
   * регистратора, write-back полной настройки — любая инвалидация
   * `domainsKeys.all`). В обоих случаях поверх свежей правды вставала бы дата
   * из давно законченной правки, и снять её было бы нечем до закрытия
   * карточки. С `base` наложение живёт ровно до первого движения строки —
   * куда бы она ни двинулась.
   */
  const [edit, setEdit] = useState<{ value: string | null; base: string | null } | null>(null);

  /**
   * Наложение снимается двумя событиями: запись провалилась (тогда правды в
   * выбранном нет — на экране обязано стоять то, что лежит в базе, и рядом
   * причина) либо строка домена сдвинулась с той, поверх которой правка
   * начиналась. Условие про строку, а не про `isPending`: между успехом
   * мутации и приездом рефетча `isPending` уже ложен, а старая дата в пропсе
   * ещё стоит — и мигание вернулось бы именно там.
   */
  const pendingEdit = edit !== null && !update.isError && (domain.expiry_date ?? null) === edit.base;
  const shown = pendingEdit ? edit.value : domain.expiry_date;

  const state = expiryState(shown, now);
  const label =
    state === "unknown" ? "set date" : `${formatExpiryDate(shown)} · ${formatExpiry(shown, now)}`;
  /** Ошибку надо не только показать, но и связать с полем: она объясняет его состояние. */
  const errorId = `domain-expiry-error-${domain.id}`;

  /**
   * Единственный вход в запись — и у выбора даты (`change`), и у подтверждения
   * снятия (`blur` на пустом поле).
   *
   * Guard несущий, а не декоративный: снятие подтверждается уходом из поля, а
   * уходят и из поля, которое было пустым С САМОГО НАЧАЛА — у домена без
   * срока, открытого и закрытого без единой правки. Без сравнения такое
   * любопытство стоило бы PUT'а, инвалидации списка доменов и перерисовки
   * полэкрана, а «сохранение», ничего не меняющее, ещё и обманывает.
   *
   * Сравниваем с ПОКАЗАННЫМ, а не со строкой домена. Разойтись они успевают:
   * человек выбрал дату, а через секунду передумал и вернул прежнюю — запись
   * первой ещё в полёте либо уже прошла, но рефетч не доехал, и в пропсе
   * по-прежнему стоит та самая «прежняя». Сравнение с пропсом объявило бы
   * возврат бездействием — и на сервере молча осталась бы дата, от которой
   * человек только что отказался.
   */
  function commit(value: string) {
    // Пустой инпут — это СНЯТЬ срок, и записывать его надо `null`: пустая
    // строка в `expiry_date` не «нет даты», а нечитаемая дата, и бэкенду она
    // приедет отказом валидации либо мусором в колонке.
    const next = value ? value : null;
    if (next === (shown ?? null)) return;
    setEdit({ value: next, base: domain.expiry_date ?? null });
    update.mutate({ expiry_date: next });
  }

  return (
    <>
      {editing ? (
        <input
          type="date"
          // Подпись «Expires:» стоит соседним узлом и с полем ничем не связана
          // — без своего имени поле звучит как «поле ввода даты» вообще.
          aria-label="Expiry date"
          aria-describedby={update.isError ? errorId : undefined}
          autoFocus
          // Значение — черновик (см. `draft`): открытое поле показывает ровно
          // то, что человек набрал, включая незаконченное и пустое. Правда о
          // сохранённом при этом не теряется: её называет ЗАКРЫТОЕ поле, и
          // после провала записи оно возвращается к дате из строки домена.
          value={draft ?? ""}
          // ПУСТОЕ значение записью не считается, и это не мелочь: `""` здесь
          // означает не «срока нет», а «дата ещё не дособрана» — ровно это
          // отдаёт нативный инпут, пока человек стирает или набирает сегмент.
          // Записанное сразу, оно снимало бы срок домена без единого вопроса, а
          // вторым PUT'ом вдогонку давало бы гонку двух записей из одного хука:
          // севший последним `null` оставил бы базу пустой под уверенно
          // нарисованной новой датой. Снять срок по-прежнему можно — но это
          // надо ПОДТВЕРДИТЬ уходом из поля.
          onChange={(e) => {
            setDraft(e.target.value);
            if (e.target.value) commit(e.target.value);
          }}
          // Уход из поля закрывает правку — и записывает РОВНО ОДИН случай:
          // пустое поле. Только его `change` пропускает намеренно, и только оно
          // поэтому требует подтверждения; всё остальное там уже записано.
          // Слать на `blur` что попало нельзя: после провала записи показанным
          // снова становится сохранённое, отвергнутая дата в поле выглядела бы
          // новой правкой — и простой уход из поля дёргал бы повтор, которого
          // никто не просил, заодно снова рисуя отвергнутую дату принятой.
          //
          // Отдельной кнопки «готово» нет намеренно: дата, выбранная в пикере,
          // записана ещё на `change`.
          //
          // Поле НЕ выключается на время записи (в отличие от селекта
          // регистратора рядом): выключенный инпут теряет фокус, и `blur`, на
          // котором держится подтверждение снятия, пришёл бы сам собой посреди
          // чужой правки. Обратной связи это не стоит — пока запись идёт, на
          // экране стоит выбранное значение, а провал называет себя строкой
          // ошибки.
          onBlur={(e) => {
            if (!e.target.value) commit("");
            setDraft(null);
          }}
          style={{
            border: "1px solid #cbd5e1",
            borderRadius: 7,
            padding: "3px 8px",
            fontSize: 13,
            fontFamily: "inherit",
            color: "#0f172a",
          }}
        />
      ) : (
        <button
          type="button"
          // Имя составное: голое «Expiry date» на кнопке ЗАМЕНИЛО бы её текст
          // для скринридера, то есть отняло бы у него саму дату, а один текст
          // кнопки («01.09.2026 · in 10 days») не говорит, чей это срок.
          aria-label={`Expiry date: ${label}`}
          aria-describedby={update.isError ? errorId : undefined}
          title="Edit expiry date"
          // Черновик заводится от ПОКАЗАННОГО: правка начинается с того, что
          // человек видит, — иначе поле открывалось бы пустым поверх даты,
          // которая только что стояла на экране.
          onClick={() => setDraft(shown ?? "")}
          style={{
            border: "none",
            background: "none",
            padding: 0,
            cursor: "pointer",
            fontSize: 13,
            fontFamily: "inherit",
            color: expiryTextColor(state),
            fontWeight: expiryTextWeight(state),
            // Пунктирное подчёркивание — единственный знак, что значение
            // правится: кнопка здесь не выглядит кнопкой ни фоном, ни рамкой.
            borderBottom: "1px dashed #94a3b8",
          }}
        >
          {label}
        </button>
      )}
      {update.isError ? (
        // `clip` и перенос по любому месту — текст ЧУЖОЙ (тело ответа бэкенда),
        // тот же приём, что у ошибок записи в полях ряда связей: без обрезки
        // одна такая строка распирает шапку, без `overflowWrap` — уезжает за
        // край.
        <span
          id={errorId}
          role="alert"
          style={{ fontSize: 12, color: ERROR_TEXT, overflowWrap: "anywhere" }}
        >
          Could not save: {clip(errorText(update.error))}
        </span>
      ) : null}
    </>
  );
}
