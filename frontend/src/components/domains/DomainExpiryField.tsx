import React, { useState } from "react";

import { clip, errorText } from "../../api/cfAutoBind";
import { Domain, useUpdateDomain } from "../../api/domains";
import { tokens } from "../../lib/designTokens";
import {
  expiryState,
  expiryTextColor,
  expiryTextWeight,
  formatExpiry,
  formatExpiryDate,
} from "../../lib/domainExpiry";
import DateField from "../ui/DateField";

/**
 * Тон отказа — ОДИН на оба красных сообщения поля.
 *
 * Их тут два и они разные по смыслу: ошибка разбора («так не пишут дату») живёт
 * внутри `DateField` и красится `tokens.semantic.danger.text`, ошибка записи
 * («сервер не принял») — здесь. Стоят они в одном поле, иногда одновременно, и
 * два почти совпадающих красных (#b91c1c и #991b1b) читались бы не как два
 * источника, а как поломка вёрстки — ровно то, про что CLAUDE.md говорит
 * «почти совпадающий оттенок хуже явно другого».
 *
 * Поэтому здесь токен, а не хекс соседних полей ряда связей
 * (`DomainServerField`, `DomainRegistrarField`, `DomainCloudflareField` — у всех
 * трёх #991b1b, мимо палитры). Свести к токену ещё и их — работа не этой фазы:
 * там своя пачка файлов и своя приёмка. Внутри ОДНОГО поля расхождение
 * недопустимо, между соседними полями оно хотя бы не бросается в глаза.
 */
const ERROR_TEXT = tokens.semantic.danger.text;

/**
 * Цвет ПРИГЛАШЕНИЯ «set date» — свой, а не из лестницы состояний срока.
 *
 * Кнопка в этом состоянии не показывает значение, она зовёт его завести, а
 * `expiryTextColor("unknown")` красит незнание — то есть прочерк, знак «тут
 * ничего нет». Тон у него соответствующий (`text.disabled`, он же тон рамки,
 * 1.48:1 на белом), и на кнопке это давало призыв к действию, который почти не
 * видно. Разъехались тут не цвета, а роли: состояние и действие — разные вещи,
 * и общего цвета им никто не обещал.
 *
 * `text.muted` — тот же тон, каким набрана подпись «Expires:» слева от кнопки:
 * приглашение звучит ровно голосом подписи, тише настоящей даты (`text.ink`) и
 * читаемо — 4.76:1 на белом фоне модалки, то есть AA для обычного текста.
 * Пунктирное подчёркивание рядом остаётся вторым каналом: цвет говорит «это
 * пока пусто», подчёркивание — «это правится».
 *
 * Значение со сроком (`ok`/`soon`/`expired`) по-прежнему красит лестница: там
 * кнопка ПОКАЗЫВАЕТ состояние, и расходиться со списком ей нельзя.
 */
const SET_DATE_TEXT = tokens.text.muted;

/**
 * Последний ответ поля о СОСТОЯНИИ набранной строки — и единственное, из чего
 * берётся значение для записи.
 *
 * `DateField` держит сырой текст у себя и наружу отдаёт уже разобранное
 * (`onParsed`/`onParseError`), поэтому у карточки нет ни своего текста, ни
 * права разбирать его самой. Позвать `parseExpiryInput` здесь было бы вторым
 * местом разбора — ровно тем дублем, ради устранения которого разбор и печать
 * поселены в один модуль (`lib/domainExpiry`): разъехавшись, они дают поле,
 * которое не принимает обратно строку, им же самим и показанную.
 *
 * `error` — не «ошибка поля», а «строку прочитать не удалось». Записывать при
 * таком ответе нечего: непонятная строка на сервер не уходит вовсе, и объясняет
 * её сам примитив своей красной строкой.
 */
type Read = { kind: "value"; iso: string | null } | { kind: "error" };

/**
 * Срок домена в шапке карточки — и правка его на месте.
 *
 * Считает и печатает здесь только `lib/domainExpiry`: дата — `formatExpiryDate`,
 * остаток словами — `formatExpiry`, цвет и начертание — `expiryTextColor` и
 * `expiryTextWeight`. Общий `fmtDate` из `ui/Primitives` для этого поля НЕ
 * годится, и это не вкусовщина: `expiry_date` приходит датой без времени, а
 * `fmtDate` печатает её в зоне читателя — западнее UTC карточка называла бы
 * предыдущий день и расходилась бы с колонкой списка (`DomainRow`), которая
 * печатает ту же дату этим же модулем. Подробности — над `formatExpiryDate`.
 *
 * Правится дата ТЕКСТОМ (`ui/DateField`), а не нативным `<input type="date">`,
 * который стоял здесь раньше: в WKWebView десктопа он не принимал ввод с
 * клавиатуры вовсе — цифры не вставали в сегменты, календарь не открывался, —
 * то есть `input.value` был пуст всегда, и все входы в запись читали пустоту.
 * Поле, которое молча не берёт ввод, хуже отсутствующего.
 *
 * Пустое состояние — «set date», а не общий прочерк `NO_VALUE`. Прочерк —
 * ответ «мы не знаем» там, где значение только ПОКАЗЫВАЮТ; здесь же оно ещё и
 * правится, и прочерк на кнопке читается как «тут делать нечего». Название
 * пробела вместе с лекарством — то же правило, по которому в карточке завёлся
 * селект регистратора: диагноз без лекарства отправляет человека искать, чем
 * починить то, что он видит.
 *
 * Своего контейнера у поля нет — оно отдаёт фрагмент: значение (кнопка либо
 * блок правки) и, отдельным узлом, строку ошибки записи. Отсюда требование к
 * месту вставки, и оно НЕ подразумевается само: вставлять поле можно только в
 * контейнер с переносом (`display: inline-flex` + `flexWrap: "wrap"`, как в
 * мета-ряду шапки). В обычной строке ошибка встанет в одну линию со значением
 * и распрёт ряд, а перенести её будет нечем.
 *
 * Цвет ЗАПОЛНЕННОГО значения берётся у модуля (`expiryTextColor`), а не пишется
 * здесь по макету: рядом в той же строке стоят подписи и бейджи, крашенные
 * общей лестницей, и третий почти совпадающий серый читался бы не как решение,
 * а как поломка вёрстки (см. комментарий над `expiryTextColor`). У пустого
 * состояния цвет теперь СВОЙ (`SET_DATE_TEXT`), и это не отступление от того же
 * правила, а его применение: «set date» — приглашение к действию, а лестница
 * красит состояния срока; общий цвет им никто не обещал, а бледность,
 * законная у прочерка в списке, на кнопке означала «нажимать нечего».
 */
export default function DomainExpiryField({ domain, now }: { domain: Domain; now: number }) {
  const update = useUpdateDomain(domain.id);
  /**
   * Открыта ли правка. Текста здесь нет намеренно: набранное принадлежит
   * `DateField` и родителю не показывается вовсе.
   *
   * Так починен один из двух кандидатов на причину исходного дефекта: раньше
   * значение открытого поля диктовала карточка, а React после события, не
   * изменившего состояние, ВОССТАНАВЛИВАЕТ значение управляемого инпута из
   * пропса — то есть посреди набора поле прыгало обратно. Теперь этого не может
   * случиться по построению: `defaultValue` у примитива — семя, читаемое один
   * раз, и сбрасывается поле только размонтированием (закрытием правки).
   */
  const [editing, setEditing] = useState(false);
  /** Что примитив в последний раз сказал о набранной строке (см. `Read`). */
  const [read, setRead] = useState<Read>({ kind: "value", iso: null });
  /**
   * Правка в полёте: что человек ввёл и КАКОЙ была строка домена в тот
   * момент. `null` — правки не было.
   *
   * Своя память нужна ровно потому, что своей строки домена у карточки нет:
   * `domain` приезжает пропсом и обновляется только после того, как доедет
   * рефетч по инвалидации. Без неё поле возвращалось бы к СТАРОЙ дате сразу
   * после записи — то есть выглядело бы так, будто правку потеряли.
   *
   * `base` — не украшение. Без него условие «показывать выбранное» пришлось бы
   * писать как «строка домена не равна выбранному», а это ДРУГОЙ вопрос: он
   * отвечает «да» и тогда, когда сервер сохранил не ровно присланную строку, и
   * тогда, когда `expiry_date` через полчаса поменял кто-то ещё (синк
   * регистратора, write-back полной настройки — любая инвалидация
   * `domainsKeys.all`). В обоих случаях поверх свежей правды вставала бы дата
   * из давно законченной правки, и снять её было бы нечем до закрытия
   * карточки. С `base` наложение живёт ровно до первого движения строки —
   * куда бы она ни двинулась.
   */
  const [edit, setEdit] = useState<{ value: string | null; base: string | null } | null>(null);

  /**
   * Наложение снимается двумя событиями: запись провалилась (тогда правды в
   * выбранном нет — на экране обязано стоять то, что лежит в базе, и рядом
   * причина) либо строка домена сдвинулась с той, поверх которой правка
   * начиналась. Условие про строку, а не про `isPending`: между успехом
   * мутации и приездом рефетча `isPending` уже ложен, а старая дата в пропсе
   * ещё стоит — и мигание вернулось бы именно там.
   */
  const pendingEdit = edit !== null && !update.isError && (domain.expiry_date ?? null) === edit.base;
  const shown = pendingEdit ? edit.value : domain.expiry_date;

  const state = expiryState(shown, now);
  const label =
    state === "unknown" ? "set date" : `${formatExpiryDate(shown)} · ${formatExpiry(shown, now)}`;
  /** Ошибку надо не только показать, но и связать с полем: она объясняет его состояние. */
  const errorId = `domain-expiry-error-${domain.id}`;
  /** Подпись про пустое поле — тоже описание поля, а не текст рядом с ним. */
  const hintId = `domain-expiry-hint-${domain.id}`;

  /**
   * Открыть правку. Семя примитива — ПОКАЗАННОЕ значение: правка начинается с
   * того, что человек видит, иначе поле открывалось бы пустым поверх даты,
   * которая только что стояла на экране.
   *
   * `read` заводится тем же значением не ради записи, а чтобы в состоянии не
   * оставалось ответа от ПРОШЛОЙ правки. Настоящий ответ приезжает мгновением
   * позже: примитив рассказывает о себе с монтирования — в том числе и о
   * нечитаемом семени, которое он показывает пустым полем.
   */
  function open() {
    setRead({ kind: "value", iso: shown ?? null });
    setEditing(true);
  }

  /**
   * Единственное МЕСТО записи — на все три входа (✓, Enter, уход из поля).
   * Входов три, гардов один набор.
   *
   * Почему запись НЕ висит на `onParsed`: примитив зовёт его на каждое
   * изменение текста и ещё раз на монтировании, а приложение обёрнуто в
   * `React.StrictMode` — в dev монтирование двойное. Запись оттуда давала бы
   * два PUT'а на одно только открытие поля и по PUT'у на каждый набранный
   * символ. Колбэки примитива — это «вот моё состояние», а не «сохрани меня».
   *
   * Гарды по порядку, и каждый сторожит своё:
   *
   * 1. Запись уже идёт. Второй PUT из того же хука — гонка: севший последним
   *    ответ решает, что лежит в базе, а на экране к тому моменту нарисован
   *    исход первого. Заодно это ответ на «можно ли нажать ✓ дважды»: нельзя,
   *    и не только мышью — Enter и уход из поля тоже сюда упираются.
   * 2. Строка не разобралась. Непонятное на сервер не уходит вовсе (это
   *    отдельный критерий приёмки), а объясняет её сам примитив — своей
   *    красной строкой, не нашей. Поле при этом НЕ закрывается: закрытое, оно
   *    размонтировало бы объяснение раньше, чем его успели прочесть.
   * 3. Отвергнутая дата не повторяется УХОДОМ ИЗ ПОЛЯ. После провала записи
   *    показанным снова становится сохранённое, и набранная дата выглядит новой
   *    правкой — простой уход дёргал бы повтор, которого никто не просил, и
   *    заново рисовал бы отвергнутое принятым. Ретрай остаётся доступен явным
   *    действием: ✓ или Enter.
   * 4. Записывать нечего — значение уже стоит. Гард несущий, а не
   *    декоративный: уходят и из поля, которое было пустым С САМОГО НАЧАЛА — у
   *    домена без срока, открытого и закрытого без единой правки. Без сравнения
   *    такое любопытство стоило бы PUT'а, инвалидации списка доменов и
   *    перерисовки полэкрана, а «сохранение», ничего не меняющее, ещё и
   *    обманывает.
   *
   *    Сравниваем с ПОКАЗАННЫМ, а не со строкой домена. Разойтись они успевают:
   *    человек записал дату, а через минуту передумал и вернул прежнюю — рефетч
   *    ещё не доехал, и в пропсе по-прежнему стоит та самая «прежняя».
   *    Сравнение с пропсом объявило бы возврат бездействием — и на сервере
   *    молча осталась бы дата, от которой человек только что отказался.
   *
   * Закрывается правка ровно двумя исходами: писать было нечего либо запись
   * УДАЛАСЬ (`onSuccess`). Провал оставляет поле открытым с набранным — это
   * рабочее место: сервер отверг дату, поправят её здесь же, и стирать
   * набранное значило бы заставить набирать заново.
   */
  function commit(from: "blur" | "explicit") {
    if (update.isPending) return;
    if (read.kind === "error") return;
    const next = read.iso;
    if (from === "blur" && update.isError && edit !== null && next === edit.value) return;
    if (next === (shown ?? null)) {
      setEditing(false);
      return;
    }
    setEdit({ value: next, base: domain.expiry_date ?? null });
    update.mutate({ expiry_date: next }, { onSuccess: () => setEditing(false) });
  }

  return (
    <>
      {editing ? (
        // Колонка: ряд «поле + ✓» и подпись под ним. Подпись отдельным рядом, а
        // не flex-итемом того же ряда, — иначе её ширина решала бы, где стоит
        // кнопка.
        <span
          style={{ display: "inline-flex", flexDirection: "column", alignItems: "flex-start", gap: 4 }}
        >
          <span style={{ display: "inline-flex", flexWrap: "wrap", alignItems: "center", gap: 6 }}>
            <DateField
              // Подпись «Expires:» стоит соседним узлом и с полем ничем не
              // связана — без своего имени поле звучит как «поле ввода даты»
              // вообще.
              aria-label="Expiry date"
              // Оба описания разом, и оба — про состояние поля: что делает
              // пустая строка и почему прошлая запись не прошла. Свою ошибку
              // разбора примитив ДОПИШЕТ сюда сам, первой.
              aria-describedby={[hintId, update.isError ? errorId : null].filter(Boolean).join(" ")}
              autoFocus
              // Семя, а не диктат: карточка называет начальное значение и
              // больше в набранное не вмешивается (см. `editing`).
              defaultValue={shown ?? null}
              onParsed={(iso) => setRead({ kind: "value", iso })}
              onParseError={() => setRead({ kind: "error" })}
              // Уход из поля — вход в запись, а не только закрытие. Своё
              // (показ отложенной ошибки) примитив делает до нас.
              //
              // Поле НЕ выключается на время записи: выключенный инпут теряет
              // фокус, и `blur`, на котором держится этот вход, пришёл бы сам
              // собой посреди чужой правки. Обратной связи это не стоит — пока
              // запись идёт, на месте ✓ стоит «Saving…», а провал называет себя
              // строкой ошибки.
              onBlur={() => commit("blur")}
              // Enter — второй вход в запись, Escape — отказ от правки.
              //
              // Escape закрывает БЕЗ записи и без отмены уже ушедшей: снять
              // сохранённое на сервере он не обещает — только выйти из правки.
              // Набранное при этом теряется, и вернуть его нечем: сброс
              // примитива — это размонтирование, другого у него нет и по
              // построению быть не должно.
              onKeyDown={(e) => {
                if (e.key === "Enter") {
                  e.preventDefault();
                  commit("explicit");
                } else if (e.key === "Escape") {
                  e.preventDefault();
                  setEditing(false);
                }
              }}
              style={{
                // Геометрия мета-ряда, а не формы: у примитива в дефолте стоит
                // просторное поле карточки сервера, а здесь значение живёт
                // внутри строки подписей и бейджей. Ширины в дефолте нет
                // намеренно — её назначает место вставки; 104px хватает и
                // набранной дате, и плейсхолдеру `DD.MM.YYYY`.
                padding: "3px 8px",
                fontSize: 13,
                borderRadius: 7,
                width: 104,
                // ПОРЯДОК В РЯДУ, а не украшение. Красную строку разбора
                // примитив рисует сразу за полем — то есть в этом ряду она
                // встала бы МЕЖДУ полем и ✓ и толкала бы кнопку вбок ровно в
                // тот момент, когда по ней собираются нажать. Явный `order`
                // ставит кнопку вплотную к полю, а объяснение — после неё:
                // кнопка не двигается вовсе. Порядку фокуса это не вредит,
                // потому что переставлены не два фокусируемых узла, а
                // фокусируемые относительно текста.
                order: -2,
              }}
            />
            {update.isPending ? (
              // Кнопки на время записи нет ВОВСЕ, а не «она выключена»: нечего
              // нажимать — нечего и задваивать. `role="status"` — чтобы про
              // «идёт запись» узнал и тот, кто экран не видит.
              <span role="status" style={{ fontSize: 12, color: tokens.text.muted, order: -1 }}>
                Saving…
              </span>
            ) : (
              <button
                type="button"
                // Голая галочка скринридеру не говорит ничего — имя обязательно.
                aria-label="Save expiry date"
                title="Save expiry date"
                // Клик по ✓ начинается с `blur` поля, и без этого мышиный путь
                // отличался бы от клавиатурного. Но гасим `blur` НЕ всегда:
                // если строка не разобралась, уход из поля — единственное, чем
                // примитив показывает объяснение короткой, но законченной
                // записи (`01.09.26` до полной длины не дорастает). Погасив
                // `blur` и здесь, кнопка съедала бы показ ошибки целиком:
                // человек жмёт ✓ и не происходит ровно ничего.
                //
                // Задержкой («обычно успевает») это не лечится: успевает она
                // не всегда, и отладить такой промах нечем.
                onMouseDown={(e) => {
                  if (read.kind !== "error") e.preventDefault();
                }}
                onClick={() => commit("explicit")}
                style={{
                  order: -1,
                  border: `1px solid ${tokens.border.control}`,
                  borderRadius: 7,
                  background: tokens.surface.subtle,
                  color: tokens.text.body,
                  padding: "3px 8px",
                  fontSize: 13,
                  lineHeight: 1.2,
                  fontFamily: "inherit",
                  cursor: "pointer",
                }}
              >
                ✓
              </button>
            )}
          </span>
          {/*
            Снятие срока названо СЛОВАМИ. Пустое поле здесь — распоряжение
            стереть дату, и догадаться об этом неоткуда: у соседних полей
            карточки пустое значение означает «не заполнено».

            Тон тихий, но читаемый (`text.faint`, 2.85:1 — подпись, а не
            призыв). `text.disabled` сюда не годится: это тон РАМКИ, 1.48:1, и
            живому слову он не положен.
          */}
          <span id={hintId} style={{ fontSize: 12, color: tokens.text.faint }}>
            Empty clears the date.
          </span>
        </span>
      ) : (
        <button
          type="button"
          // Имя составное: голое «Expiry date» на кнопке ЗАМЕНИЛО бы её текст
          // для скринридера, то есть отняло бы у него саму дату, а один текст
          // кнопки («01.09.2026 · in 10 days») не говорит, чей это срок.
          aria-label={`Expiry date: ${label}`}
          aria-describedby={update.isError ? errorId : undefined}
          title="Edit expiry date"
          onClick={open}
          style={{
            border: "none",
            background: "none",
            padding: 0,
            cursor: "pointer",
            fontSize: 13,
            fontFamily: "inherit",
            // Пусто — это приглашение (свой читаемый тон, см. `SET_DATE_TEXT`);
            // всё остальное — показанное состояние срока, и красит его та же
            // лестница, что колонку списка.
            color: state === "unknown" ? SET_DATE_TEXT : expiryTextColor(state),
            fontWeight: expiryTextWeight(state),
            // Пунктирное подчёркивание — единственный знак, что значение
            // правится: кнопка здесь не выглядит кнопкой ни фоном, ни рамкой.
            borderBottom: `1px dashed ${tokens.text.faint}`,
          }}
        >
          {label}
        </button>
      )}
      {update.isError ? (
        // `clip` и перенос по любому месту — текст ЧУЖОЙ (тело ответа бэкенда),
        // тот же приём, что у ошибок записи в полях ряда связей: без обрезки
        // одна такая строка распирает шапку, без `overflowWrap` — уезжает за
        // край.
        <span
          id={errorId}
          role="alert"
          style={{ fontSize: 12, color: ERROR_TEXT, overflowWrap: "anywhere" }}
        >
          Could not save: {clip(errorText(update.error))}
        </span>
      ) : null}
    </>
  );
}
