import React, { useId, useRef } from "react";

/**
 * Отступ содержимого панели от строки вкладок — 24px по макету (панель там
 * `24px 28px 28px`; горизонтальные и нижний в карточке домена даёт `Modal`).
 *
 * Держит его примитив, а не каждая вкладка у себя в корне. Так было сначала —
 * и две вкладки уже компенсировали одно и то же число копией, а третья, забыв,
 * встала бы вплотную к строке вкладок молча, без единой ошибки. Слота под
 * переопределение нарочно нет: пока ни одной вкладке не понадобилось другое
 * значение, а проп без потребителя — приглашение развести их.
 */
const PANEL_PADDING_TOP = 24;

export type TabItem = {
  id: string;
  label: React.ReactNode;
};

/**
 * Подчёркнутые вкладки макета — и первые в продукте, до которых можно добраться
 * с клавиатуры.
 *
 * Копий строки вкладок в продукте уже три (`pages/Activity`, `pages/Settings`,
 * `pages/ServerDetail`), и все три сделаны одинаково: `<div onClick>` без роли и
 * без tabindex. Кликом они работают, а больше никак — до такой «вкладки» не
 * доводит ни Tab, ни стрелка, и скринридер называет её просто группой, не
 * сообщая ни что это переключатель, ни какая из них выбрана. Здесь роли
 * (`tablist`/`tab`/`tabpanel`), `aria-selected` и ходьба стрелками есть с
 * рождения. Те три копии сознательно не трогаем: они принадлежат своим экранам
 * и своему скоупу — но переезжать им, когда дело дойдёт, уже есть куда.
 *
 * Примитив УПРАВЛЯЕМЫЙ (`value` + `onChange`): активная вкладка — это состояние
 * экрана, а не строки кнопок. Модалка домена решает, с какой вкладки
 * открываться, и она же однажды будет поднимать выбор в ссылку `sdmp://`;
 * заведи мы состояние внутри, у выбора стало бы два хозяина, и вечный вопрос
 * «чей ответ правильный» пришлось бы решать синхронизацией.
 *
 * Содержимое панели приходит `children`, а не полем `content` у каждой вкладки,
 * и это не стилистика: отдай мы примитиву все пять поддеревьев сразу, он либо
 * смонтировал бы их разом, либо всё равно рисовал бы только активное — а
 * остальные четыре считались бы вхолостую на КАЖДЫЙ рендер модалки.
 * Вызывающий рисует ровно активную вкладку, примитив отвечает за обвязку.
 *
 * Цену надо назвать точно, иначе первый же читатель проверит её, не найдёт и
 * «починит» примитив на eager-рендер. Запросов у вкладок карточки домена
 * СЕГОДНЯ почти нет: зоны Cloudflare, реестр и аккаунты регистратора читает
 * сама модалка, независимо от вкладки, а `useReadDomainFacts` у Server и Logs —
 * это `useMutationState` (`api/runGate`), подписка на чужой прогон, а не
 * запрос. Смонтировать Server или Logs стоит НУЛЯ походов в сеть. Внутри
 * поддеревьев запрос заводят двое, и лишний из них ровно один: список аккаунтов
 * регистратора (`DomainRegistrarField`) читается той же записью кэша, что и у
 * модалки, — второго похода нет; а `useCloudflareAccounts`
 * (`DomainCloudflareField`) модалка не зовёт вовсе. И он тоже на Overview, то
 * есть на вкладке, открытой по умолчанию.
 *
 * Значит, платится сегодня холостой рендер четырёх поддеревьев, а не сеть; а
 * запросы придут вместе с содержимым вкладок-заглушек, и тогда решение уже
 * будет принято правильно.
 *
 * У этого решения есть цена, и она называется здесь, а не выясняется потом:
 * нарисована ровно активная вкладка, значит переключение РАЗМОНТИРУЕТ прежнее
 * поддерево, и локальное состояние внутри него исчезает молча. Поэтому всё, что
 * обязано пережить переход между вкладками, поднимается в модалку и приезжает
 * вниз пропсами. Ближайший случай — набранный, но не отправленный список
 * nameservers в `DomainNsPanel` (`text`/`edited`/`zoneSource` в `useNsDraft`): по дороге на
 * Server и обратно он пропал бы вместе с правкой, которую человек делал руками.
 *
 * Стрелка активирует вкладку СРАЗУ (automatic activation), и это выбор, а не
 * умолчание. APG советует ручную активацию (стрелка ведёт фокус, Enter/Space
 * выбирает) там, где показ вкладки дорог, — а проход Overview → Logs у нас
 * монтирует Server по пути. Цена посчитана и сегодня равна одному рендеру
 * поддерева: ни запроса, ни мутации монтирование вкладки не стоит (см. выше);
 * ручная же активация стоила бы человеку лишнего
 * нажатия на КАЖДОМ переключении. Станет дорого — здесь и меняем.
 */
export function Tabs({
  items,
  value,
  onChange,
  label,
  children,
  tablistStyle,
}: {
  items: TabItem[];
  value: string;
  onChange: (id: string) => void;
  /**
   * Доступное имя строки вкладок. Необязательно, но осмысленно почти всегда:
   * без него скринридер объявляет безымянный «список вкладок», а на экране, где
   * такая строка не одна, их не различить на слух.
   */
  label?: string;
  children?: React.ReactNode;
  /**
   * Стили СТРОКИ вкладок (отступ сверху под шапкой модалки), не панели: у
   * компонента нет общего корня — он возвращает фрагмент, — поэтому «просто
   * `style`» здесь некуда было бы положить, и имя обязано называть адресата.
   */
  tablistStyle?: React.CSSProperties;
}) {
  /**
   * Префикс идентификаторов из `useId`, а не константа: `aria-controls` и
   * `aria-labelledby` связывают вкладку с панелью по id, и две строки вкладок на
   * одном экране со статическими id связались бы крест-накрест — первая
   * указывала бы на панель второй.
   */
  const uid = useId();
  const tabDomId = (id: string) => `${uid}tab-${id}`;
  const panelDomId = (id: string) => `${uid}panel-${id}`;

  /**
   * Ссылки на кнопки нужны ровно для фокуса при ходьбе стрелками: выбор меняет
   * `onChange`, но если фокус останется на прежней кнопке, следующая стрелка
   * посчитается от неё, и строка «поедет» не туда.
   */
  const btns = useRef<Record<string, HTMLButtonElement | null>>({});

  /**
   * Индексов два, и путать их нельзя.
   *
   * `activeIdx` — правда о выборе: `-1` значит «ни одна вкладка не выбрана», и
   * тогда ни `aria-selected`, ни имя панели ничего не утверждают. Неизвестный
   * `value` — не поломка, а обычный вход: вкладка однажды поедет в ссылку
   * `sdmp://`, а оттуда приезжает что угодно, включая id вкладки, которой в этой
   * сборке уже нет.
   *
   * `focusIdx` — точка входа клавиатуры, и она есть ВСЕГДА. Пока индекс был
   * один, при неизвестном `value` у всех кнопок стояло `tabIndex={-1}`, а
   * ходьба упиралась в проверку «нечего двигать»: до строки нельзя было
   * добраться ни Tab'ом, ни стрелкой, то есть примитив терял ровно то свойство,
   * ради которого заведён, и починить это с клавиатуры было нечем. Первая
   * вкладка становится достижимой, но НЕ выбранной — выбор остаётся за
   * `onChange`.
   */
  const activeIdx = items.findIndex((t) => t.id === value);
  const focusIdx = activeIdx < 0 ? 0 : activeIdx;

  const goTo = (idx: number) => {
    const next = items[idx];
    if (!next) return;
    onChange(next.id);
    btns.current[next.id]?.focus();
  };

  const move = (delta: number) => {
    if (items.length === 0) return;
    // По кругу: строка вкладок короткая и видна целиком, упор в край здесь
    // ничего не подсказывает — только заставляет отсчитывать шаги назад.
    goTo((focusIdx + delta + items.length) % items.length);
  };

  return (
    <>
      <div
        role="tablist"
        aria-label={label}
        // `gap:4px` и `margin-bottom:-1px` у кнопок — из макета: активная
        // вкладка кладёт свою 2px-черту ПОВЕРХ 1px-линии строки, а не под неё.
        style={{ display: "flex", gap: 4, borderBottom: "1px solid #e2e8f0", ...tablistStyle }}
        onKeyDown={(e) => {
          // Только горизонтальные стрелки. Вертикальные принадлежат прокрутке
          // модалки (`Modal` держит `overflowY:auto`), и перехватывать их у
          // горизонтальной строки не за что.
          if (e.key === "ArrowRight") {
            e.preventDefault();
            move(1);
          } else if (e.key === "ArrowLeft") {
            e.preventDefault();
            move(-1);
          } else if (e.key === "Home") {
            // Home/End — из той же рекомендации APG, что и стрелки: край строки
            // достигается одним нажатием, а не отсчётом шагов.
            e.preventDefault();
            goTo(0);
          } else if (e.key === "End") {
            e.preventDefault();
            goTo(items.length - 1);
          }
        }}
      >
        {items.map((t, i) => {
          const active = i === activeIdx;
          return (
            <button
              key={t.id}
              // Модалки продукта содержат формы, и кнопка без `type` в форме —
              // это submit.
              type="button"
              role="tab"
              id={tabDomId(t.id)}
              aria-selected={active}
              aria-controls={panelDomId(t.id)}
              /**
               * Roving tabindex: в таб-порядке ровно одна кнопка — та, с
               * которой клавиатура входит в строку (обычно активная, см.
               * `focusIdx`). Иначе клавиша Tab прогоняет по всем пяти кнопкам
               * подряд, прежде чем добраться до содержимого панели, а по самой
               * строке ходят стрелками — то есть Tab делал бы чужую работу пять
               * раз.
               */
              tabIndex={i === focusIdx ? 0 : -1}
              ref={(el) => {
                btns.current[t.id] = el;
              }}
              onClick={() => onChange(t.id)}
              style={{
                border: "none",
                background: "none",
                cursor: "pointer",
                padding: "10px 14px 12px",
                // Семейство шрифта здесь НЕ назначается, и это осознанно, а не
                // забыто. Причина, по которой оно раньше стояло явно, никуда не
                // делась: у `<button>` шрифт по умолчанию не наследуется, и без
                // объявления кнопка берёт системный шрифт формы, выпадая из
                // строки. Но закрывает это теперь `index.css`, где правило
                // `input,select,textarea,button` называет семейство ровно один
                // раз на всё приложение, — а стоявший тут хардкод `'Inter'`
                // называл шрифт, которого в сборке не было вовсе, то есть с
                // подключением IBM Plex Sans он бы уронил вкладки в системный
                // ровно там, где обещал этого не допустить.
                fontSize: 14,
                fontWeight: active ? 600 : 500,
                color: active ? "#0f172a" : "#64748b",
                borderBottom: `2px solid ${active ? "#0f172a" : "transparent"}`,
                marginBottom: -1,
              }}
              onMouseEnter={(e) => {
                if (!active) e.currentTarget.style.color = "#0f172a";
              }}
              onMouseLeave={(e) => {
                if (!active) e.currentTarget.style.color = "#64748b";
              }}
            >
              {t.label}
            </button>
          );
        })}
      </div>
      {/*
        Панель одна на строку вкладок, и имя ей даёт активная вкладка. Своего
        `tabIndex` у неё нет намеренно: фокусируемой панель делают, когда внутри
        нет ни одного фокусируемого элемента, — а в панелях С СОДЕРЖИМЫМ внутри
        поля, селекты и кнопки, и лишняя остановка Tab только удлиняла бы путь
        до них.

        ОГОВОРКА, потому что премиса верна не для всех панелей. У карточки
        домена две вкладки — заглушки (Template и Custom), и внутри них не
        фокусируется НИЧЕГО: это не недоделка, а смысл заглушки — живых органов
        управления там нет и быть не должно. По APG такой панели полагается как
        раз `tabindex=0`, иначе до её текста нельзя добраться с клавиатуры
        вовсе. Цена не платится потому, что добираться там не до чего:
        содержимое заглушки — одна строка, видимая целиком и без прокрутки, и
        клавиатура ничего от неё не скрывает.

        Считать это за себя примитив не может — о фокусируемости своих детей он
        не знает ничего, — поэтому условие записано словами: появится панель,
        чей нефокусируемый текст придётся ПРОКРУЧИВАТЬ, — возвращаться сюда и
        заводить `tabIndex` для таких панелей явным пропом.
      */}
      <div
        role="tabpanel"
        id={panelDomId(value)}
        // Отступ панели — здесь, а не в каждой вкладке: см. `PANEL_PADDING_TOP`.
        style={{ paddingTop: PANEL_PADDING_TOP }}
        // Ссылка на несуществующий id — не «почти имя», а поломанная связь:
        // скринридер объявил бы панель безымянной, но уже после похода за
        // элементом, которого нет. Нет выбранной вкладки — нет и атрибута.
        aria-labelledby={activeIdx >= 0 ? tabDomId(value) : undefined}
      >
        {children}
      </div>
    </>
  );
}
