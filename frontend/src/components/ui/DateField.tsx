import React, { useId, useState } from "react";

import { tokens } from "../../lib/designTokens";
import {
  ExpiryInputError,
  NO_VALUE,
  formatExpiryDate,
  parseExpiryInput,
} from "../../lib/domainExpiry";

/**
 * Подписи ошибок разбора. Обе называют ОЖИДАЕМОЕ, а не обвиняют в описке — и
 * это не вежливость, а точность.
 *
 * `date` покрывает три разных беды: «31 февраля» (числа нет в календаре),
 * американский порядок («12/25/2026» — это 25-й месяц) и описку в годе
 * («0226»). Подпись вроде «wrong day» на американском порядке отправила бы
 * человека искать ошибку не там — в числе, где её нет. Поэтому обе строки
 * начинаются с формы, которую поле принимает, а `date` добавляет к ней
 * порядок: день первым.
 *
 * Язык интерфейса здесь английский — как у соседей («set date», «Could not
 * save»), при том что комментарии в проекте русские.
 */
const MESSAGE: Record<ExpiryInputError, string> = {
  format: "Expected DD.MM.YYYY — four digits for the year.",
  date: "Expected a real date in DD.MM.YYYY — day first, then month.",
};

/**
 * Что примитив НЕ отдаёт наружу через `...rest`.
 *
 * `value`/`defaultValue`/`onChange` — потому что текстом поля распоряжается оно
 * само (см. `text` ниже), и переданные снаружи они молча отобрали бы у него
 * разбор. `type` — потому что ровно ради ухода от `type="date"` всё и
 * затевалось. `onInvalid` — имя занято: у DOM так называется событие штатной
 * валидации формы, а здесь это половина контракта разбора; поле никаких
 * `required`/`pattern` не ставит, так что нативное событие всё равно не
 * приходит, но тип обязан говорить об этом вслух.
 *
 * Запрет — типом, а не молчаливым перекрытием: место вызова узнаёт о конфликте
 * от компилятора, а не по пропавшему разбору в проде.
 */
type InputPassThrough = Omit<
  React.InputHTMLAttributes<HTMLInputElement>,
  "value" | "defaultValue" | "onChange" | "onInvalid" | "type" | "children"
>;

export type DateFieldProps = InputPassThrough & {
  /**
   * НАЧАЛЬНЫЙ текст поля — ISO-дата (`2026-09-01`), которую поле напечатает
   * по-человечески (`01.09.2026`). Имя по соглашению React (`defaultValue` —
   * неуправляемое поле): это семя, а не диктат.
   *
   * Разница несущая. Диктующий пропс (`value={prop}`) — один из двух кандидатов
   * на причину дефекта, ради которого примитив и написан: React после события,
   * не изменившего состояние, ВОССТАНАВЛИВАЕТ значение управляемого инпута из
   * пропса, и посреди набора поле прыгает обратно. Здесь этого не может
   * случиться по построению — пропс читается один раз, на первом рендере.
   *
   * Отсюда же и способ поле СБРОСИТЬ: перемонтировать (сменить `key` либо
   * закрыть правку, как это делает карточка домена), а не подсунуть другой ISO.
   */
  defaultValue?: string | null;
  /**
   * Строка прочиталась. `null` — поле пусто, то есть «значение снять»: это не
   * ошибка, а единственный способ стереть однажды записанную дату.
   */
  onParsed: (iso: string | null) => void;
  /**
   * Строка не прочиталась. Зовётся на КАЖДОЕ такое изменение, а не однажды:
   * форме карточки сервера больше неоткуда узнать, что Save пора выключить.
   */
  onInvalid: (error: ExpiryInputError) => void;
};

/**
 * Поле даты, набираемой руками: `01.09.2026`.
 *
 * Появилось на месте нативного `<input type="date">`, который в WKWebView
 * десктопа не принимал ввод с клавиатуры вовсе — цифры не вставали в сегменты,
 * календарь не открывался. Поле, которое молча не берёт ввод, хуже
 * отсутствующего, поэтому `type="date"` уходит из проекта совсем: решение
 * выбрано так, чтобы не зависеть от того, какой из двух кандидатов на причину
 * верен (восстановление значения React'ом или сам системный редактор даты).
 *
 * Форму даты знает не браузер, а `lib/domainExpiry` — и печать
 * (`formatExpiryDate`), и разбор (`parseExpiryInput`) берутся оттуда, своих
 * копий здесь нет ни одной. Иначе поле рано или поздно перестанет принимать
 * обратно строку, которую само же и показало, — а виноватым в этом выглядит
 * человек.
 *
 * ЧЕГО ПРИМИТИВ НЕ УМЕЕТ — сохранять. Потребителя два, и сохраняют они
 * по-разному: срок в шапке карточки домена пишется сразу (по ✓/Enter/уходу из
 * поля), а форма карточки сервера ждёт своей кнопки Save. Запись, поселённая
 * здесь, заставила бы второго её обходить. Поэтому контракт наружу — три
 * ответа о СОСТОЯНИИ строки (`onParsed(iso)`, `onParsed(null)`,
 * `onInvalid(kind)`), а что с ними делать, решает место вызова.
 *
 * ГРАНИЦА ОТВЕТСТВЕННОСТИ У КРАСНОЙ СТРОКИ. Здесь рисуется только ошибка
 * РАЗБОРА — местная, мгновенная, про набранный текст. Ошибка ЗАПИСИ приезжает с
 * сервера и рисуется потребителем. Слить их в одну строку значило бы соврать
 * про источник: «Could not save» и «так не пишут дату» просят разного и от
 * разных людей.
 *
 * Разметка — фрагмент, без своего контейнера: у потребителей разная раскладка
 * (мета-ряд `inline-flex` с переносом в шапке карточки домена и колонка формы
 * на карточке сервера), и обёртка, годная одному, распирала бы второго. Отсюда
 * требование к месту вставки, и оно не подразумевается само: контейнер обязан
 * уметь перенос — иначе красная строка встанет в одну линию с полем.
 */
export default function DateField({
  defaultValue,
  onParsed,
  onInvalid,
  style,
  // Достаётся из `rest` намеренно: у поля бывает ДВА описания разом — своя
  // ошибка разбора и чужая ошибка записи, — и `aria-describedby` по спецификации
  // список, а не одно имя. Спред, положенный поверх, затёр бы чужой id молча, и
  // причина отказа сервера перестала бы читаться вслух.
  "aria-describedby": describedBy,
  ...rest
}: DateFieldProps) {
  /**
   * Сырой текст — состояние ПРИМИТИВА. Родитель в него не вмешивается: семя
   * читается инициализатором `useState`, то есть ровно один раз (см.
   * `defaultValue`).
   *
   * Нечитаемое семя даёт ПУСТОЕ поле, а не прочерк: `formatExpiryDate` отвечает
   * на незнание знаком `NO_VALUE` — он для показа, и предлагать человеку
   * править «—» значит предлагать править знак «значения нет».
   */
  const [text, setText] = useState(() => {
    const printed = formatExpiryDate(defaultValue);
    return printed === NO_VALUE ? "" : printed;
  });
  const [error, setError] = useState<ExpiryInputError | null>(null);

  // `useId`, а не константа: на карточке сервера таких полей ДВА рядом (Purchase
  // Date и Expiry Date), и статический id связал бы оба со строкой первого.
  const uid = useId();
  const errorId = `${uid}error`;

  function handleChange(e: React.ChangeEvent<HTMLInputElement>) {
    const next = e.target.value;
    setText(next);

    const result = parseExpiryInput(next);
    if (result.kind === "error") {
      setError(result.error);
      onInvalid(result.error);
      return;
    }
    // Красное обязано УХОДИТЬ вместе с причиной: пережившее починку, оно учит
    // себя не читать.
    setError(null);
    // Пустая строка — это `null`, «снять значение». Тримминг делает разбор
    // (`parseExpiryInput`), поэтому и строка из одних пробелов считается пустой.
    onParsed(result.kind === "parsed" ? result.iso : null);
  }

  return (
    <>
      <input
        type="text"
        // Подсказка мягкой клавиатуре; на десктопе, ради которого поле и
        // написано, она инертна — точки и слэши физическая клавиатура набирает
        // как обычно. Оговорка на будущее: на телефоне цифровая раскладка
        // разделителей не показывает, так что появись у этого поля тачевый
        // потребитель — `inputMode` придётся пересмотреть (`decimal` даёт хотя
        // бы точку). Сегодня такого потребителя нет: веб-панель read-only.
        inputMode="numeric"
        // Плейсхолдер обещает ровно ту форму, которую разбор принимает и печать
        // выдаёт (см. `INPUT_FORMATS` в `lib/domainExpiry`). Цвет ему достаётся
        // браузерный: до `::placeholder` инлайн-стиль не дотягивается, а ради
        // одного тона заводить CSS-файл примитиву не стоит.
        placeholder="DD.MM.YYYY"
        /*
         * `maxLength={10}` здесь НЕТ намеренно, хотя длина правильной даты ровно
         * такая.
         *
         * Он режет ВСТАВКУ: дата, скопированная из письма регистратора, приезжает
         * с пробелами по краям (` 01.09.2026 ` — 12 символов), браузер обрезает
         * её до десяти ПЕРЕД нашим `change`, и в поле оказывается « 01.09.202» —
         * то есть ⌘V молча портит верную дату. Вставка же — ровно то, чего
         * нативное поле не умело вовсе, и ломать её ограничением длины значит
         * менять один дефект на другой.
         *
         * Взамен не теряется ничего: слишком длинную строку разбор отвергает сам
         * и с названной причиной, а поле мешает набору и без вставки — вписать
         * цифру в середину, не стерев сначала лишнюю, при `maxLength` нельзя.
         */
        value={text}
        onChange={handleChange}
        // Своя ошибка — первой: она про то, что в поле СЕЙЧАС, а чужая (запись)
        // рассказывает про прошлую попытку.
        aria-describedby={[error ? errorId : null, describedBy].filter(Boolean).join(" ") || undefined}
        // `autoFocus`, `aria-label`, `onKeyDown`, `onBlur` — всё это приезжает
        // отсюда и достаётся потребителю нетронутым: своих обработчиков на этих
        // событиях у примитива нет, и перехватывать ему нечего. На них держится
        // Фаза 3 — запись срока по Enter и по уходу из поля.
        {...rest}
        style={{
          // Геометрия общего поля формы (`Inp` в `ui/Primitives`) — под карточку
          // сервера, где DateField встанет между двумя такими. Компактный
          // инлайн шапки карточки домена доназначает своё через `style`, как это
          // делают `Inp` и `Btn`.
          width: "100%",
          padding: "8px 12px",
          border: `1px solid ${tokens.border.control}`,
          borderRadius: tokens.radius.sm,
          fontSize: 13,
          // Семейство наследуется, а не назначается: инпут иначе уходит в
          // системный шрифт формы и выпадает из строки, в которой стоит.
          fontFamily: "inherit",
          color: tokens.text.ink,
          background: tokens.surface.subtle,
          boxSizing: "border-box",
          ...style,
        }}
        /*
         * Фокус рисует БРАУЗЕР своим кольцом, и `outline: none` здесь нет.
         *
         * Соседний `Inp` кольцо гасит и заменяет его сменой рамки на
         * `onFocus`/`onBlur`. Повторить это тут нельзя без вреда: собственный
         * `onBlur` затёр бы переданный снаружи — а на нём у карточки домена
         * держится вся запись срока. Складывать два обработчика ради оттенка
         * рамки дороже, чем оставить кольцо, которое к тому же честнее: оно
         * видно и тем, кто разницу двух серых не различает.
         */
      />
      {error ? (
        // Не `role="alert"`, в отличие от соседних строк отказа: те приезжают с
        // сервера редко и асинхронно, а эта меняется на КАЖДОМ символе —
        // объявленная вслух, она перебивала бы сам набор. Связь с полем
        // (`aria-describedby`) остаётся: строка объясняет состояние поля, а не
        // висит рядом с ним.
        <span id={errorId} style={{ fontSize: 12, color: tokens.semantic.danger.text }}>
          {MESSAGE[error]}
        </span>
      ) : null}
    </>
  );
}
