import { describe, it, expect } from "vitest";

import { formatUptime, mbToGb } from "./Primitives";

/**
 * Форматирование показаний железа — одно на весь продукт.
 *
 * Обе функции здесь раньше существовали в двух экземплярах: аптайм дашборд
 * считал по-своему («3 days»), а список и деталь — по-своему («3d 0h»); перевод
 * МБ→ГБ был написан трижды и в двух копиях из трёх округлял до целого. Один и
 * тот же сервер назывался на двух экранах по-разному, и это не косметика:
 * читатель сверяет экраны глазами и должен видеть одно число, а не два.
 *
 * Проверяются границы и «данных нет» — то, на чём такие функции и врут.
 */

describe("formatUptime", () => {
  it("сутки и больше — дни с часами", () => {
    expect(formatUptime(86400)).toBe("1d 0h");
    expect(formatUptime(172800)).toBe("2d 0h");
    expect(formatUptime(3 * 86400 + 5 * 3600)).toBe("3d 5h");
  });

  it("меньше суток — часы с минутами, и до дней не округляется", () => {
    // 86399 секунд — это «23h 59m», а не «1 day»: округление вверх на границе
    // добавляло бы машине сутки работы, которых не было.
    expect(formatUptime(86399)).toBe("23h 59m");
    expect(formatUptime(3600)).toBe("1h 0m");
  });

  it("меньше часа — минуты, меньше минуты — «<1m», а не «0»", () => {
    expect(formatUptime(1800)).toBe("30m");
    // Ноль здесь означает «только что поднялся», и «0h» это скрадывало.
    expect(formatUptime(0)).toBe("<1m");
    expect(formatUptime(59)).toBe("<1m");
  });

  it("аптайма нет — прочерк, а не ноль", () => {
    // «0h» у сервера, которого мы ни разу не опрашивали, — это выдуманное
    // показание: незнание, нарисованное как измерение.
    expect(formatUptime(null)).toBe("—");
    expect(formatUptime(undefined)).toBe("—");
  });
});

describe("mbToGb", () => {
  it("переводит с одним знаком после запятой", () => {
    expect(mbToGb(2048)).toBe(2);
    // 1.5 ГБ — не «2 GB»: округление до целого дорисовывало бы треть памяти.
    expect(mbToGb(1536)).toBe(1.5);
    expect(mbToGb(3891)).toBe(3.8);
  });
});
