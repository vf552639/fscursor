import { MutationKey, useMutationState } from "@tanstack/react-query";

import { queryClient } from "./queryClient";

/**
 * Гейт «один прогон за раз» — заявкой в `MutationCache`, а не флагом в стейте.
 *
 * Ключ, а не поле компонента, потому что прогон живёт ДОЛЬШЕ страницы, а
 * страница размонтируется на любой навигации (`<main key={page}>` в
 * DesktopWorkspace). Пока гейт жил в `useRef`/`useState` экземпляра, уход со
 * страницы посреди прогона и возврат давали НОВЫЙ экземпляр с живой кнопкой —
 * второй клик запускал второй проход поверх первого.
 *
 * Общий модуль, потому что таких прогонов на вкладке Domains уже два —
 * привязка к зонам Cloudflare и полная настройка, — и защита у них устроена
 * одинаково с точностью до ключа. Две копии этого приёма разъехались бы на
 * первой же правке: `networkMode` и синхронность заявки здесь не украшения, а
 * условия, без которых гейт либо не срабатывает, либо не отпускает.
 */

/**
 * Занять ключ и выполнить `run`. Если по ключу уже идёт прогон — не делать
 * ничего: у идущего прогона свой отчёт, и второй такой же ответил бы теми же
 * числами дважды.
 *
 * Гейт спрашивает КЭШ, а не отрендеренный `pending`, и обе причины настоящие:
 * `pending` доезжает только к следующему рендеру (два клика успевают случиться
 * в одном такте), а кэш вдобавок помнит прогон, запущенный ПРОШЛЫМ экземпляром
 * страницы. Заявка встаёт в `pending` синхронно внутри `execute`, до первого
 * `await`, поэтому второй клик в том же такте её уже видит.
 */
export async function runExclusive(key: MutationKey, run: () => Promise<void>): Promise<void> {
  const running = queryClient.getMutationCache().find({ mutationKey: key, status: "pending" });
  if (running) return;
  await queryClient
    .getMutationCache()
    .build(queryClient, {
      mutationKey: key,
      // Работу делает Tauri-команда, а не webview: `navigator.onLine` про эту
      // сеть ничего не знает. С дефолтным `networkMode: "online"` react-query
      // на «оффлайне» браузера не запустил бы `mutationFn` вовсе, а заявка
      // осталась бы висеть — кнопка погасла бы навсегда.
      networkMode: "always" as const,
      mutationFn: () => run(),
    })
    // `execute` отклоняет промис, если `mutationFn` бросил, а вызывающие зовут
    // прогон через `void` — то есть отказ стал бы unhandled rejection. Гейт при
    // этом своё отработал: заявка снята в любом исходе.
    .execute(undefined)
    .catch(() => {});
}

/**
 * Идёт ли прогон по этому ключу — то есть надо ли гасить его кнопки.
 *
 * Кнопок у одного прогона бывает несколько и живут они в разных компонентах
 * (шапка вкладки и тулбар): признак обязан быть один на всех, иначе погасшая
 * половина означала бы, что второй вход в то же действие остался живым.
 */
export function useRunPending(key: MutationKey): boolean {
  return useMutationState({ filters: { mutationKey: key, status: "pending" } }).length > 0;
}
