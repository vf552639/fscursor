import { useQuery } from "@tanstack/react-query";

// RDAP — публичный протокол реестра, ключей и секретов он не требует, но ходит
// он из десктопа: сеть в вебе упёрлась бы в CORS реестров, а веб у нас «только
// смотрит» (см. `lib/runtime`).
import { requireDesktop } from "../lib/runtime";
// Не `invokeSynced`: локальный SQLCipher-кэш этой команде не нужен вовсе — она
// не резолвит из него сущность, а спрашивает у реестра про имя домена. Синк
// перед каждым вызовом был бы платой ни за что.
import { invokeIfTauri } from "../lib/tauri-invoke";

/**
 * Что реестр сказал про делегирование домена.
 *
 * Три состояния, а не «список или ошибка», и разводятся они тегом `state` из
 * Rust (`rdap::RegistryNameservers`). Это не формальность: правило проекта «не
 * рисуй незнание здоровьем» (CLAUDE.md п. 6, `lib/serverStatus.ts`) требует,
 * чтобы «мы не смогли спросить» нельзя было ни показать пустым списком («NS не
 * прописаны»), ни спутать с «домена нет в реестре». Чинятся эти три случая
 * по-разному — прописать NS, разобраться с самим доменом, повторить позже, — и
 * потребитель обязан их различать.
 */
export type RegistryNameservers =
  /**
   * Реестр ответил про этот домен. Список МОЖЕТ быть пуст — это содержательный
   * ответ «зарегистрирован, но никуда не делегирован», а не отсутствие данных.
   */
  | { state: "registered"; nameservers: string[] }
  /** Домена в реестре нет. Утверждение реестра, а не наша неудача. */
  | { state: "not_registered" }
  /** Спросить не удалось — про делегирование не известно ничего. */
  | { state: "unavailable"; reason: string };

export const rdapKeys = {
  /**
   * Ключ на ДОМЕН и только на него: реестру всё равно, к какому аккаунту
   * регистратора домен привязан у нас (у части доменов аккаунта нет вовсе), а
   * запись кэша обязана совпадать с заданным вопросом.
   */
  nameservers: (domain: string) => ["rdap", "nameservers", domain] as const,
};

/**
 * Куда домен делегирован ПО ДАННЫМ РЕЕСТРА.
 *
 * Единственный источник «как есть», который работает у всех провайдеров. У
 * Hostiq чтения NS в API нет вовсе (в `domain/list` нет такого поля), у ручных
 * провайдеров вроде Dynadot нет и самого API — то есть
 * `useRegistrarNameservers` для большинства доменов ответить не может ничем.
 * RDAP отвечает и там, и отвечает именно на вопрос «куда делегирован», а не
 * «отвечает ли зона»: на `betify2.com` реестр вернул серверы Cloudflare при
 * SERVFAIL у рекурсивного резолвера.
 *
 * `staleTime` — пять минут: это поход в чужой публичный сервис, а делегирование
 * домена меняется либо нашей же кнопкой, либо руками в панели регистратора, то
 * есть редко. Дефолтные 10 секунд означали бы запрос в реестр на каждое
 * переоткрытие карточки.
 */
export function useRegistryNameservers(domain: string | null | undefined) {
  return useQuery({
    queryKey: domain ? rdapKeys.nameservers(domain) : ["rdap", "nameservers", "disabled"],
    queryFn: async () => {
      requireDesktop("Reading nameservers from the domain registry");
      return invokeIfTauri<RegistryNameservers>("domain_registry_nameservers", { domain });
    },
    enabled: !!domain,
    staleTime: 5 * 60_000,
  });
}
