import { useQuery } from "@tanstack/react-query";

// RDAP — публичный протокол реестра, ключей и секретов он не требует, но ходит
// он из десктопа: сеть в вебе упёрлась бы в CORS реестров, а веб у нас «только
// смотрит» (см. `lib/runtime`).
import { requireDesktop } from "../lib/runtime";
// Не `invokeSynced`: локальный SQLCipher-кэш этой команде не нужен вовсе — она
// не резолвит из него сущность, а спрашивает у реестра про имя домена. Синк
// перед каждым вызовом был бы платой ни за что.
import { invokeIfTauri } from "../lib/tauri-invoke";

/**
 * Что реестр сказал про делегирование домена.
 *
 * Три состояния, а не «список или ошибка», и разводятся они тегом `state` из
 * Rust (`rdap::RegistryNameservers`). Это не формальность: правило проекта «не
 * рисуй незнание здоровьем» (CLAUDE.md п. 6, `lib/serverStatus.ts`) требует,
 * чтобы «мы не смогли спросить» нельзя было ни показать пустым списком («NS не
 * прописаны»), ни спутать с «домена нет в реестре». Чинятся эти три случая
 * по-разному — прописать NS, разобраться с самим доменом, повторить позже, — и
 * потребитель обязан их различать.
 */
export type RegistryNameservers =
  /**
   * Реестр ответил про этот домен. Список МОЖЕТ быть пуст — это содержательный
   * ответ «зарегистрирован, но никуда не делегирован», а не отсутствие данных.
   */
  | { state: "registered"; nameservers: string[] }
  /** Домена в реестре нет. Утверждение реестра, а не наша неудача. */
  | { state: "not_registered" }
  /** Спросить не удалось — про делегирование не известно ничего. */
  | { state: "unavailable"; reason: string };

/**
 * Развести все три состояния, ничего не забыв.
 *
 * Union заставляет потребителя СУЗИТЬ тип, но не заставляет РАЗВЕСТИ незнание:
 * `if (answer.state === "registered") … else <серый бейдж>` компилируется
 * прекрасно и молча схлопывает «домена нет в реестре» с «спросить не удалось» —
 * то есть осуществляет ровно тот страх, ради которого этот тип и заведён. А
 * дальше `registered` с пустым списком превращается в утверждение «NS не
 * прописаны».
 *
 * Поэтому разбор состояний идёт через этот хелпер: `never`-ветка в `default`
 * ломает СБОРКУ, если в union появится четвёртое состояние, а три обязательных
 * поля — если потребитель решит обойтись двумя. Тем же приёмом в проекте держат
 * перечисление причин у бейджа делегирования (`lib/nsDelegation.ts`,
 * `NsUnknownReason`).
 */
export function foldRegistryNameservers<T>(
  answer: RegistryNameservers,
  on: {
    /** Реестр ответил. Пустой список — «зарегистрирован, но не делегирован». */
    registered: (nameservers: string[]) => T;
    /** Домена в реестре нет — утверждение реестра. */
    notRegistered: () => T;
    /** Спросить не удалось — про делегирование не известно ничего. */
    unavailable: (reason: string) => T;
  },
): T {
  switch (answer.state) {
    case "registered":
      return on.registered(answer.nameservers);
    case "not_registered":
      return on.notRegistered();
    case "unavailable":
      return on.unavailable(answer.reason);
    default: {
      // Недостижимо, пока union и этот switch совпадают, — а разойдутся они
      // ошибкой компиляции здесь, а не серым бейджем у пользователя.
      const unhandled: never = answer;
      throw new Error(`unhandled registry answer: ${JSON.stringify(unhandled)}`);
    }
  }
}

export const rdapKeys = {
  /**
   * Ключ на ДОМЕН и только на него: реестру всё равно, к какому аккаунту
   * регистратора домен привязан у нас (у части доменов аккаунта нет вовсе), а
   * запись кэша обязана совпадать с заданным вопросом.
   */
  nameservers: (domain: string) => ["rdap", "nameservers", domain] as const,
};

/**
 * Куда домен делегирован ПО ДАННЫМ РЕЕСТРА.
 *
 * ЕДИНСТВЕННЫЙ источник «как есть» — и он же единственный, который работает у
 * всех провайдеров. У Hostiq чтения NS в API нет вовсе (в `domain/list` нет
 * такого поля), у ручных провайдеров вроде Dynadot нет и самого API — то есть
 * чтение через API регистратора отвечало у одного провайдера из двух, а у
 * остальных доменов бейдж делегирования был серым по построению; поэтому оно
 * снято целиком, а не оставлено вторым путём. RDAP отвечает везде, и отвечает
 * именно на вопрос «куда делегирован», а не «отвечает ли зона»: на `betify2.com`
 * реестр вернул серверы Cloudflare при SERVFAIL у рекурсивного резолвера.
 *
 * `staleTime` — пять минут: это поход в чужой публичный сервис, а делегирование
 * домена меняется либо нашей же кнопкой, либо руками в панели регистратора, то
 * есть редко. Дефолтные 10 секунд означали бы запрос в реестр на каждое
 * переоткрытие карточки.
 */
export function useRegistryNameservers(domain: string | null | undefined) {
  return useQuery({
    // Ключ строится тем же `rdapKeys`, даже когда домена нет: отдельная строка-
    // заглушка была бы четвёртым пространством ключей, про которое надо помнить
    // при инвалидации. Запрос при `!domain` всё равно не летит (`enabled`).
    queryKey: rdapKeys.nameservers(domain ?? ""),
    queryFn: async () => {
      requireDesktop("Reading nameservers from the domain registry");
      return invokeIfTauri<RegistryNameservers>("domain_registry_nameservers", { domain });
    },
    enabled: !!domain,
    staleTime: 5 * 60_000,
  });
}
