import { useQuery } from "@tanstack/react-query";

import { queryClient } from "./queryClient";
import { rdapKeys } from "./rdap";

/**
 * «NS этому домену только что отправлены» — ОДИН признак на все пути записи.
 *
 * Путей записи NS два, и оба меняют делегирование у регистратора одной и той же
 * командой (`registrar_set_nameservers`): кнопка на карточке домена
 * (`useSetNameservers`) и массовый прогон полной настройки
 * (`domain_full_setup` с `pushNs`, см. `api/fullSetup.ts`). Из этого следуют два
 * последствия, и оба обязаны наступать НА ОБОИХ путях:
 *
 * 1. **Кэш ответа реестра протух.** Мы только что попросили поменять ровно то,
 *    что реестр нам рассказал, и без сброса его ответ лежал бы в кэше ещё пять
 *    минут (`useRegistryNameservers`, `staleTime`) — бейдж делегирования всё это
 *    время показывал бы состояние ДО пуша.
 * 2. **Совет под бейджем врёт.** Реестр узнаёт о смене не сразу (на Hostiq
 *    мерили ~20 секунд, у других TLD это часы), поэтому сверка честно остаётся
 *    `MISMATCH` — но единственное действие, которое подпись умеет предложить
 *    («пропишите NS зоны ниже»), пользователь только что выполнил.
 *
 * Модуль существует затем, чтобы этих правил было ОДНО, а не по одному на путь.
 * Расползание ровно тут уже стоило дефекта: одиночный пуш чинили в фазе 4
 * (коммит `91c2b3c`) двумя правками по месту — сбросом `rdapKeys` в `onSettled`
 * и чтением MutationCache по `SET_NAMESERVERS_KEY` в карточке, — и массовый путь
 * остался с протухшим диагнозом и врущим советом, потому что своей мутации под
 * тем ключом у него нет и никогда не было. Третий путь записи (а он появится:
 * см. долг плана про переиспользование сервиса регистратора) получит оба
 * последствия одним вызовом `noteNsPush`, а не двумя догадками.
 */

/**
 * Сколько длится «только что».
 *
 * Пять минут — не круглое число, а срок годности того самого ответа реестра
 * (`useRegistryNameservers`, `staleTime`), из-за которого признак и заведён; они
 * же были фактическим сроком жизни прежнего признака (запись MutationCache
 * убирается сборщиком через `gcTime`, у мутаций это те же 5 минут). Дальше
 * «только что» перестаёт быть правдой, и совет «пропишите NS» снова уместен:
 * пуш, о котором реестр не узнал за это время, стоит повторить.
 */
export const NS_PUSH_FRESH_MS = 5 * 60_000;

export const nsPushKeys = {
  /**
   * Ключ на ИМЯ домена — то же самое, чем адресуется ответ реестра
   * (`rdapKeys.nameservers`), и по той же причине: аккаунт регистратора к
   * вопросу «куда домен делегирован» отношения не имеет, а у части доменов его
   * нет вовсе. Имя берётся как есть, из строки домена: приведи его здесь к
   * какому-нибудь виду — и признак стал бы адресоваться иначе, чем кэш, который
   * он гасит.
   */
  lastPush: (domain: string) => ["ns-push", domain] as const,
};

/**
 * Пуш NS по этому домену состоялся — записать признак и погасить ответ реестра.
 *
 * Зовётся ЛЮБЫМ путём записи NS, сразу как известен исход.
 *
 * `applied: false` (регистратор отказал) не просто «не записываем признак», а
 * снимает его: отказавший повтор после удавшегося пуша обязан вернуть совет
 * «пропишите NS» — иначе карточка молчала бы о том, что делать. Кэш реестра
 * гасится и на этом исходе: отказ мог примениться частично.
 *
 * Хранилище — кэш того же `QueryClient`, где лежит ответ реестра. Не из
 * экономии: признак обязан переживать размонтирование карточки (ответ
 * регистратора приходит секундами, а массовый прогон идёт минутами при закрытой
 * карточке), сам умирать по `gcTime` и очищаться в тестах тем же
 * `queryClient.clear()`, что и всё остальное. Модульная `Map` дала бы состояние,
 * которое между тестами не сбрасывает никто.
 */
export function noteNsPush(domainName: string, applied: boolean): void {
  queryClient.setQueryData<number | null>(
    nsPushKeys.lastPush(domainName),
    applied ? Date.now() : null,
  );
  queryClient.invalidateQueries({ queryKey: rdapKeys.nameservers(domainName) });
}

/**
 * Был ли по этому домену удавшийся пуш только что.
 *
 * `useQuery` здесь — подписка, а не запрос: `queryFn` не выполняется никогда
 * (`enabled: false`), данные в кэш кладёт `noteNsPush`. Нужна она затем, чтобы
 * карточка перерисовалась на пуше, случившемся не в ней самой (массовый прогон
 * идёт из страницы, а его исход приезжает по одному домену за раз).
 *
 * Отдельного таймера на истечение свежести нет намеренно: минута, на которой
 * совет сменится обратно, того не стоит, а перерисовка случается на любом
 * следующем ответе реестра или обновлении строки домена.
 */
export function useNsJustPushed(domainName: string): boolean {
  const { data } = useQuery({
    queryKey: nsPushKeys.lastPush(domainName),
    queryFn: (): number | null => null,
    enabled: false,
    gcTime: NS_PUSH_FRESH_MS,
  });
  return data != null && Date.now() - data < NS_PUSH_FRESH_MS;
}
