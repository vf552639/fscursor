import { fireEvent, screen } from "@testing-library/react";

/**
 * Открыть вкладку по её видимому имени.
 *
 * Общий хелпер, а не по копии в каждом файле, ровно по той причине, по которой
 * заведён `secretBlobKit`: экранов с вкладками в продукте станет много, и в
 * какой-нибудь из копий однажды кликнут по `getByText(name)` — который на
 * экране с вкладкой «Server» и словом «Server» в ряду связей найдёт не ту
 * ноду и молча ничего не переключит.
 *
 * Спрашиваем `role="tab"` — то есть ровно то, что примитив `ui/Tabs` и
 * обещает: клик по чему-то без этой роли переключателем вкладок не является, и
 * тест, прошедший по такому клику, охранял бы не поведение, а вёрстку.
 */
export function openTab(name: string | RegExp) {
  fireEvent.click(screen.getByRole("tab", { name }));
}
